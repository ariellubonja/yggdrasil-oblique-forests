#!/usr/bin/env python3
"""fig:dyn-vs-size -- speedup vs. dataset size (rows x features), one panel per arm.

Speedup = train_s(SPO-RF Exact, Highway) / train_s(arm), full depth, 240 trees, 48
threads, m7i.metal-24xl. Sources (all committed under benchmarks/results/):
  spo_vs_gbt/large_results.csv   HIGGS / SUSY / Epsilon, 15 arms (mean over reps)
  spo_vs_gbt/speedup_map.csv     Trunk 1M x {32..8192}, dyn_vec vs exact_hwy only
  ablation_vectorized_dynamic/   Trunk 1.5Mx4096, 150kx40k, 15kx400k, all arms
Emits a pgfplots groupplot (.tex, \\input it) plus the point CSV. Overleaf's MCP can
only carry text, hence pgfplots rather than a PDF.
"""
from __future__ import annotations

import argparse
import io
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
RES = ROOT / "benchmarks" / "results"
SPO = RES / "runtime" / "speedup_map_by_dataset"
PAPER = ROOT / "paper" / "spaa27"

PANELS = [  # (arm, panel title)
    ("spo_rf_dyn_scalar", "Dynamic"),
    ("spo_rf_rand_vec", "Vectorized"),
    ("spo_rf_dyn_vec", "Dynamic + Vectorized"),
]
BASE = "spo_rf_exact_hwy"
ABL_FILES = {  # ablation_vectorized_dynamic/<file> -> arm
    "dfs_exact_hwy.csv": BASE,
    "dfs_scalar_dynamic.csv": "spo_rf_dyn_scalar",
    "dfs_vectorized_random.csv": "spo_rf_rand_vec",
    "dfs_vectorized_dynamic.csv": "spo_rf_dyn_vec",
}
LABEL_LEFT = {"EPSILON", "SUSY"}  # datasets whose value label sits left of the mark
ABL_SHAPES = {  # ablation dataset name -> (rows, features); HIGGS dropped (dup of large)
    "trunk_1500000_x_4096": (1_500_000, 4096),
    "trunk_150000_x_40000": (150_000, 40_000),
    "trunk_15000_x_400000": (15_000, 400_000),
}


def _read_provenance_csv(path: Path) -> pd.DataFrame:
    """Ablation CSVs carry a '==== PROVENANCE ====' header block before the table."""
    text = path.read_text()
    body = text.split("====================\n", 1)[-1]
    return pd.read_csv(io.StringIO(body))


def load_points() -> pd.DataFrame:
    rows = []
    large = pd.read_csv(SPO / "large_results.csv")
    large = large[(large.status == "OK") & (large.max_depth == -1)]
    for (ds, arm), g in large.groupby(["dataset", "method"]):
        rows.append(dict(dataset=ds, rows=g.rows.iloc[0], features=g.features.iloc[0],
                         arm=arm, train_s=g.train_s.mean(), synthetic=False, src="large_results"))
    spm = pd.read_csv(SPO / "speedup_map.csv")
    spm = spm[(spm.status == "OK") & (spm.family == "rf") & (spm.max_depth == -1)
              & (spm.min_examples == 1) & spm.dataset.str.startswith("trunk_")]
    for (ds, arm), g in spm.groupby(["dataset", "arm"]):
        rows.append(dict(dataset=ds, rows=g.rows.iloc[0], features=g.features.iloc[0],
                         arm=arm, train_s=g.train_s.mean(), synthetic=True, src="speedup_map"))
    for fname, arm in ABL_FILES.items():
        abl = _read_provenance_csv(RES / "runtime" / "ablation_vectorized_dynamic" / fname)
        for _, r in abl.iterrows():
            if r.dataset not in ABL_SHAPES:
                continue
            nr, nf = ABL_SHAPES[r.dataset]
            rows.append(dict(dataset=r.dataset, rows=nr, features=nf, arm=arm,
                             train_s=r.median_s, synthetic=True, src="ablation"))
    df = pd.DataFrame(rows)
    # A shape may now appear in more than one source (the B6 speedup_map sweep
    # covers three shapes the ablation CSVs already had). Keep one source per
    # dataset -- a speedup is a ratio, so numerator and denominator must come
    # from the same campaign -- preferring the source with the most arms.
    src_rank = {"large_results": 0, "ablation": 1, "speedup_map": 2}
    arms_per = df.groupby(["dataset", "src"])["arm"].nunique()
    keep = {ds: min(g.index.get_level_values("src"),
                     key=lambda sc: (-g.loc[(ds, sc)], src_rank.get(sc, 9)))
            for ds, g in arms_per.groupby(level="dataset")}
    df = df[[keep[r.dataset] == r.src for r in df.itertuples()]].copy()

    base = df[df.arm == BASE].set_index("dataset").train_s
    df = df[df.arm != BASE].copy()
    df["speedup"] = base.reindex(df.dataset).values / df.train_s.values
    df = df[df.arm.isin([a for a, _ in PANELS])].dropna(subset=["speedup"])
    return df.sort_values(["arm", "rows", "features"]).reset_index(drop=True)


def _pgf_table(g: pd.DataFrame) -> str:
    lines = ["x y meta anc"]
    for _, r in g.iterrows():
        anc = "east" if r.dataset in LABEL_LEFT else "west"
        lines.append(f"{int(r.rows)} {int(r.features)} {r.speedup:.3f} {anc}")
    return "\n".join(lines)


def emit_tex(df: pd.DataFrame) -> str:
    out = [
        "% Generated by benchmarks/src/spo_vs_gbt/make_dyn_vs_size_figure.py -- do not hand-edit.",
        "% Needs \\usepackage{pgfplots}\\pgfplotsset{compat=1.18}\\usepgfplotslibrary{groupplots}.",
        "\\begin{tikzpicture}",
        "\\def\\eastname{east}",
        "\\pgfplotsset{",
        "  colormap={spdup}{rgb255(0cm)=(211,59,59); rgb255(1cm)=(225,224,220); rgb255(2cm)=(42,120,214)},",
        "  % marks and value labels are separate plots: 'nodes near coords' and 'use mapped color'",
        "  % both own scatter/@pre marker code and clobber each other when combined.",
        "  dynsize/.style={scatter, only marks, scatter src=explicit,",
        "    visualization depends on={\\thisrow{meta} \\as \\spd},",
        "    scatter/@pre marker code/.append style={/tikz/mark size=1.6pt+5.5pt*(\\spd-0.65)},",
        "    scatter/use mapped color={draw=black!55, fill=mapped color, line width=0.4pt}},",
        "  dynlabel/.style={only marks, mark=none, point meta=explicit, forget plot,",
        "    visualization depends on={value \\thisrow{anc} \\as \\anc},",
        "    nodes near coords={\\pgfmathprintnumber[fixed,precision=2]{\\pgfplotspointmeta}$\\times$},",
        "    nodes near coords style={font=\\tiny, anchor=\\anc, yshift=1.5pt, inner sep=0pt,",
        "      /utils/exec={\\ifx\\anc\\eastname\\tikzset{xshift=-2.5pt}\\else\\tikzset{xshift=2.5pt}\\fi}}},",
        "}",
        "\\begin{groupplot}[",
        "  group style={group size=3 by 1, horizontal sep=0.55cm, ylabels at=edge left, yticklabels at=edge left},",
        "  width=0.35\\linewidth, height=0.25\\linewidth, xmode=log, ymode=log,",
        "  point meta min=0.65, point meta max=1.35,",
        "  xmin=6000, xmax=4e7, ymin=7, ymax=2.2e6,",
        "  xtick={1e4,1e5,1e6,1e7}, ytick={1e1,1e2,1e3,1e4,1e5,1e6},",
        "  xlabel={Rows}, ylabel={Features}, label style={font=\\small}, tick label style={font=\\scriptsize},",
        "  title style={font=\\small, yshift=-3pt}, grid=major, grid style={black!12},",
        "  axis line style={black!45}, tick style={black!45}, enlargelimits=false, clip=false,",
        "]",
    ]
    for i, (arm, title) in enumerate(PANELS):
        g = df[df.arm == arm]
        opts = [f"title={{\\strut {title}}}"]
        if i == len(PANELS) - 1:
            opts += ["colorbar", "colorbar style={width=0.18cm, ytick={0.8,1.0,1.2}, "
                     "yticklabel={\\pgfmathprintnumber{\\tick}$\\times$}, tick label style={font=\\scriptsize}, "
                     "ylabel={Speedup vs.\\ Exact (Highway)}, ylabel style={font=\\scriptsize}}"]
        out.append(f"\\nextgroupplot[{', '.join(opts)}]")
        for synthetic, mark in ((False, "*"), (True, "square*")):
            gg = g[g.synthetic == synthetic]
            if gg.empty:
                continue
            tbl = _pgf_table(gg)
            out += [f"\\addplot[dynsize, mark={mark}] table[x=x, y=y, meta=meta] {{", tbl, "};",
                    "\\addplot[dynlabel] table[x=x, y=y, meta=meta] {", tbl, "};"]
    out += ["\\end{groupplot}", "\\end{tikzpicture}", ""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(PAPER / "figures" / "results" / "dyn_vs_size.tex"))
    ap.add_argument("--csv", default=str(SPO / "analysis" / "dyn_vs_size_points.csv"))
    a = ap.parse_args()
    df = load_points()
    Path(a.csv).parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(a.csv, index=False)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(emit_tex(df))
    print(df[["dataset", "rows", "features", "arm", "train_s", "speedup", "src"]].to_string())
    print(f"wrote {a.out} and {a.csv}")


if __name__ == "__main__":
    main()
