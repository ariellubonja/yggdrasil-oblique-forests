#!/usr/bin/env python3
"""KDD27 appendix table body: mean test accuracy / ROC AUC / log-loss per arm of the CC18 AA-vs-SPO GBT study.

  python3 make_cc18_aa_spo_table.py <results.csv> <out_body.tex>
Mean over datasets of the per-dataset 10-fold mean; only (dataset, fold) cells finished in every arm. Best per column bold.
"""
import sys

import pandas as pd

ARMS = [("aa_ydf", "AA (YDF defaults)"), ("spo_harness", "SPO (harness defaults)"),
        ("spo_ydf", "SPO (YDF defaults)"), ("aa_spo_ydf", "AA+SPO (YDF defaults)")]
METRICS = [("test_acc", "Accuracy", max), ("test_auc", "ROC AUC", max), ("test_logloss", "Log-loss", min)]


def main():
    src, out = sys.argv[1], sys.argv[2]
    df = pd.read_csv(src)
    df = df[(df.rc == 0) & df.arm.isin([a for a, _ in ARMS])]
    n = df.groupby(["dataset", "fold"]).arm.nunique()
    df = df.set_index(["dataset", "fold"]).loc[n[n == len(ARMS)].index].reset_index()
    means = {m: df.pivot_table(index="dataset", columns="arm", values=m).mean() for m, _, _ in METRICS}
    best = {m: pick(means[m]) for m, _, pick in METRICS}
    rows = []
    for a, label in ARMS:
        cells = []
        for m, _, _ in METRICS:
            v = f"{means[m][a]:.4f}"
            cells.append(f"\\textbf{{{v}}}" if f"{means[m][a]:.4f}" == f"{best[m]:.4f}" else v)
        rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
    body = ["% auto-generated by benchmarks/src/cc18_aa_spo_gbt/make_cc18_aa_spo_table.py -- regenerate, do not hand-edit",
            "", "\\begin{tabular}{lrrr}", "\\toprule",
            "Arm & " + " & ".join(h for _, h, _ in METRICS) + " \\\\", "\\midrule", *rows,
            "\\bottomrule", "\\end{tabular}", ""]
    open(out, "w").write("\n".join(body))
    print("\n".join(body))


if __name__ == "__main__":
    main()
