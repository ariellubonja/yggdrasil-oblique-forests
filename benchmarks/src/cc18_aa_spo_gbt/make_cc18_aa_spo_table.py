#!/usr/bin/env python3
"""KDD28 appendix table body: mean test accuracy / ROC AUC / log-loss per arm of the CC18 AA-vs-SPO GBT study.

  python3 make_cc18_aa_spo_table.py <results.csv> <out_body.tex> [--time] [--profile NAME]   (--out = <out_body.tex>)
--arm_map cc18_aa=aa_ydf,... --recorded <csv>: rows named in the map come from <results.csv> (--profile), the
other rows from the recorded CSV (--recorded_profile); Train ratios divide by the (a) AA of the same CSV.
--time adds train_s (mean over datasets of the fold mean, seconds per model; same run as the metrics) and its ratio to AA.
Mean over datasets of the per-dataset 10-fold mean; only (dataset, fold) cells finished in every arm. Best per column bold.
"""
import argparse
import pathlib
import sys

import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "distributed_spo_gbt" / "params"))
import params as kdd28  # noqa: E402  (kdd28_params.json)

# Row labels (a)-(e) are referenced from the hand-owned setup footnote.
ARMS = [("aa_ydf", "(a) AA (YDF defaults)"), ("spo_harness", "(b) SPO (harness, 30 trees, Dyn Hist)"),
        ("spo_harness_exact300", "(c) SPO (harness, 300 trees, exact)"),
        ("spo_ydf", "(d) SPO (YDF defaults)"), ("aa_spo_ydf", "(e) AA+SPO (YDF defaults)")]
METRICS = [("test_acc", "Accuracy", max), ("test_auc", "ROC AUC", max), ("test_logloss", "Log-loss", min)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("out_pos", nargs="?", metavar="out_body.tex")
    ap.add_argument("--out", default=None, help="output body path (same as the 2nd positional)")
    ap.add_argument("--time", action="store_true")
    ap.add_argument("--auc_first", action="store_true", help="ROC AUC column before Accuracy")
    ap.add_argument("--arm_map", default="", help="src_arm=row_arm,... (kdd28_ydf: cc18_aa=aa_ydf,cc18_spo=spo_ydf,...)")
    ap.add_argument("--recorded", default="", help="CSV with the rows --arm_map does not fill")
    ap.add_argument("--recorded_profile", default=kdd28.generator_profile(__file__))
    kdd28.add_profile_arg(ap, __file__)
    opt = ap.parse_intermixed_args()
    src, out, with_time = opt.src, opt.out or opt.out_pos, opt.time
    if opt.auc_first:
        METRICS[0], METRICS[1] = METRICS[1], METRICS[0]
    amap = dict(kv.split("=") for kv in opt.arm_map.split(",")) if opt.arm_map else {a: a for a, _ in ARMS}
    rest = [a for a, _ in ARMS if a not in amap.values()]
    if rest and not opt.recorded:
        sys.exit(f"rows {rest} need --recorded")
    df = pd.read_csv(src)
    df = df[(df.rc == 0) & df.arm.isin(amap)]
    kdd28.check_frame(df, opt.profile, list(amap), pathlib.Path(src).name, arm_of=lambda r: r["arm"])
    df = df.assign(arm=df.arm.map(amap))
    setups = [kdd28.setup_line(opt.profile, list(amap))]
    if rest:  # recorded rows + their own (a) as the Train-ratio base
        rec = pd.read_csv(opt.recorded)
        rec = rec[(rec.rc == 0) & rec.arm.isin(rest + ["aa_ydf"])]
        kdd28.check_frame(rec, opt.recorded_profile, rest + ["aa_ydf"], pathlib.Path(opt.recorded).name + " (recorded)",
                          arm_of=lambda r: r["arm"])
        rec_aa = rec[rec.arm == "aa_ydf"].assign(arm="aa_ydf@rec")
        df = pd.concat([df, rec[rec.arm != "aa_ydf"], rec_aa], ignore_index=True)
        setups.append(kdd28.setup_line(opt.recorded_profile, rest).replace("% setup:", "% setup (recorded rows):"))
    n = df[df.arm != "aa_ydf@rec"].groupby(["dataset", "fold"]).arm.nunique()
    df = df.set_index(["dataset", "fold"]).loc[n[n == len(ARMS)].index].reset_index()
    means = {m: df.pivot_table(index="dataset", columns="arm", values=m).mean()[[a for a, _ in ARMS]] for m, _, _ in METRICS}
    secs = df.pivot_table(index="dataset", columns="arm", values="train_s").mean()
    best = {m: pick(means[m]) for m, _, pick in METRICS}
    rows = []
    for a, label in ARMS:
        cells = []
        for m, _, _ in METRICS:
            v = f"{means[m][a]:.4f}"
            cells.append(f"\\textbf{{{v}}}" if f"{means[m][a]:.4f}" == f"{best[m]:.4f}" else v)
        if with_time:
            aa = "aa_ydf@rec" if a in rest else "aa_ydf"
            cells.append(f"{secs[a]:.2f} ({secs[a] / secs[aa]:.1f}$\\times$)")
        rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
    body = ["% auto-generated by benchmarks/src/cc18_aa_spo_gbt/make_cc18_aa_spo_table.py -- regenerate, do not hand-edit",
            "", "\\begin{tabular}{l" + "r" * (len(METRICS) + with_time) + "}", "\\toprule",
            "Arm & " + " & ".join([h for _, h, _ in METRICS] + (["Train (s)"] if with_time else [])) + " \\\\", "\\midrule", *rows,
            "\\bottomrule", "\\end{tabular}", ""]
    text = kdd28.add_setup("\n".join(body), "\n".join(setups))
    open(out, "w").write(text)
    print(text)


if __name__ == "__main__":
    main()
