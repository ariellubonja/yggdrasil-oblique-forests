"""KDD27 column-replication figure data: mean delta + bootstrap CI (top), per-dataset delta boxes (bottom).
A "single" slot right of r=1 shows single-machine SPO-GBT (single_machine_spo_gbt.csv) vs distributed r=0.

Writes .dat files and a pgfplots body; the figure environment and caption live in main.tex.
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
CSV = ROOT / "benchmarks/results/accuracy/distributed_spo_gbt/column_replication_vertex/results.csv"
OUT = ROOT / "paper/distributed_spo_gbt_kdd27/figures/evaluation/column_replication"
SINGLE = CSV.parent / "single_machine_spo_gbt.csv"
CLIP = 5.0
XS = 1.2  # x position of the single-machine slot
BODY = r"""%% auto-generated by benchmarks/src/distributed_spo_gbt/make_column_replication_fig.py -- regenerate, do not hand-edit
\begin{tikzpicture}
\begin{groupplot}[group style={group size=1 by 2, vertical sep=0.35cm, xticklabels at=edge bottom, xlabels at=edge bottom},
  width=\linewidth, xmin=-0.05, xmax=1.27, xtick={0,0.1,...,1.0}, extra x ticks={%(xs)g}, extra x tick labels={single},
  extra x tick style={grid=none},
  xticklabel style={/pgf/number format/fixed, /pgf/number format/precision=1, /pgf/number format/fixed zerofill},
  xlabel={column replication $r$}, tick label style={font=\footnotesize}, label style={font=\footnotesize},
  tick style={draw=none}, ymajorgrids, grid style={gray!25}, axis line style={gray!70}, every axis plot/.append style={line join=round}]
\nextgroupplot[height=3.6cm, ylabel={$\Delta$ mean acc.\ (pts)}, extra x tick labels={}]
\addplot[draw=none, fill={rgb,255:red,55;green,138;blue,221}, fill opacity=0.18, forget plot] table {figures/evaluation/column_replication/band.dat};
\addplot[gray!80, forget plot] coordinates {(-0.05,0) (1.27,0)};
\draw[gray!60, densely dotted] ({axis cs:1.1,0}|-{rel axis cs:0,0}) -- ({axis cs:1.1,0}|-{rel axis cs:0,1});
\addplot[color={rgb,255:red,0;green,131;blue,0}, dashed] coordinates {(-0.05,%(sm).4f) (1.27,%(sm).4f)};
\addplot[color={rgb,255:red,0;green,131;blue,0}, mark=square*, mark size=1.5pt, only marks, error bars/.cd, y dir=both, y explicit]
  table[x=x, y=mean, y error plus=ep, y error minus=em] {figures/evaluation/column_replication/single.dat};
\addplot[color={rgb,255:red,55;green,138;blue,221}, mark=*, mark size=1.5pt, thick] table[x=r, y=mean] {figures/evaluation/column_replication/mean.dat};
\nextgroupplot[height=4.2cm, ymin=-%(clip)g, ymax=%(clip)g, ytick={-4,-2,...,4}, ylabel={per-dataset $\Delta$ (pts)}]
\addplot[gray!80, forget plot] coordinates {(-0.05,0) (1.27,0)};
\draw[gray!60, densely dotted] ({axis cs:1.1,0}|-{rel axis cs:0,0}) -- ({axis cs:1.1,0}|-{rel axis cs:0,1});
\addplot[only marks, mark=*, mark size=0.6pt, color={rgb,255:red,0;green,131;blue,0}, opacity=0.45] table[x=x, y=d] {figures/evaluation/column_replication/single_dots.dat};
\addplot[color={rgb,255:red,0;green,131;blue,0}, empty line=jump] table {figures/evaluation/column_replication/single_boxes.dat};
\addplot[only marks, mark=*, mark size=0.6pt, color={rgb,255:red,55;green,138;blue,221}, opacity=0.45] table[x=x, y=d] {figures/evaluation/column_replication/dots.dat};
\addplot[gray!90, empty line=jump] table {figures/evaluation/column_replication/boxes.dat};
\addplot[black, thick, empty line=jump] table {figures/evaluation/column_replication/medians.dat};
\addplot[color={rgb,255:red,216;green,90;blue,48}, mark=diamond*, mark size=1.6pt, restrict x to domain=0.05:1.05] table[x=r, y=mean] {figures/evaluation/column_replication/mean.dat};
\addplot[color={rgb,255:red,216;green,90;blue,48}, mark=diamond*, mark size=1.6pt, only marks] table[x=x, y=mean] {figures/evaluation/column_replication/single.dat};
\end{groupplot}
\end{tikzpicture}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=str(CSV))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    d = pd.read_csv(a.csv)
    d = d[d.rc == 0]
    m = d.groupby(["dataset", "replication"]).test_acc.mean().unstack()
    R = m.columns.values
    delta = m.sub(m[0.0], axis=0) * 100
    rng = np.random.default_rng(0)
    idx = rng.integers(0, len(delta), (10000, len(delta)))
    boot = np.stack([delta[c].values[idx].mean(1) for c in R], 1)
    lo, hi = np.percentile(boot, [2.5, 97.5], 0)
    pd.DataFrame({"r": R, "mean": delta.mean().values, "lo": lo, "hi": hi}).to_csv(
        out / "mean.dat", sep=" ", index=False, float_format="%.4f")
    band = np.r_[np.c_[R, lo], np.c_[R[::-1], hi[::-1]]]
    np.savetxt(out / "band.dat", band, fmt="%.4f", header="x y", comments="")
    sg = pd.read_csv(SINGLE)
    sg = sg[sg.rc == 0].groupby("dataset").test_acc.mean().reindex(m.index)
    assert sg.notna().all(), "single-machine run misses datasets"
    ds = (sg - m[0.0]) * 100
    slo, shi = np.percentile(ds.values[idx].mean(1), [2.5, 97.5])
    pd.DataFrame({"x": [XS], "mean": [ds.mean()], "ep": [shi - ds.mean()], "em": [ds.mean() - slo]}).to_csv(
        out / "single.dat", sep=" ", index=False, float_format="%.4f")
    box, med, dots, n_out = [], [], [], 0
    hw = 0.03
    sbox, sdots = [], []
    for c, v, bx, dt in [(c, delta[c].values, box, dots) for c in R[1:]] + [(XS, ds.values, sbox, sdots)]:
        q1, q2, q3 = np.percentile(v, [25, 50, 75])
        lw = v[v >= q1 - 1.5 * (q3 - q1)].min()
        uw = v[v <= q3 + 1.5 * (q3 - q1)].max()
        bx += [(c - hw, q1), (c + hw, q1), (c + hw, q3), (c - hw, q3), (c - hw, q1), None,
                (c, q3), (c, uw), None, (c, q1), (c, lw), None,
                (c - hw / 2, uw), (c + hw / 2, uw), None, (c - hw / 2, lw), (c + hw / 2, lw), None]
        med += [(c - hw, q2), (c + hw, q2), None]
        keep = np.abs(v) <= CLIP
        n_out += int((~keep).sum())
        dt += [(c + j, y) for j, y in zip(rng.uniform(-0.022, 0.022, keep.sum()), v[keep])]
    for name, pts in (("boxes", box), ("medians", med), ("single_boxes", sbox)):
        with open(out / f"{name}.dat", "w") as f:
            f.write("x y\n" + "".join("\n" if p is None else f"{p[0]:.4f} {p[1]:.4f}\n" for p in pts))
    for name, pts in (("dots", dots), ("single_dots", sdots)):
        with open(out / f"{name}.dat", "w") as f:
            f.write("x d\n" + "".join(f"{x:.4f} {y:.4f}\n" for x, y in pts))
    (out.parent / "fig_column_replication_body.tex").write_text(BODY % {"clip": CLIP, "xs": XS, "sm": ds.mean()})
    print(f"{len(delta)} datasets; single-machine {ds.mean():+.2f} pts vs r=0; "
          f"{n_out} of {len(delta) * len(R)} per-dataset deltas (incl. single) outside +-{CLIP:g} pts")


if __name__ == "__main__":
    main()
