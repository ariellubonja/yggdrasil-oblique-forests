#!/usr/bin/env python3
"""Vertex P=F grid -> pgfplots BODY: grouped log-scale bars of tree-training seconds per dataset, one panel per machine type.
Same cells and selection as make_pf_grid_table.py (imports its grid()); bars = arm x W, hue = arm, lightness = W.
Writes <out_dir>/fig_vertex_<tag>_pf_body.tex + <tag>.dat per panel; figure environment/caption live in main.tex.
Usage: make_pf_grid_fig.py [--out_dir DIR]  (defaults reproduce the paper's hm4 + hm16 panels)"""
import argparse, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_pf_grid_table import DATASETS, grid  # noqa: E402
from make_pf_grid_table import ARMS as _ARMS  # noqa: E402

ARMS = _ARMS[::-1]  # SPO first, as in the paper's MULTI_THREAD bar figure

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "../../../paper/distributed_spo_gbt_kdd27/figures/evaluation/vertex_pf")
TEX_DIR = "figures/evaluation/vertex_pf"  # path as seen from main.tex
PANELS = [  # (tag, title, run_prefix, machine, W list, oom log glob, legend?)
    ("hm4", "n2-highmem-4", "pfhm4_20261025", "n2-highmem-4", "1,2,4,8,16",
     os.path.join(HERE, "../../results/runtime/distributed_spo_gbt/barriers/vertex/p_F/pfhm4_20261025_youtube8m/launcher.log")),
    ("hm16", "n2-highmem-16", "pfgrid20261025", "n2-highmem-16", "1,2,4", None),
]
# Light-mode W ramps (validated: adjacent SPO/AA pairs ΔE >= 13.5 CVD, >= 16.6 normal).
COLORS = {"spo": ["0b3d6e", "1f5fa6", "3f86d2", "6fa8e0", "9cc3ea"], "aa": ["8a2f10", "bd3f14", "e3692e", "f08c5a", "f5ad87"]}
YMIN, YMAX = 10, 12000


def panel(tag, title, g, out_dir, width, legend):
    W = g["W"]; cols = [f"{arm}_w{w}" for w in W for arm, _ in ARMS]
    dat = ["dataset " + " ".join(cols)]
    oom = []  # (dataset index, bar index) slots to label
    for di, (ds, dsname) in enumerate(DATASETS):
        vals = []
        for wi, w in enumerate(W):
            for ai, (arm, _) in enumerate(ARMS):
                r = g["rows"].get((ds, arm)); v = r[wi] if r else "--"
                if v == "OOM":
                    oom.append((dsname, wi * len(ARMS) + ai))
                vals.append(v if v not in ("OOM", "--") else "nan")
        dat.append(dsname.replace(" ", "") + " " + " ".join(vals))
    open(os.path.join(out_dir, f"{tag}.dat"), "w").write("\n".join(dat) + "\n")
    bw, gap = (4.4, 0.6) if len(cols) > 6 else (6.2, 0.8)  # pt
    xs = ",".join(d.replace(" ", "") for _, d in DATASETS); xl = ",".join(d for _, d in DATASETS)
    opts = [f"width={width}", "height=5cm", f"ybar={gap}pt", f"bar width={bw}pt", "ymode=log", "log origin=infty",
            f"ymin={YMIN}", f"ymax={YMAX}", f"symbolic x coords={{{xs}}}", f"xtick={{{xs}}}", f"xticklabels={{{xl}}}",
            "enlarge x limits=0.14", f"title={{\\texttt{{{title}}}}}", "title style={font=\\footnotesize, yshift=-0.5ex}",
            "ymajorgrids", "grid style={black!12}", "axis line style={black!30}", "tick style={draw=none}",
            "tick label style={font=\\footnotesize}", "label style={font=\\footnotesize}", "unbounded coords=jump",
            "ytick={10,100,1000,10000}", "log ticks with fixed point", "clip=false"]
    if tag == PANELS[0][0]:
        opts.append("ylabel={Tree-training time (s)}")
    else:
        opts.append("yticklabels={}")
    if legend:
        opts += ["legend style={font=\\scriptsize, at={(0.5,-0.17)}, anchor=north, draw=none, legend columns=5, "
                 "/tikz/every even column/.append style={column sep=0.5em}}", "legend cell align=left"]
    lines = [f"% auto-generated by benchmarks/src/distributed_spo_gbt/make_pf_grid_fig.py -- regenerate, do not hand-edit",
             f"% cells: {g['src']}", "\\begin{tikzpicture}[baseline=(current bounding box.north)]", "\\begin{axis}[" + ", ".join(opts) + "]"]
    for wi, w in enumerate(W):
        for arm, armname in ARMS:
            lines.append(f"\\addplot[draw=none, fill={{rgb,255:red,{int(COLORS[arm][wi][:2],16)};green,{int(COLORS[arm][wi][2:4],16)};"
                         f"blue,{int(COLORS[arm][wi][4:],16)}}}] table[x=dataset, y={arm}_w{w}] {{{TEX_DIR}/{tag}.dat}};")
            if legend:
                lines.append(f"\\addlegendentry{{{armname.split()[0]} $W{{=}}{w}$}}")
    n = len(cols)
    for dsname, bi in oom:  # label empty slots; shift = bar index relative to the group centre
        shift = (bi - (n - 1) / 2) * (bw + gap)
        lines.append(f"\\node[rotate=90, anchor=west, font=\\tiny, inner sep=1pt] at ([xshift={shift:.1f}pt]axis cs:{dsname.replace(' ', '')},{YMIN}) {{OOM}};")
    lines += ["\\end{axis}", "\\end{tikzpicture}"]
    open(os.path.join(out_dir, f"fig_vertex_{tag}_pf_body.tex"), "w").write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out_dir", default=OUT); ap.add_argument("--trees", type=int, default=10)
    a = ap.parse_args(); os.makedirs(a.out_dir, exist_ok=True)
    for tag, title, prefix, machine, w, oom_logs in PANELS:
        g = grid(prefix, machine, a.trees, w, oom_logs)
        panel(tag, title, g, a.out_dir, "0.6\\textwidth" if tag == "hm4" else "0.38\\textwidth", legend=(tag == "hm4"))
        print("wrote", tag, "panel to", a.out_dir, file=sys.stderr)


if __name__ == "__main__":
    main()
