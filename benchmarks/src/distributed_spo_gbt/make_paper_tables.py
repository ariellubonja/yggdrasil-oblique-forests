#!/usr/bin/env python3
"""Emit the Distributed SPO-GBT paper's runtime and accuracy tables (LaTeX).
Runtime: 50-tree grid (results.csv, binary weights) vs same-boot single-machine anchors (anchors.csv).
Accuracy: Table-9-style AUC suite (suite_results.csv) vs the SPAA paper's single-machine GBT arms."""
import argparse, pathlib
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[3]
R = ROOT / "benchmarks/results/runtime"
OUT = ROOT / "paper/distributed_spo_gbt_kdd27/tables"
HDR = "% auto-generated by benchmarks/src/distributed_spo_gbt/make_paper_tables.py -- regenerate, do not hand-edit\n"
NAMES = {"HIGGS": "HIGGS", "SUSY": "SUSY", "EPSILON": "Epsilon", "YOUTUBE8M": "YouTube-8M"}
AXES = (("SPO-GBT", "SPARSE_OBLIQUE", "spo_gbt_exact_hwy"), ("AA-GBT", "AXIS_ALIGNED", "aa_gbt_exact"))
DASH = r"\multicolumn{1}{c}{---}"


def col(label):
    return r"\multicolumn{1}{c}{\parbox[b]{1.1cm}{\centering " + label + "}}"


def runtime_table(trees=50, workers=(1, 4)):
    d = pd.read_csv(R / "distributed_spo_gbt/results.csv")
    d = d[(d.rc == 0) & (d.trees == trees)].drop_duplicates(["dataset", "workers", "split_axis"], keep="last")
    a = pd.read_csv(R / "distributed_spo_gbt/anchors.csv")
    a = a[(a.rc == 0) & (a.trees == trees)].drop_duplicates(["dataset", "arm"], keep="last")
    heads = []
    for fam, _, _ in AXES:
        heads += [col(f"{fam} single machine")] + [col(f"{fam} dist.\\ $W{{=}}{w}$") for w in workers]
    lines = [HDR, r"\begin{table*}[t]", r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{4pt}",
             rf"\caption{{Training time in seconds of sparse oblique (SPO) and axis-aligned (AA) GBT ({trees} trees, depth 6), in single-machine and distributed with $W$ workers. \texttt{{MULTI\_THREAD}} mode. Default n. threads used for Distributed (6 per worker).}}",
             "% Threads: single machine = harness default (all cores); distributed = "
             + ", ".join(f"W={w}: {int(d[d.workers == w].threads_per_worker.iloc[0])}/worker" for w in workers) + ".",
             r"\label{tab:dist-runtime}",
             r"\begin{tabular}{l" + ("r" * (1 + len(workers)) + "|") * (len(AXES) - 1) + "r" * (1 + len(workers)) + "}",
             r"\toprule", "Dataset & " + " & ".join(heads) + r" \\", r"\midrule"]
    for ds in NAMES:
        cells = []
        for _, axis, arm in AXES:
            ref = a[(a.dataset == ds) & (a.arm == arm)].train_s
            ref = float(ref.iloc[0]) if len(ref) else None
            vals = [ref] + [next(iter(d[(d.dataset == ds) & (d.workers == w) & (d.split_axis == axis)].tree_training_s), None)
                            for w in workers]
            best = min((v for v in vals if v is not None), default=None)
            for i, v in enumerate(vals):
                if v is None: cells.append(DASH); continue
                s = f"{v:.0f}"
                if i and ref: s += f" ({v / ref:.1f}$\\times$)"
                cells.append(rf"\textbf{{{s}}}" if v == best else s)
        lines.append(NAMES[ds] + " & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    return "\n".join(lines) + "\n"


def accuracy_table(metric="test_auc"):
    p = pd.read_csv(R / "speedup_map_by_dataset/suite_results.csv"); p = p[p.status == "OK"]
    d = pd.read_csv(R / "distributed_spo_gbt/suite_results.csv"); d = d[d.rc == 0]
    d = d.drop_duplicates(["dataset", "fold", "workers", "split_axis"], keep="last")
    nfolds = p[p.method == "aa_gbt_exact"].groupby("dataset").fold.nunique()
    workers = sorted(d.workers.unique())
    arms = []  # (family, label, per-dataset fold values)
    for fam, axis, _ in AXES:
        parm = "spo_gbt_exact_hwy_fullproj" if axis == "SPARSE_OBLIQUE" else "aa_gbt_exact"
        arms.append((fam, f"{fam} single machine", p[p.method == parm].groupby("dataset")[metric]))
        for w in workers:
            arms.append((fam, f"{fam} dist.\\ $W{{=}}{w}$", d[(d.split_axis == axis) & (d.workers == w)].groupby("dataset")[metric]))
    stats = [(fam, lab, g.agg(["mean", "std", "count"])) for fam, lab, g in arms]
    # Only datasets whose every distributed cell has all folds (suite still running).
    done = [ds for ds in sorted(d.dataset.unique())
            if all(ds in s.index and s.loc[ds, "count"] == nfolds.get(ds, -1) for _, _, s in stats)]
    fams = [f for f, _, _ in AXES]
    lines = [HDR, r"\begin{table*}[t]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{2pt}",
             r"\caption{Test ROC AUC of single-machine and distributed GBT with $W$ workers (300 trees, depth 6), for sparse oblique (SPO) and axis-aligned (AA). Cells are the mean $\pm$ std over 5 CV folds. Single chronological holdouts have no std. Single-machine SPO-GBT samples $F$ projections per node; distributed SPO-GBT workers \TODO{sample $F/W$ projections from their $F/W$ columns.}}",
             rf"% {len(done)}/{nfolds.size} datasets complete when generated; the rest are still running.",
             r"\label{tab:dist-accuracy}",
             r"\begin{tabular}{l" + "|".join("r" * sum(f == fam for f, _, _ in stats) for fam in fams) + "}",
             r"\toprule", "Dataset & " + " & ".join(col(lab) for _, lab, _ in stats) + r" \\", r"\midrule"]
    means = {lab: [] for _, lab, _ in stats}
    for ds in done:
        cells = []
        for fam in fams:
            blk = [(lab, s.loc[ds]) for f, lab, s in stats if f == fam]
            best = max(r["mean"] for _, r in blk)
            for lab, r in blk:
                means[lab].append(r["mean"])
                mu, has_sd = f"{r['mean']:.4f}"[1:], r["count"] > 1
                sd = r"$_{\pm" + f"{r['std']:.4f}"[1:] + "}$" if has_sd else r"\phantom{$_{\pm.0000}$}"
                if abs(r["mean"] - best) < 5e-5:
                    cells.append(r"{\boldmath\textbf{" + mu + sd + "}}" if has_sd else r"\textbf{" + mu + "}" + sd)
                else:
                    cells.append(mu + sd)
        lines.append(ds.replace("_", r"\_") + " & " + " & ".join(cells) + r" \\")
    lines += [r"\midrule", "Mean & " + " & ".join(f"{sum(means[lab]) / len(means[lab]):.4f}"[1:] + r"\phantom{$_{\pm.0000}$}"
                                                 for _, lab, _ in stats) + r" \\",
              r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    return "\n".join(lines) + "\n"


FIG_ARMS = (("SPO", "SPARSE_OBLIQUE", "spo_gbt_exact_hwy", ("0C447C", "378ADD", "B5D4F4")),
            ("AA", "AXIS_ALIGNED", "aa_gbt_exact", ("993C1D", "D85A30", "F5C4B3")))


def runtime_figure(trees=50, workers=(1, 4)):
    """Same cells as runtime_table, as interleaved SPO/AA bars on a log axis."""
    d = pd.read_csv(R / "distributed_spo_gbt/results.csv")
    d = d[(d.rc == 0) & (d.trees == trees)].drop_duplicates(["dataset", "workers", "split_axis"], keep="last")
    a = pd.read_csv(R / "distributed_spo_gbt/anchors.csv")
    a = a[(a.rc == 0) & (a.trees == trees)].drop_duplicates(["dataset", "arm"], keep="last")
    series = []  # (legend, color, {dataset: seconds}), interleaved SPO/AA per setting
    for k, w in enumerate((None,) + tuple(workers)):
        for fam, axis, arm, colors in FIG_ARMS:
            if w is None:
                v = {ds: a[(a.dataset == ds) & (a.arm == arm)].train_s for ds in NAMES}
                lab = f"{fam} Local"
            else:
                v = {ds: d[(d.dataset == ds) & (d.workers == w) & (d.split_axis == axis)].tree_training_s for ds in NAMES}
                lab = f"{fam} $W{{=}}{w}$ Dist."
            series.append((lab, colors[k], {ds: float(x.iloc[0]) for ds, x in v.items() if len(x)}))
    lines = [HDR, r"\begin{figure}[t]", r"\centering",
             r"\begin{tikzpicture}", r"\begin{axis}[ybar, ymode=log, log origin=infty, ymin=5, ymax=5000,",
             r"  width=\columnwidth, height=5.2cm, bar width=3.6pt, enlarge x limits=0.15,",
             "  symbolic x coords={" + ",".join(NAMES.values()) + "}, xtick=data,",
             r"  ylabel={Training time (s)}, ymajorgrids, major grid style={gray!25},",
             r"  tick label style={font=\footnotesize}, label style={font=\footnotesize},",
             r"  legend style={font=\scriptsize, at={(0.5,1.03)}, anchor=south, draw=none, /tikz/every even column/.append style={column sep=6pt}},",
             r"  legend columns=2, legend cell align=left, area legend, xtick style={draw=none}]"]
    for lab, color, v in series:
        coords = " ".join(f"({NAMES[ds]},{v[ds]:.0f})" for ds in NAMES if ds in v)
        lines += [rf"\addplot[fill={{rgb,255:red,{int(color[:2], 16)};green,{int(color[2:4], 16)};blue,{int(color[4:], 16)}}}, draw=none] coordinates {{{coords}}};",
                  rf"\addlegendentry{{{lab}}}"]
    lines += [r"\end{axis}", r"\end{tikzpicture}",
              r"\caption{Training time in seconds (log scale) of sparse oblique (SPO) and axis-aligned (AA) GBT, local (single machine) and distributed with $W$ workers. Same runs as Table~\ref{tab:dist-runtime}.}",
              r"\Description{Grouped bar chart per dataset of SPO and AA GBT training time, local and distributed.}",
              r"\label{fig:dist-runtime}", r"\end{figure}"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default=str(OUT)); args = ap.parse_args()
    out = pathlib.Path(args.out); out.mkdir(parents=True, exist_ok=True)
    (out / "table_dist_runtime.tex").write_text(runtime_table())
    (out / "table_dist_accuracy.tex").write_text(accuracy_table())
    fig = out.parent / "figures"; fig.mkdir(exist_ok=True)
    (fig / "fig_dist_runtime.tex").write_text(runtime_figure())
    print(f"wrote {out}/table_dist_runtime.tex, table_dist_accuracy.tex")
