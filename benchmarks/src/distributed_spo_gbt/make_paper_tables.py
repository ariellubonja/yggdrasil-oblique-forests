#!/usr/bin/env python3
"""Emit the Distributed SPO-GBT paper's accuracy table BODY (tabular only) and the accuracy figures.
Table/figure environments, captions and labels live in main.tex, which \\input{}s the bodies.
Accuracy: Table-9-style AUC suite (suite_results.csv) vs the SPAA paper's single-machine GBT arms."""
import argparse, pathlib
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[3]
R = ROOT / "benchmarks/results/runtime"
OUT = ROOT / "paper/distributed_spo_gbt_kdd28/tables"
HDR = ("% auto-generated by benchmarks/src/distributed_spo_gbt/make_paper_tables.py -- regenerate, do not hand-edit\n"
       "% source: IN-PROCESS runs on one m7i.metal-24xl (workers = threads of one process, no network), not a Vertex cluster\n")
NAMES = {"HIGGS": "HIGGS", "SUSY": "SUSY", "EPSILON": "Epsilon", "YOUTUBE8M": "YouTube-8M"}
AXES = (("SPO-GBT", "SPARSE_OBLIQUE", "spo_gbt_exact_hwy"), ("AA-GBT", "AXIS_ALIGNED", "aa_gbt_exact"))


def col(label):
    return r"\multicolumn{1}{c}{\parbox[b]{1.0cm}{\centering " + label + "}}"


ACC_CSV = None  # --accuracy_csv: one rerun file (run_table8_local.sh) for every accuracy arm


def _rerun_frames(path):
    """run_table8_local.sh results.csv -> the (single-machine, distributed) frames of the recorded CSVs."""
    x = pd.read_csv(path); x = x[x.rc == 0]
    one = x[x.workers == "single"]
    p = one.assign(status="OK", method=one.arm.map({"single:SPO": "spo_gbt_exact_hwy_fullproj", "single:AA": "aa_gbt_exact"}))
    d = x[x.workers != "single"].assign(workers=lambda f: f.workers.astype(int))
    return p, d


def accuracy_stats(metric="test_auc"):
    """Per-arm (family, label, mean/std/count by dataset) and the datasets with every fold done."""
    if ACC_CSV:
        p, d = _rerun_frames(ACC_CSV)
    else:
        p = pd.read_csv(R / "speedup_map_by_dataset/suite_results.csv"); p = p[p.status == "OK"]
        d = pd.read_csv(R / "distributed_spo_gbt/suite_results.csv"); d = d[d.rc == 0]
    d = d.drop_duplicates(["dataset", "fold", "workers", "split_axis"], keep="last")
    nfolds = p[p.method == "aa_gbt_exact"].groupby("dataset").fold.nunique()
    workers = sorted(d.workers.unique())
    arms = []  # (family, label, per-dataset fold values)
    for fam, axis, _ in AXES:
        parm = "spo_gbt_exact_hwy_fullproj" if axis == "SPARSE_OBLIQUE" else "aa_gbt_exact"
        arms.append((fam, f"{fam} single machine", p[p.method == parm].groupby("dataset")[metric]))
        for w in workers:
            arms.append((fam, f"{fam} dist.\\ $W{{=}}{w}$", d[(d.split_axis == axis) & (d.workers == w)].groupby("dataset")[metric]))
    stats = [(fam, lab, g.agg(["mean", "std", "count"])) for fam, lab, g in arms]
    # Only datasets whose every distributed cell has all folds (suite still running).
    done = [ds for ds in sorted(d.dataset.unique())
            if all(ds in s.index and s.loc[ds, "count"] == nfolds.get(ds, -1) for _, _, s in stats)]
    return stats, done, nfolds


def accuracy_table(metric="test_auc"):
    stats, done, nfolds = accuracy_stats(metric)
    fams = [f for f, _, _ in AXES]
    lines = [HDR, r"\resizebox{\linewidth}{!}{%",  # 13 columns at W up to 32
             r"\begin{tabular}{l" + "|".join("r" * sum(f == fam for f, _, _ in stats) for fam in fams) + "}",
             r"\toprule", "Dataset & " + " & ".join(col(lab) for _, lab, _ in stats) + r" \\", r"\midrule"]
    means = {lab: [] for _, lab, _ in stats}
    for ds in done:
        cells = []
        for fam in fams:
            blk = [(lab, s.loc[ds]) for f, lab, s in stats if f == fam]
            best = max(r["mean"] for _, r in blk)
            for i, (lab, r) in enumerate(blk):
                means[lab].append(r["mean"])
                mu, has_sd = f"{r['mean']:.4f}"[1:], r["count"] > 1
                sd = r"$_{\pm" + f"{r['std']:.4f}"[1:] + "}$" if has_sd else r"\phantom{$_{\pm.0000}$}"
                if abs(r["mean"] - best) < 5e-5:
                    c = r"{\boldmath\textbf{" + mu + sd + "}}" if has_sd else r"\textbf{" + mu + "}" + sd
                else:
                    c = mu + sd
                # distributed cells colored by AUC delta (x1e3) vs the family's single machine, as the old heatmap
                cells.append(_delta_color((r["mean"] - blk[0][1]["mean"]) * 1e3) + c if i else c)
        lines.append(ds.replace("_", r"\_") + " & " + " & ".join(cells) + r" \\")
    # Mean row: bold the best per family, compared at the printed 4 decimals
    avg = {lab: round(sum(means[lab]) / len(means[lab]), 4) for _, lab, _ in stats}
    top = {fam: max(avg[lab] for f, lab, _ in stats if f == fam) for fam in fams}
    ref = {f: avg[lab] for f, lab, _ in reversed(stats)}  # first arm per family = single machine
    mcells = [("" if "single" in lab else _delta_color((avg[lab] - ref[f]) * 1e3))
              + (r"\textbf{%s}" if avg[lab] == top[f] else "%s") % f"{avg[lab]:.4f}"[1:] + r"\phantom{$_{\pm.0000}$}"
              for f, lab, _ in stats]
    lines += [r"\midrule", "Mean & " + " & ".join(mcells) + r" \\",
              r"\bottomrule", r"\end{tabular}}"]
    return "\n".join(lines) + "\n"


FIG_ARMS = (("SPO", "SPARSE_OBLIQUE", "spo_gbt_exact_hwy", ("0C447C", "378ADD", "B5D4F4")),
            ("AA", "AXIS_ALIGNED", "aa_gbt_exact", ("993C1D", "D85A30", "F5C4B3")))


def _rgb(c):
    return "{rgb,255:red,%d;green,%d;blue,%d}" % tuple(int(c[k:k + 2], 16) for k in (0, 2, 4))


def _diverge(v, cap=15.0):
    """Blue (better) / red (worse) / gray midpoint, as an RGB triple string for \\cellcolor[RGB]."""
    t = max(-1.0, min(1.0, v / cap))
    mid, pole = (240, 239, 236), ((42, 120, 214) if t > 0 else (227, 73, 72))
    return ",".join(str(round(m + abs(t) * (q - m))) for m, q in zip(mid, pole))


def _delta_color(v):
    """Cell prefix: diverging background, white text past |v| > 9."""
    return rf"\cellcolor[RGB]{{{_diverge(v)}}}" + (r"\color{white}" if abs(v) > 9 else "")


def accuracy_mean_figure(metric="test_auc"):
    """The table's Mean row as one line per family over W, single machine as dotted references (tikzpicture only)."""
    stats, done, _ = accuracy_stats(metric)
    xs = [lab.split("W{=}")[1].rstrip("$") for f, lab, _ in stats if f == AXES[0][0] and "W{=}" in lab]
    xl = [f"$W{{=}}{w}$" for w in xs]
    lines = [HDR, r"\begin{tikzpicture}",
             r"\begin{axis}[width=0.5\textwidth, height=4.6cm, symbolic x coords={" + ",".join(xs) + "}, xtick=data,",
             "  xticklabels={" + ",".join(xl) + r"}, ylabel={Mean test ROC AUC},",
             r"  yticklabel style={/pgf/number format/fixed, /pgf/number format/precision=3, /pgf/number format/fixed zerofill},",
             r"  tick label style={font=\footnotesize}, label style={font=\footnotesize}, tick style={draw=none},",
             r"  legend style={font=\scriptsize, at={(0.5,1.03)}, anchor=south, draw=none,"
             r" /tikz/every even column/.append style={column sep=6pt}}, legend columns=2, legend cell align=left]"]
    all_m, refs = [], []
    for (f, _, _, colors), mark in zip(FIG_ARMS, ("*", "diamond*")):
        m = [sum(st.loc[ds, "mean"] for ds in done) / len(done) for g, _, st in stats if g == f"{f}-GBT"]
        all_m += m
        refs.append((f, colors[1], m[0]))  # m[0] = single machine, drawn flat across all W
        style = "" if mark == "*" else ", dashed"
        lines += [rf"\addplot[color={_rgb(colors[1])}, mark={mark}, thick{style}] coordinates {{"
                  + " ".join(f"({x},{v:.4f})" for x, v in zip(xs, m[1:])) + "};", rf"\addlegendentry{{{f}-GBT}}"]
    lo, hi = min(all_m), max(all_m)  # legend sits above the axis
    lines[2] = lines[2].replace("height=4.6cm,", f"height=4.6cm, ymin={lo - 0.1 * (hi - lo):.4f}, ymax={hi + 0.1 * (hi - lo):.4f},")
    for f, c, v in refs:
        lines += [rf"\addplot[color={_rgb(c)}, thick, densely dotted, no marks] coordinates {{({xs[0]},{v:.4f}) ({xs[-1]},{v:.4f})}};",
                  rf"\addlegendentry{{single-machine {f}-GBT}}"]
    lines += [r"\end{axis}", r"\end{tikzpicture}"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--accuracy_csv", default="", help="rerun results.csv for the accuracy table + figure")
    ap.add_argument("--accuracy_note", default="IN-PROCESS rerun on one EC2 box (Xeon 8259CL; workers = threads of one process)")
    args = ap.parse_args()
    out = pathlib.Path(args.out); out.mkdir(parents=True, exist_ok=True)
    if args.accuracy_csv:
        ACC_CSV = args.accuracy_csv
        HDR = ("% auto-generated by benchmarks/src/distributed_spo_gbt/make_paper_tables.py -- regenerate, do not hand-edit\n"
               "% source: " + args.accuracy_note + ", "
               + args.accuracy_csv.split("benchmarks/")[-1] + "\n")
    (out / "table_dist_accuracy_body.tex").write_text(accuracy_table())
    fig = out.parent / "figures/evaluation/multi_thread_m7i_metal_24x"; fig.mkdir(parents=True, exist_ok=True)
    (fig / "fig_dist_accuracy_mean_body.tex").write_text(accuracy_mean_figure())
    print(f"wrote accuracy bodies under {out}")
