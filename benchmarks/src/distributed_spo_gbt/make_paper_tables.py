#!/usr/bin/env python3
"""Emit the Distributed SPO-GBT paper's accuracy table BODY (tabular only) and the accuracy figures.
Table/figure environments, captions and labels live in main.tex, which \\input{}s the bodies.
Accuracy: one rerun results.csv (--accuracy_csv, required) for every arm."""
import argparse, pathlib, sys
import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "params"))
import params as kdd28  # noqa: E402  (params/kdd28_params.json)

ROOT = pathlib.Path(__file__).resolve().parents[3]
OUT = ROOT / "paper/distributed_spo_gbt_kdd28/tables"
HDR = ("% auto-generated by benchmarks/src/distributed_spo_gbt/make_paper_tables.py -- regenerate, do not hand-edit\n"
       "% source: IN-PROCESS runs on one m7i.metal-24xl (workers = threads of one process, no network), not a Vertex cluster\n")
NAMES = {"HIGGS": "HIGGS", "SUSY": "SUSY", "EPSILON": "Epsilon", "YOUTUBE8M": "YouTube-8M"}
AXES = (("SPO-GBT", "SPARSE_OBLIQUE", "spo_gbt_exact_hwy"), ("AA-GBT", "AXIS_ALIGNED", "aa_gbt_exact"))


def col(label):
    return r"\multicolumn{1}{c}{\parbox[b]{1.0cm}{\centering " + label + "}}"


ACC_CSV = None  # --accuracy_csv: one rerun file (run_table8_local.sh) for every accuracy arm
PROFILE = kdd28.generator_profile(__file__)  # --profile
ARMS_SHOWN = ["single_spo", "single_aa", "dist_spo", "dist_aa"]
ARM_NAME = {a: a for a in ARMS_SHOWN}  # role -> profile arm (--arms)
_CHECKED = []
# Extra single-machine columns after AA-GBT, each its own block: (csv, row arm, profile arm, family label)
EXTRA_SPECS = {"aaspo": ("single:AA+SPO", "distacc_single_aa_spo", "AA+SPO-GBT"),
               "exact300": ("single:SPO-harness-exact300", "distacc_single_spo_harness_exact300", "SPO-GBT Hao")}
EXTRA = []
EXTRA_FIRST = False  # --extra_first: extra single-machine columns right after Dataset (default: after AA-GBT)
ONE_BOLD = False  # --one_bold (implied by --purple): one bold per row = highest unrounded mean over all columns
PURPLE_ON = False  # --purple: dist SPO cell == dist AA cell at the same W on every fold -> both purple, dataset gets *
PURPLE = r"\cellcolor[RGB]{215,195,240}"
SHAPES = {}  # dataset -> (rows, features) from --dataset_shapes, always printed after the name
SHAPES_CSV = "benchmarks/results/runtime/speedup_map_by_dataset/analysis/per_dataset_summary.csv"  # same fold files
PLACEHOLDER_W = []  # --placeholder_workers: SPO dist columns printed as "--" until their rows exist
PLACEHOLDERS = set()  # labels of those columns (no rows yet)
STD_BELOW = False  # --std_below: the +-std goes under the mean, in \tiny gray (white on dark cells)
GROUP_HEADER = False  # --group_header: '<family> dist.' spans its W=... columns (narrower table, larger font)
TIME_ROW = False  # --time_row: a "Mean time (s)" row (train_s) under Mean, single-machine columns only
SHAPE_BELOW = False  # --shape_below: (rows, cols) under the dataset name, in \tiny gray
GRAY = r"\color{black!55}"
SHORT = {"HR_Analytics_Job_Change_of_Data_Scientists": "HR_Data_Scientists"}


def _k(n):
    return f"{round(n / 1000)}k" if n >= 10000 else str(n)


def ds_label(ds, mark=""):
    name = SHORT.get(ds, ds).replace("_", r"\_") + mark
    if ds not in SHAPES:
        sys.exit(f"--dataset_shapes has no row for {ds}")
    r, f = SHAPES[ds]
    if SHAPE_BELOW:  # shape on a second, smaller gray line: narrower first column
        return r"\shortstack[l]{" + name + r"\\[-2pt]{\tiny" + GRAY + f" ({_k(r)}, {f})" + "}}"
    return f"{name} ({_k(r)}, {f})"


def purple_pairs(d, metric):
    """{(dataset, W)} where distributed SPO and AA give the same raw metric on every fold."""
    out = set()
    for (ds, w), g in d.groupby(["dataset", "workers"]):
        s = g[g.split_axis == "SPARSE_OBLIQUE"].set_index("fold")[metric]
        a = g[g.split_axis == "AXIS_ALIGNED"].set_index("fold")[metric]
        if len(s) and s.index.is_unique and a.index.is_unique and sorted(s.index) == sorted(a.index) \
                and (s.sort_index() == a.sort_index()).all():
            out.add((ds, int(w)))
    return out


def _rerun_arm(r):
    """run_table8_local.sh arm label -> table8 arm."""
    w, a = str(r["arm"]).split(":")
    return ARM_NAME[("single_" if w == "single" else "dist_") + a.lower()]


def check_inputs(p, d):
    """Refuse drift of the rows used (once per run)."""
    if _CHECKED:
        return
    _CHECKED.append(1)
    x = pd.read_csv(ACC_CSV)
    kdd28.check_frame(x[x.rc == 0], PROFILE, ARMS_SHOWN, pathlib.Path(ACC_CSV).name, arm_of=_rerun_arm)
    for path, row_arm, parm, _ in EXTRA:
        y = pd.read_csv(path); y = y[(y.rc == 0) & (y.arm == row_arm)]
        kdd28.check_frame(y, PROFILE, [parm], pathlib.Path(path).name, arm_of=lambda r, parm=parm: parm)


def _rerun_frames(path):
    """run_table8_local.sh results.csv -> the (single-machine, distributed) frames of the recorded CSVs."""
    x = pd.read_csv(path); x = x[x.rc == 0]
    one = x[x.workers == "single"]
    p = one.assign(status="OK", method=one.arm.map({"single:SPO": "spo_gbt_exact_hwy_fullproj", "single:AA": "aa_gbt_exact"}))
    d = x[x.workers != "single"].assign(workers=lambda f: f.workers.astype(int))
    return p, d


def accuracy_stats(metric="test_auc"):
    """Per-arm (family, label, mean/std/count by dataset) and the datasets with every fold done."""
    p, d = _rerun_frames(ACC_CSV)
    check_inputs(p[p.method.isin(["spo_gbt_exact_hwy_fullproj", "aa_gbt_exact"])], d)
    d = d.drop_duplicates(["dataset", "fold", "workers", "split_axis"], keep="last")
    nfolds = p[p.method == "aa_gbt_exact"].groupby("dataset").fold.nunique()
    axis_arms, extra_arms = [], []  # (family, label, per-dataset fold values)
    times = {}  # single-machine label -> per-dataset mean train_s (--time_row)
    for fam, axis, _ in AXES:
        parm = "spo_gbt_exact_hwy_fullproj" if axis == "SPARSE_OBLIQUE" else "aa_gbt_exact"
        axis_arms.append((fam, f"{fam} single machine", p[p.method == parm].groupby("dataset")[metric]))
        times[f"{fam} single machine"] = p[p.method == parm].groupby("dataset").train_s.mean()
        da = d[d.split_axis == axis]  # per-axis W: AA need not run every W (2026-11-06)
        ws = set(da.workers.unique()) | (set(PLACEHOLDER_W) if axis == "SPARSE_OBLIQUE" else set())
        for w in sorted(ws):
            lab = f"{fam} dist.\\ $W{{=}}{w}$"
            if w not in set(da.workers.unique()):
                PLACEHOLDERS.add(lab)
                axis_arms.append((fam, lab, None))
                continue
            axis_arms.append((fam, lab, da[da.workers == w].groupby("dataset")[metric]))
    for path, row_arm, _, fam in EXTRA:  # bold = best of all single-machine columns
        y = pd.read_csv(path); y = y[(y.rc == 0) & (y.arm == row_arm)]
        extra_arms.append((fam, f"{fam} single machine", y.groupby("dataset")[metric]))
        times[f"{fam} single machine"] = y.groupby("dataset").train_s.mean()
    arms = extra_arms + axis_arms if EXTRA_FIRST else axis_arms + extra_arms
    allds = sorted(d.dataset.unique())
    empty = pd.DataFrame({"mean": float("nan"), "std": float("nan"), "count": 0}, index=allds)
    stats = [(fam, lab, empty if g is None else g.agg(["mean", "std", "count"])) for fam, lab, g in arms]
    # Only datasets whose every distributed cell has all folds (suite still running); placeholders skipped.
    done = [ds for ds in allds
            if all(ds in s.index and s.loc[ds, "count"] == nfolds.get(ds, -1) for _, lab, s in stats if lab not in PLACEHOLDERS)]
    accuracy_stats.purple = purple_pairs(d, metric) if PURPLE_ON else set()
    accuracy_stats.times = times
    return stats, done, nfolds


def group_header(stats, fams):
    """Two header rows: '<family> dist.' over its W columns (cmidrule), then W=..., so dist columns are number-wide."""
    top, rules, bot, j = [], [], [], 2  # j = tabular column index (1 = Dataset)
    for k, fam in enumerate(fams):
        labs = [lab for f, lab, _ in stats if f == fam]
        dist = [lab for lab in labs if "W{=}" in lab]
        for lab in labs:
            if "W{=}" not in lab:
                top.append(r"\multicolumn{1}{c}{}"); bot.append(col(lab)); j += 1  # no | in the group row
        if dist:
            top.append(r"\multicolumn{%d}{c}{%s dist.}" % (len(dist), fam))
            rules.append(r"\cmidrule(lr){%d-%d}" % (j, j + len(dist) - 1))
            bot += [r"\multicolumn{1}{c}{$W{=}" + lab.split("W{=}")[1] + "}" for lab in dist]; j += len(dist)
    return [" & " + " & ".join(top) + r" \\", "".join(rules), "Dataset & " + " & ".join(bot) + r" \\"]


def accuracy_table(metric="test_auc"):
    stats, done, nfolds = accuracy_stats(metric)
    axis_fams, extra_fams = [f for f, _, _ in AXES], [e[3] for e in EXTRA]
    fams = extra_fams + axis_fams if EXTRA_FIRST else axis_fams + extra_fams
    singles = [lab for _, lab, _ in stats if "single" in lab]
    lines = [HDR, r"\resizebox{\linewidth}{!}{%",  # 13 columns at W up to 32
             r"\begin{tabular}{l" + "|".join("r" * sum(f == fam for f, _, _ in stats) for fam in fams) + "}",
             r"\toprule"] + (group_header(stats, fams) if GROUP_HEADER else
             ["Dataset & " + " & ".join(col(lab) for _, lab, _ in stats) + r" \\"]) + [r"\midrule"]
    means = {lab: [] for _, lab, _ in stats}
    purple = accuracy_stats.purple
    for ds in done:
        gbest = max(s.loc[ds, "mean"] for _, lab, s in stats if lab not in PLACEHOLDERS)
        cells = []
        for fam in fams:
            blk = [(lab, s.loc[ds]) for f, lab, s in stats if f == fam]
            best = max(r["mean"] for lab, r in blk if lab not in PLACEHOLDERS)
            if fam in extra_fams:
                best = max(s.loc[ds, "mean"] for _, lab, s in stats if lab in singles)
            for i, (lab, r) in enumerate(blk):
                if lab in PLACEHOLDERS:
                    cells.append("--")
                    continue
                means[lab].append(r["mean"])
                is_best = r["mean"] == gbest if ONE_BOLD else abs(r["mean"] - best) < 5e-5
                mu, has_sd = f"{r['mean']:.4f}"[1:], r["count"] > 1
                sd = r"$_{\pm" + f"{r['std']:.4f}"[1:] + "}$" if has_sd else r"\phantom{$_{\pm.0000}$}"
                if STD_BELOW:  # mean on top, +-std under it in \tiny
                    b = (lambda t: r"{\boldmath\textbf{" + t + "}}") if is_best else (lambda t: t)
                    sd = r"\\[-2pt]{\tiny" + GRAY + " " + b(r"$\pm$" + f"{r['std']:.4f}"[1:]) + "}" if has_sd else ""
                    c = r"\shortstack[r]{" + b(mu) + sd + "}"
                elif is_best:
                    c = r"{\boldmath\textbf{" + mu + sd + "}}" if has_sd else r"\textbf{" + mu + "}" + sd
                else:
                    c = mu + sd
                # distributed cells colored by AUC delta (x1e3) vs the family's single machine, as the old heatmap
                w = int(lab.split("W{=}")[1].rstrip("$")) if "W{=}" in lab else None
                pre = PURPLE if w is not None and fam in axis_fams and (ds, w) in purple else (
                    _delta_color((r["mean"] - blk[0][1]["mean"]) * 1e3) if i else "")
                cells.append(pre + (c.replace(GRAY, "") if r"\color{white}" in pre else c))
        mark = "$^{*}$" if any(x == ds for x, _ in purple) else ""
        lines.append(ds_label(ds, mark) + " & " + " & ".join(cells) + r" \\")
    # Mean row: bold the best per family, compared at the printed 4 decimals
    real = [(f, lab, s) for f, lab, s in stats if lab not in PLACEHOLDERS]
    raw = {lab: sum(means[lab]) / len(means[lab]) for _, lab, _ in real}
    avg = {lab: round(raw[lab], 4) for _, lab, _ in real}
    top = {fam: max(avg[lab] for f, lab, _ in real if f == fam) for fam in fams}
    for fam in extra_fams:
        top[fam] = max(avg[lab] for lab in singles)
    ref = {f: avg[lab] for f, lab, _ in reversed(real)}  # first arm per family = single machine
    pad = "" if STD_BELOW else r"\phantom{$_{\pm.0000}$}"
    mcells = ["--" if lab in PLACEHOLDERS else ("" if "single" in lab else _delta_color((avg[lab] - ref[f]) * 1e3))
              + (r"\textbf{%s}" if (raw[lab] == max(raw.values()) if ONE_BOLD else avg[lab] == top[f]) else "%s") % f"{avg[lab]:.4f}"[1:] + pad
              for f, lab, _ in stats]
    lines += [r"\midrule", "Mean & " + " & ".join(mcells) + r" \\"]
    if TIME_ROW:  # mean over the table's datasets of the per-dataset mean train_s, single-machine columns only
        tm = accuracy_stats.times
        sec = lambda x: f"{x:,.0f}".replace(",", "{,}") if x >= 10 else f"{x:.1f}"
        lines.append("Mean time (s) & " + " & ".join(sec(tm[lab].loc[done].mean()) if lab in tm else "" for _, lab, _ in stats) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}"]
    return kdd28.add_setup("\n".join(lines) + "\n", kdd28.setup_line(PROFILE, ARMS_SHOWN + [e[2] for e in EXTRA]))


FIG_ARMS = (("SPO", "SPARSE_OBLIQUE", "spo_gbt_exact_hwy", ("0C447C", "378ADD", "B5D4F4")),
            ("AA", "AXIS_ALIGNED", "aa_gbt_exact", ("993C1D", "D85A30", "F5C4B3")))


def _rgb(c):
    return "{rgb,255:red,%d;green,%d;blue,%d}" % tuple(int(c[k:k + 2], 16) for k in (0, 2, 4))


def _diverge(v, cap=15.0):
    """Blue (better) / red (worse) / gray midpoint, as an RGB triple string for \\cellcolor[RGB]."""
    t = max(-1.0, min(1.0, v / cap))
    mid, pole = (240, 239, 236), ((42, 120, 214) if t > 0 else (227, 73, 72))
    return ",".join(str(round(m + abs(t) * (q - m))) for m, q in zip(mid, pole))


def _delta_color(v):
    """Cell prefix: diverging background, white text past |v| > 9."""
    return rf"\cellcolor[RGB]{{{_diverge(v)}}}" + (r"\color{white}" if abs(v) > 9 else "")


def accuracy_mean_figure(metric="test_auc"):
    """The table's Mean row as one line per family over W, single machine as dotted references (tikzpicture only)."""
    stats, done, _ = accuracy_stats(metric)
    xs = [lab.split("W{=}")[1].rstrip("$") for f, lab, _ in stats if f == AXES[0][0] and "W{=}" in lab]
    xl = [f"$W{{=}}{w}$" for w in xs]
    lines = [HDR, r"\begin{tikzpicture}",
             r"\begin{axis}[width=0.5\textwidth, height=4.6cm, symbolic x coords={" + ",".join(xs) + "}, xtick=data,",
             "  xticklabels={" + ",".join(xl) + r"}, ylabel={Mean test ROC AUC},",
             r"  yticklabel style={/pgf/number format/fixed, /pgf/number format/precision=3, /pgf/number format/fixed zerofill},",
             r"  tick label style={font=\footnotesize}, label style={font=\footnotesize}, tick style={draw=none},",
             r"  legend style={font=\scriptsize, at={(0.5,1.03)}, anchor=south, draw=none,"
             r" /tikz/every even column/.append style={column sep=6pt}}, legend columns=2, legend cell align=left]"]
    all_m, refs = [], []
    for (f, _, _, colors), mark in zip(FIG_ARMS, ("*", "diamond*")):
        m = [sum(st.loc[ds, "mean"] for ds in done) / len(done) for g, _, st in stats if g == f"{f}-GBT"]
        all_m += m
        refs.append((f"{f}-GBT", colors[1], m[0]))  # m[0] = single machine, drawn flat across all W
        style = "" if mark == "*" else ", dashed"
        lines += [rf"\addplot[color={_rgb(colors[1])}, mark={mark}, thick{style}] coordinates {{"
                  + " ".join(f"({x},{v:.4f})" for x, v in zip(xs, m[1:])) + "};", rf"\addlegendentry{{{f}-GBT}}"]
    for (_, _, _, fam), col_ in zip(EXTRA, ("5A9E3C", "8A5CC8")):  # extra single-machine arms: dotted refs
        v = next(sum(st.loc[ds, "mean"] for ds in done) / len(done) for g, _, st in stats if g == fam)
        all_m.append(v); refs.append((fam, col_, v))
    lo, hi = min(all_m), max(all_m)  # legend sits above the axis
    lines[2] = lines[2].replace("height=4.6cm,", f"height=4.6cm, ymin={lo - 0.1 * (hi - lo):.4f}, ymax={hi + 0.1 * (hi - lo):.4f},")
    same = {}  # refs that print at the same y interleave their dashes, so every colour shows
    for i, (_, _, v) in enumerate(refs): same.setdefault(f"{v:.4f}", []).append(i)
    for i, (f, c, v) in enumerate(refs):
        grp = same[f"{v:.4f}"]; k = len(grp)
        dash = "densely dotted" if k == 1 else f"dash pattern=on 4pt off {4 * (k - 1)}pt, dash phase={4 * grp.index(i)}pt"
        lines += [rf"\addplot[color={_rgb(c)}, thick, {dash}, no marks] coordinates {{({xs[0]},{v:.4f}) ({xs[-1]},{v:.4f})}};",
                  rf"\addlegendentry{{single-machine {f}}}"]
    lines += [r"\end{axis}", r"\end{tikzpicture}"]
    return kdd28.add_setup("\n".join(lines) + "\n", kdd28.setup_line(PROFILE, ARMS_SHOWN))


