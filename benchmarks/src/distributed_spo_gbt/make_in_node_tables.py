#!/usr/bin/env python3
"""Emit the Distributed SPO-GBT paper's in-node parallelism table BODIES (tabular only).
Captions, labels and table environments live in main.tex, which \input{}s the bodies.
Arms: "SPO in-node sequential" = rebased-main 23053344, "SPO in-node parallel" = in-node-parallelism-SPOGBT cee3b4c8.
Sources: benchmarks/results/runtime/GBT/in_node_parallelism_2026-10-22/{sm_thread_sweep_old_vs_new.csv,susy_and_distributed_old_vs_new.txt}."""
import argparse, pathlib, re
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "benchmarks/results/runtime/GBT/in_node_parallelism_2026-10-22"
OUT = ROOT / "paper/distributed_spo_gbt_kdd27/tables"
HDR = ("% auto-generated by benchmarks/src/distributed_spo_gbt/make_in_node_tables.py -- regenerate, do not hand-edit\n"
       "% data: benchmarks/results/runtime/GBT/in_node_parallelism_2026-10-22/ (run 2026-10-22, m7i.metal-24xl);\n"
       "% sequential = rebased-main 23053344, parallel = in-node-parallelism-SPOGBT cee3b4c8.\n")
SEQ, PAR = "SPO in-node sequential", "SPO in-node parallel"
DSEQ, DPAR = "Dist. SPO in-node sequential", "Dist. SPO in-node parallel"
# Paper order and names; SUSY (F=18) has P = ceil(sqrt(18)) = 5 and comes from the txt, not the CSV.
DATASETS = [("HIGGS", "HIGGS", None), ("SUSY", "SUSY", 5), ("EPSILON", "Epsilon", None), ("YT8M", "YouTube-8M", None)]
THREADS = (1, 4, 8, 16, 24, 48)
DASH = r"\multicolumn{1}{c}{---}"


def secs(v):
    return f"{v:.1f}" if v >= 10 else f"{v:.2f}"


def parse_txt():
    """(sm|dist, base|new|new_stdsort, threads) -> dict(train_s, findsplits_ms)."""
    runs = {}
    for line in (SRC / "susy_and_distributed_old_vs_new.txt").read_text().splitlines():
        m = re.match(r"^(sm|dist)_bin_(base|new|new_stdsort)_t(\d+)_n\d+\s+(.*)$", line)
        if not m:
            continue
        kind, arm, t, rest = m.group(1), m.group(2), int(m.group(3)), m.group(4)
        r = {}
        if (mm := re.search(r"train_block_s=([\d.]+)", rest)):
            r["train_s"] = float(mm.group(1))
        if (mm := re.search(r"train=([\d.]+)(ms|s)\b", rest)):
            r["train_s"] = float(mm.group(1)) / (1000 if mm.group(2) == "ms" else 1)
        if (mm := re.search(r"avg:([\d.]+)ms", rest)):
            r["findsplits_ms"] = float(mm.group(1))
        runs[(kind, arm, t)] = r
    return runs


def threads_table():
    d = pd.read_csv(SRC / "sm_thread_sweep_old_vs_new.csv", comment="#")
    txt = parse_txt()
    lines = [HDR, r"\begin{tabular}{ll" + "r" * len(THREADS) + "}", r"\toprule",
             r"Dataset & Arm & \multicolumn{" + str(len(THREADS)) + r"}{c}{Threads $T$} \\",
             " & & " + " & ".join(str(t) for t in THREADS) + r" \\", r"\midrule"]
    for key, name, p_fixed in DATASETS:
        if key in set(d.dataset):
            sub = d[d.dataset == key].set_index("threads")
            p = int(sub.P.iloc[0])
            seq = {t: float(sub.old_train_block_s[t]) for t in sub.index}
            par = {t: float(sub.new_train_block_s[t]) for t in sub.index}
        else:  # SUSY: single-machine rows of the txt
            p = p_fixed
            seq = {t: r["train_s"] for (k, a, t), r in txt.items() if k == "sm" and a == "base"}
            par = {t: r["train_s"] for (k, a, t), r in txt.items() if k == "sm" and a == "new"}
        row_seq = [secs(seq[t]) if t in seq else DASH for t in THREADS]
        row_par = [secs(par[t]) if t in par else DASH for t in THREADS]
        row_spd = [f"{seq[t] / par[t]:.2f}$\\times$" if t in seq and t in par else DASH for t in THREADS]
        lines += [f"{name} ($P{{=}}{p}$) & {SEQ} & " + " & ".join(row_seq) + r" \\",
                  f" & {PAR} & " + " & ".join(row_par) + r" \\",
                  r" & speedup & " + " & ".join(row_spd) + r" \\"]
        if key != DATASETS[-1][0]:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def distributed_table():
    txt = parse_txt()
    ts = sorted({t for (k, _, t) in txt if k == "dist"})
    arms = (("base", DSEQ, r"\texttt{std::sort}"), ("new_stdsort", DPAR, r"\texttt{std::sort}"), ("new", DPAR, "VQSort"))
    lines = [HDR,
             "% mean worker-side FindSplits call (ms): " + "; ".join(
                 f"{a}@T{t} {txt[('dist', a, t)]['findsplits_ms']:.1f}" for a, _, _ in arms for t in ts),
             r"\begin{tabular}{ll" + "r" * len(ts) + "}", r"\toprule",
             "Arm & Sort & " + " & ".join(f"$T{{=}}{t}$" for t in ts) + r" \\", r"\midrule"]
    for a, name, sort in arms:
        cells = []
        for t in ts:
            v, ref = txt[("dist", a, t)]["train_s"], txt[("dist", "base", t)]["train_s"]
            cells.append(f"{secs(v)} ({ref / v:.1f}$\\times$)")
        lines.append(f"{name} & {sort} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default=str(OUT)); args = ap.parse_args()
    out = pathlib.Path(args.out); out.mkdir(parents=True, exist_ok=True)
    for name, fn in (("table_in_node_threads_body.tex", threads_table), ("table_in_node_distributed_body.tex", distributed_table)):
        (out / name).write_text(fn()); print("wrote", out / name)
