#!/usr/bin/env python3
"""Vertex AI barrier grid -> LaTeX tabular body (tree-training seconds, test accuracy) per dataset x arm x W.

Reads every <results>/vertex/<RUN_ID>_<dataset>/<arm>_w<W>/eval.json; arms: aa, spo, and spo-innode (image tag
contains INNODE_TAG). Emits the tabular body only (the table* environment and caption live in main.tex).
Usage: make_vertex_hm4_table.py [--out BODY.tex] [--md]
"""
import argparse, glob, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "../../results/runtime/distributed_spo_gbt/barriers/vertex")
INNODE_TAG = "4df36453"           # wheel built from time-barriers-innode (in-node SPO parallelism + VQSort)
MACHINE = "n2-highmem-4"
W_LIST = [1, 2, 4, 8, 16]
DATASETS = [("epsilon", "Epsilon"), ("higgs", "HIGGS"), ("susy", "SUSY"), ("youtube8m", "YouTube-8M")]
ARMS = [("aa", "AA"), ("spo", "SPO"), ("spo-innode", "SPO in-node")]


def load():
    cells = {}
    for p in glob.glob(os.path.join(RESULTS, "*", "*", "eval.json")):
        e = json.load(open(p))
        if e.get("machine_type") != MACHINE or e.get("trees") != 50:
            continue
        arm = e["arm"] + ("-innode" if INNODE_TAG in e.get("image", "") else "")
        key = (e["dataset"], arm, e["workers"])
        if key in cells and cells[key]["run"] > os.path.basename(os.path.dirname(os.path.dirname(p))):
            continue  # keep the newest run per cell
        cells[key] = dict(run=os.path.basename(os.path.dirname(os.path.dirname(p))), t=e["tree_training_s"],
                          setup=e["setup_s"], acc=e.get("accuracy"), p=e.get("projections_per_worker"))
    return cells


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=None); ap.add_argument("--md", action="store_true")
    a = ap.parse_args(); cells = load()
    lines = ["% auto-generated by benchmarks/src/distributed_spo_gbt/make_vertex_hm4_table.py -- regenerate, do not hand-edit",
             r"\begin{tabular}{ll|" + "r" * len(W_LIST) + "|r}", r"\toprule",
             "Dataset & Arm & " + " & ".join(f"$W={w}$" for w in W_LIST) + r" & Acc. \\", r"\midrule"]
    md = ["| dataset | arm | " + " | ".join(f"W={w}" for w in W_LIST) + " | acc |", "|---" * (len(W_LIST) + 3) + "|"]
    for ds, dsname in DATASETS:
        first = True
        for arm, armname in ARMS:
            row = [cells.get((ds, arm, w)) for w in W_LIST]
            if not any(row):
                continue
            accs = [c["acc"] for c in row if c and c["acc"] is not None]
            acc = f"{min(accs):.3f}" if accs and max(accs) - min(accs) < 0.0015 else (f"{min(accs):.3f}--{max(accs):.3f}" if accs else "")
            tex = [f"{c['t']:.0f}" if c else "--" for c in row]
            lines.append(f"{dsname if first else ''} & {armname} & " + " & ".join(tex) + f" & {acc} \\\\")
            md.append(f"| {dsname if first else ''} | {armname} | " + " | ".join(tex) + f" | {acc} |")
            first = False
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"; lines.append(r"\end{tabular}")
    body = "\n".join(lines) + "\n"
    if a.out:
        open(a.out, "w").write(body); print("wrote", a.out, file=sys.stderr)
    else:
        print(body)
    if a.md:
        print("\n".join(md))


if __name__ == "__main__":
    main()
