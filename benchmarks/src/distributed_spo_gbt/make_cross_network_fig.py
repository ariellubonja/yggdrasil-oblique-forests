#!/usr/bin/env python3
"""KDD27 cross-network projections figure: pgfplots body + .dat files (caption/label live in main.tex).

(a) cross-network speedup (in-worker time / cross-network time) vs rows x features, log-log;
(b) cross-network tree-training time split into in-worker time, communication wait and other extra,
    for the 8 datasets with the lowest speedup; (c) test accuracy, cross-network vs in-worker.
  python make_cross_network_fig.py [results.csv] [paper_dir]
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    HERE, "../../results/runtime/distributed_spo_gbt/naive_column_shipping/vertex_hm4_20261029/results.csv")
PAPER = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "../../../paper/distributed_spo_gbt_kdd27")
REL = "figures/evaluation/cross_network"
os.makedirs(os.path.join(PAPER, REL), exist_ok=True)

by = {}
for r in csv.DictReader(open(SRC)):
    by.setdefault(r["dataset"], {})[r["arm"]] = r
rows = []
for name, v in by.items():
    a, b = v["in_worker"], v["cross_network"]
    ta, tb, wait = float(a["tree_training_s"]), float(b["tree_training_s"]), float(b["ship_s_max"])
    rows.append(dict(name=name, cells=int(a["rows_train"]) * int(a["features"]), ta=ta, tb=tb, wait=wait,
                     other=max(0.0, tb - ta - wait), sp=ta / tb,
                     acca=float(a["test_acc"]), accb=float(b["test_acc"])))


def write(fname, header, lines):
    with open(os.path.join(PAPER, REL, fname), "w") as f:
        f.write(header + "\n" + "\n".join(lines) + "\n")


write("speedup.dat", "cells speedup", [f"{r['cells']} {r['sp']:.4f}" for r in sorted(rows, key=lambda r: r["cells"])])
write("accuracy.dat", "inworker crossnet", [f"{r['acca']:.4f} {r['accb']:.4f}" for r in rows])
slow = sorted(rows, key=lambda r: r["sp"])[:8][::-1]  # lowest speedup at the top
write("breakdown.dat", "idx inworker wait other",
      [f"{i} {r['ta']:.2f} {r['wait']:.2f} {r['other']:.2f}" for i, r in enumerate(slow)])
labels = ",".join("{" + r["name"].replace("_", r"\_") + "}" for r in slow)

BLUE, ORANGE = "{rgb,255:red,55;green,138;blue,221}", "{rgb,255:red,216;green,90;blue,48}"
body = rf"""% auto-generated by benchmarks/src/distributed_spo_gbt/make_cross_network_fig.py -- regenerate, do not hand-edit
\begin{{tikzpicture}}
\begin{{groupplot}}[group style={{group size=3 by 1, horizontal sep=2.2cm}},
  width=0.30\textwidth, height=4.6cm, tick label style={{font=\footnotesize}}, label style={{font=\footnotesize}},
  tick style={{draw=none}}, grid style={{gray!25}}, axis line style={{gray!70}}]
\nextgroupplot[xmode=log, ymode=log, xmin=1e2, xmax=1e7, ymin=0.25, ymax=1.15, ytick={{0.25,0.5,0.75,1}},
  yticklabels={{0.25$\times$,0.5$\times$,0.75$\times$,1$\times$}}, ymajorgrids, xmajorgrids,
  xlabel={{rows $\times$ features}}, ylabel={{cross-network speedup}}, title={{(a)}}, title style={{font=\footnotesize}}]
\addplot[gray!80, dashed, forget plot] coordinates {{(1e2,1) (1e7,1)}};
\addplot[only marks, mark=*, mark size=1.3pt, color={BLUE}] table[x=cells, y=speedup] {{{REL}/speedup.dat}};
\nextgroupplot[xbar stacked, bar width=6pt, xmin=0, ytick=data, yticklabels={{{labels}}},
  y tick label style={{font=\scriptsize}}, xmajorgrids, enlarge y limits=0.08,
  xlabel={{cross-network time (s)}}, title={{(b)}}, title style={{font=\footnotesize}},
  legend style={{font=\scriptsize, at={{(0.98,0.02)}}, anchor=south east, draw=none, fill=white, fill opacity=0.8, text opacity=1}},
  legend cell align=left, reverse legend]
\addplot[fill={BLUE}, draw=none] table[x=inworker, y=idx] {{{REL}/breakdown.dat}};
\addplot[fill={ORANGE}, draw=none] table[x=wait, y=idx] {{{REL}/breakdown.dat}};
\addplot[fill=gray!40, draw=none] table[x=other, y=idx] {{{REL}/breakdown.dat}};
\legend{{in-worker time, communication wait, other}}
\nextgroupplot[xmin=0.1, xmax=1.02, ymin=0.1, ymax=1.02, xmajorgrids, ymajorgrids,
  xlabel={{in-worker accuracy}}, ylabel={{cross-network accuracy}}, title={{(c)}}, title style={{font=\footnotesize}}]
\addplot[gray!80, dashed, forget plot] coordinates {{(0.1,0.1) (1.02,1.02)}};
\addplot[only marks, mark=*, mark size=1.3pt, color={BLUE}] table[x=inworker, y=crossnet] {{{REL}/accuracy.dat}};
\end{{groupplot}}
\end{{tikzpicture}}
"""
open(os.path.join(PAPER, "figures/evaluation/fig_cross_network_body.tex"), "w").write(body)
print("wrote", os.path.join(PAPER, "figures/evaluation/fig_cross_network_body.tex"), "+ 3 .dat;",
      "speedup range", round(min(r["sp"] for r in rows), 3), round(max(r["sp"] for r in rows), 3))
