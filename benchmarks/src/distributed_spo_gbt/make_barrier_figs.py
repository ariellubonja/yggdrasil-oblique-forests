"""Barrier-timing figure (YouTube-8M, W=16, Vertex n2-highmem-4) from the manager's barriers.csv.
Usage (repo root): python benchmarks/src/distributed_spo_gbt/make_barrier_figs.py
Writes .dat files + two pgfplots bodies under paper/distributed_spo_gbt_kdd27/figures/evaluation/grcp_n2/.
"""
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
RUN = ROOT / "benchmarks/results/runtime/distributed_spo_gbt/barriers/vertex/p_F/pfhm4bar20261025_youtube8m"
OUT = ROOT / "paper/distributed_spo_gbt_kdd27/figures/evaluation/grcp_n2"
TEXDIR = "figures/evaluation/grcp_n2/yt8m_barriers"  # path as seen from main.tex
HDR = "% auto-generated by benchmarks/src/distributed_spo_gbt/make_barrier_figs.py -- regenerate, do not hand-edit\n"
ARMS = [("AA", "aa_w16"), ("SPO", "spo_w16")]
TREE = 1  # SPO tree shown in the swimlane panel
RGB = {"ytFS": (31, 56, 100), "ytES": (55, 138, 221), "ytSS": (29, 158, 117), "ytSE": (186, 117, 23),
       "ytCK": (127, 119, 221), "ytMW": (216, 90, 48), "ytWT": (242, 193, 78)}  # navy FindSplits, gold waiting
COLORDEFS = "".join(rf"\definecolor{{{k}}}{{RGB}}{{{r},{g},{b}}}" + "\n" for k, (r, g, b) in RGB.items())
COL = {"FindSplits": "ytFS", "EvaluateSplits": "ytES", "ShareSplits": "ytSS", "StartNewIter": "ytSE", "EndIter": "ytSE",
       "CreateCheckpoint": "ytCK", "comm": "ytMW", "wait": "ytWT"}
SEGS = [("fs_compute", "FindSplits compute (median worker)", COL["FindSplits"]),
        ("straggler", "Straggler wait (slowest $-$ median)", COL["wait"]),
        ("evalsplits", "EvaluateSplits", COL["EvaluateSplits"]),
        ("sharesplits", "ShareSplits", COL["ShareSplits"]),
        ("startend_ckpt", "Tree start/end + checkpoints", COL["StartNewIter"]),
        ("mgrcomm", "Manager--worker comm.", COL["comm"])]
LANES = [("Manager", 3), ("Slowest wkr.", 2), ("Median wkr.", 1), ("Fastest wkr.", 0)]
AXSTYLE = r"tick label style={font=\scriptsize}, label style={font=\scriptsize}, tick style={draw=none}"


def load(sub):
    d = pd.read_csv(RUN / sub / "barriers.csv")
    return d[d.iter >= 0]


def budget(d):
    fs, wmax = d[d.stage == "FindSplits"], lambda st: d[d.stage == st].worker_max_s.sum()
    return {"fs_compute": fs.worker_med_s.sum(), "straggler": (fs.worker_max_s - fs.worker_med_s).sum(),
            "evalsplits": wmax("EvaluateSplits"), "sharesplits": wmax("ShareSplits"),
            "startend_ckpt": d[d.stage.isin(["StartNewIter", "EndIter", "CreateCheckpoint"])].barrier_s.sum(),
            "mgrcomm": (d.fanout_s + d.comm_residual_s).sum()}


def budget_body(tot):
    pct = tot.div(tot.sum(axis=1), axis=0) * 100
    lines = [HDR, COLORDEFS + r"\begin{tikzpicture}",
             r"\begin{axis}[width=\linewidth, height=5.4cm, xbar stacked, bar width=0.8cm, symbolic y coords={SPO,AA}, ytick={SPO,AA},",
             r"  yticklabels={SPO-GBT,AA-GBT}, enlarge y limits=0.5, xmin=0, xmax=100, xlabel={Share of summed wall time (\%)},",
             "  " + AXSTYLE + r", xmajorgrids, major grid style={gray!25}, axis on top=false,",
             r"  legend style={font=\scriptsize, at={(0.5,-0.3)}, anchor=north, draw=none, legend columns=2, /tikz/every even column/.append style={column sep=0.6em}},",
             r"  legend cell align=left, area legend, clip=false]"]
    for col, name, color in SEGS:
        lines.append(rf"\addplot[draw=none, fill={color}] table[y=arm, x={col}_pct] {{{TEXDIR}/budget.dat}};")
        lines.append(rf"\addlegendentry{{{name}}}")
    for arm, r in tot.iterrows():
        lines.append(rf"\node[anchor=west, font=\scriptsize, inner sep=2pt] at (axis cs:100,{arm}) {{{r.sum():.0f}\,s}};")
    return "\n".join(lines + [r"\end{axis}", r"\end{tikzpicture}", ""]), pct


def lane_rects(d, x0=None, x1=None):
    out, h = [], 0.36
    box = lambda c, a, b, y, pat=False: (rf"\fill[pattern=north east lines, pattern color={c}]" if pat else rf"\fill[{c}]") + \
        f" (axis cs:{a:.6f},{y - h}) rectangle (axis cs:{b:.6f},{y + h});"
    for _, r in d.iterrows():
        end = r.t + r.barrier_s
        if x0 is not None and (end < x0 or r.t > x1):
            continue
        c = COL.get(r.stage, "gray")
        out.append(box(c, r.t, end, 3))
        for y, w in ((2, r.worker_max_s), (1, r.worker_med_s), (0, r.worker_min_s)):
            s, e = r.t + r.fanout_s, r.t + r.fanout_s + w
            out.append(box(c, s, e, y))
            if end > e:
                out.append(box(COL["wait"], e, end, y, pat=True))
    return out


def swimlane_body(d):
    fs = d.index[d.stage == "FindSplits"]
    z0 = 0.0  # zoom = whole level 0, so the wait bars keep their true proportion
    z1 = d.t[fs[1]] + 0.02
    tend = d.t.iloc[-1] + d.barrier_s.iloc[-1]
    ylab = ", ".join(n for n, _ in LANES[::-1])
    common = (rf"ymin=-0.6, ymax=3.6, ytick={{0,1,2,3}}, yticklabels={{{ylab}}}, " + AXSTYLE +
              r", axis on top, clip=true")
    lines = [HDR, COLORDEFS + r"\begin{tikzpicture}",
             r"\begin{groupplot}[group style={group size=1 by 2, vertical sep=1.05cm}, width=\linewidth, height=3.3cm, " + common + "]",
             rf"\nextgroupplot[xmin=0, xmax={tend:.4f}, xlabel={{Wall time since tree start (s)}}, xlabel shift=-3pt]"]
    lines += lane_rects(d)
    lines.append(rf"\fill[black, opacity=0.18] (axis cs:{z0:.6f},-0.6) rectangle (axis cs:{z1:.6f},3.6);")
    lines.append(rf"\nextgroupplot[xmin={z0:.6f}, xmax={z1:.6f}, xlabel={{Zoom on tree level 0 (s)}}, xlabel shift=-3pt,"
                 r" xticklabel style={/pgf/number format/fixed, /pgf/number format/precision=1},"
                 r" legend style={font=\scriptsize, at={(0.5,-0.55)}, anchor=north, draw=none, legend columns=3,"
                 r" /tikz/every even column/.append style={column sep=0.5em}}, legend cell align=left]")
    for name, key in (("FindSplits", "FindSplits"), ("EvaluateSplits", "EvaluateSplits"), ("ShareSplits", "ShareSplits"),
                      ("Tree start/end", "StartNewIter")):
        lines.append(rf"\addlegendimage{{area legend, draw=none, fill={COL[key]}}}\addlegendentry{{{name}}}")
    lines.append(rf"\addlegendimage{{area legend, draw=none, pattern=north east lines, pattern color={COL['wait']}}}"
                 r"\addlegendentry{Waiting at barrier}")
    lines += lane_rects(d, z0, z1)
    return "\n".join(lines + [r"\end{groupplot}", r"\end{tikzpicture}", ""]), (z0, z1)


def main():
    (OUT / "yt8m_barriers").mkdir(parents=True, exist_ok=True)
    tot = pd.DataFrame({arm: budget(load(sub)) for arm, sub in ARMS}).T[[c for c, _, _ in SEGS]]
    body, pct = budget_body(tot)
    dat = pd.concat([tot, pct.add_suffix("_pct")], axis=1).rename_axis("arm").reset_index()
    (OUT / "yt8m_barriers/budget.dat").write_text(HDR + dat.to_string(index=False, float_format="%.4f") + "\n")
    (OUT / "fig_yt8m_barriers_budget_body.tex").write_text(body)
    print(tot.assign(total=tot.sum(axis=1)).round(3).to_string())
    d = load("spo_w16").query("iter == @TREE").copy()
    d["t"] = d.t_begin_s - d.t_begin_s.iloc[0]
    cols = ["t", "stage", "layer", "barrier_s", "fanout_s", "worker_max_s", "worker_med_s", "worker_min_s"]
    (OUT / "yt8m_barriers/swimlane_spo_tree1.dat").write_text(HDR + d[cols].to_string(index=False, float_format="%.6f") + "\n")
    body, (z0, z1) = swimlane_body(d.reset_index(drop=True))
    (OUT / "fig_yt8m_barriers_swimlane_body.tex").write_text(body)
    print(f"zoom window {z0:.4f}-{z1:.4f} s")


if __name__ == "__main__":
    main()
