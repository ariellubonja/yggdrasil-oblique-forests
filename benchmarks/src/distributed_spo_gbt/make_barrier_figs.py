"""Barrier-timing figure (YouTube-8M, W=16, Vertex n2-highmem-4) from the manager's barriers.csv.
Usage (repo root): python benchmarks/src/distributed_spo_gbt/make_barrier_figs.py
Writes .dat files + two pgfplots bodies under paper/distributed_spo_gbt_kdd27/figures/evaluation/grcp_n2/.
"""
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
RUN = ROOT / "benchmarks/results/runtime/distributed_spo_gbt/barriers/vertex/p_F/pfhm4bar20261025_youtube8m"
OUT = ROOT / "paper/distributed_spo_gbt_kdd27/figures/evaluation/grcp_n2"
TEXDIR = "figures/evaluation/grcp_n2/yt8m_barriers"  # path as seen from main.tex
HDR = "% auto-generated by benchmarks/src/distributed_spo_gbt/make_barrier_figs.py -- regenerate, do not hand-edit\n"
ARMS = [("AA", "aa_w16"), ("SPO", "spo_w16")]
SEGS = [("findsplits", "FindSplits compute", "{rgb,255:red,140;green,150;blue,165}"),
        ("evalsplits", "EvaluateSplits compute", "{rgb,255:red,55;green,138;blue,221}"),
        ("sharesplits", "ShareSplits (worker--worker comm.)", "{rgb,255:red,29;green,158;blue,117}"),
        ("startend", "Tree start/end", "{rgb,255:red,186;green,117;blue,23}"),
        ("checkpoint", "Checkpoints", "{rgb,255:red,127;green,119;blue,221}"),
        ("mgrcomm", "Manager--worker comm.", "{rgb,255:red,216;green,90;blue,48}")]
ARM_STYLE = {"AA": ("{rgb,255:red,216;green,90;blue,48}", "diamond*"), "SPO": ("{rgb,255:red,55;green,138;blue,221}", "*")}


def load(sub):
    d = pd.read_csv(RUN / sub / "barriers.csv")
    return d[d.iter >= 0]


def totals(d):
    wmax = lambda *st: d[d.stage.isin(st)].worker_max_s.sum()
    return {"findsplits": wmax("FindSplits"), "evalsplits": wmax("EvaluateSplits"),
            "sharesplits": wmax("ShareSplits"), "startend": wmax("StartNewIter", "EndIter"),
            "checkpoint": d[d.stage == "CreateCheckpoint"].barrier_s.sum(),
            "mgrcomm": (d.fanout_s + d.comm_residual_s).sum()}


def layers(d):
    fs = d[d.stage == "FindSplits"]
    g = fs.groupby("layer")
    out = g[["worker_min_s", "worker_med_s", "worker_max_s"]].mean()
    out["idle_pct"] = 100 * g.idle_s.sum() / (fs.num_replies * fs.worker_max_s).groupby(fs.layer).sum()
    return out.reset_index()


def totals_body(tot):
    lines = [HDR, r"\begin{tikzpicture}",
             r"\begin{axis}[width=\linewidth, height=5.2cm, ybar stacked, bar width=0.9cm, symbolic x coords={AA,SPO}, xtick=data,",
             r"  xticklabels={AA-GBT,SPO-GBT}, enlarge x limits=0.5, ymin=0, ymax=" + f"{1.4 * tot.sum(axis=1).max():.0f}" + r", ylabel={Time summed over 10 trees (s)},",
             r"  tick label style={font=\footnotesize}, label style={font=\footnotesize}, tick style={draw=none},",
             r"  legend style={font=\scriptsize, at={(0.5,-0.14)}, anchor=north, draw=none, legend columns=2, /tikz/every even column/.append style={column sep=0.6em}},",
             r"  legend cell align=left, clip=false]"]
    for col, name, color in SEGS:
        lines.append(rf"\addplot[draw=none, fill={color}] table[x=arm, y={col}] {{{TEXDIR}/totals.dat}};")
        lines.append(rf"\addlegendentry{{{name}}}")
    for arm, r in tot.iterrows():
        rest = r.drop("findsplits").sum()
        lines.append(rf"\node[anchor=south, font=\scriptsize, align=center, inner sep=1pt] at (axis cs:{arm},{r.sum():.2f})"
                     rf" {{total {r.sum():.1f}\,s\\non-FindSplits {rest:.2f}\,s\\mgr--worker comm.\ {r.mgrcomm:.2f}\,s}};")
    return "\n".join(lines + [r"\end{axis}", r"\end{tikzpicture}", ""])


def layers_body(ymax):
    lines = [HDR, r"\begin{tikzpicture}",
             r"\begin{axis}[width=\linewidth, height=6.3cm, xmin=-0.5, xmax=4.5, xtick={0,...,4}, ymin=0, ymax=" + f"{ymax:.0f}," + "",
             r"  xlabel={Tree level}, ylabel={FindSplits time per call (s)},",
             r"  tick label style={font=\footnotesize}, label style={font=\footnotesize}, tick style={draw=none},",
             r"  legend style={font=\scriptsize, at={(0.02,0.98)}, anchor=north west, draw=none}, legend cell align=left]"]
    for k, (arm, _) in enumerate(ARMS):
        color, mark = ARM_STYLE[arm]
        dx = -0.18 if k == 0 else 0.18
        f = f"{TEXDIR}/findsplits_{arm.lower()}.dat"
        mk = rf"mark={mark}, mark size=1.8pt, mark options={{fill=white, draw=black, line width=0.4pt}}"
        lines += [rf"\addplot[color={color}, only marks, {mk}, legend image code/.code={{\draw[line width=4pt, color={color}]"
                  rf" (0.15cm,-0.13cm) -- (0.15cm,0.13cm); \draw plot[only marks, {mk}] coordinates {{(0.15cm,0cm)}};}},",
                  r"  error bars/.cd, y dir=both, y explicit, error mark=none, error bar style={line width=4pt, color=" + color + "}]",
                  rf"  table[x expr=\thisrow{{layer}}{dx:+.2f}, y=med_s, y error plus expr=\thisrow{{max_s}}-\thisrow{{med_s}},"
                  rf" y error minus expr=\thisrow{{med_s}}-\thisrow{{min_s}}] {{{f}}};",
                  rf"\addlegendentry{{{arm}-GBT}}",
                  rf"\addplot[draw=none, forget plot, nodes near coords={{\pgfmathprintnumber[fixed, precision=1]{{\pgfplotspointmeta}}}},"
                  r" nodes near coords style={font=\tiny, anchor=south, inner sep=1.5pt}, point meta=explicit]",
                  rf"  table[x expr=\thisrow{{layer}}{dx:+.2f}, y=max_s, meta=idle_pct] {{{f}}};"]
    return "\n".join(lines + [r"\end{axis}", r"\end{tikzpicture}", ""])


def main():
    (OUT / "yt8m_barriers").mkdir(parents=True, exist_ok=True)
    tot = pd.DataFrame({arm: totals(load(sub)) for arm, sub in ARMS}).T[[c for c, _, _ in SEGS]]
    (OUT / "yt8m_barriers/totals.dat").write_text(HDR + tot.rename_axis("arm").reset_index().to_string(index=False, float_format="%.4f") + "\n")
    ymax = 0
    for arm, sub in ARMS:
        lay = layers(load(sub)).rename(columns={"worker_min_s": "min_s", "worker_med_s": "med_s", "worker_max_s": "max_s"})
        (OUT / f"yt8m_barriers/findsplits_{arm.lower()}.dat").write_text(HDR + lay.to_string(index=False, float_format="%.4f") + "\n")
        ymax = max(ymax, 1.2 * lay.max_s.max())
        print(arm, "\n", lay.round(3).to_string(index=False))
    print(tot.round(3).to_string())
    (OUT / "fig_yt8m_barriers_totals_body.tex").write_text(totals_body(tot))
    (OUT / "fig_yt8m_barriers_layers_body.tex").write_text(layers_body(ymax))


if __name__ == "__main__":
    main()
