#!/usr/bin/env python3
"""Emit tabular BODIES for the P=F, W=1, 10-tree Vertex probe (n2-highmem-16): the in-node ablation
table and the setup-cost table. Captions/labels live in main.tex. Reads barriers/vertex/*/*/eval.json."""
import glob, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "../../results/runtime/distributed_spo_gbt/barriers/vertex")
OUT = os.path.join(HERE, "../../../paper/distributed_spo_gbt_kdd27/tables")
HDR = "% auto-generated by benchmarks/src/distributed_spo_gbt/make_pf_ablation_tables.py -- regenerate, do not hand-edit\n"
DATASETS = [("susy", "SUSY"), ("higgs", "HIGGS"), ("epsilon", "Epsilon"), ("youtube8m", "YouTube-8M")]
# probe arms: run-dir prefix -> row label; all SPO rows use the same P=F cells, models byte-identical
ARMS = [("pfw1base", "SPO baseline"), ("pfw1vqsort", "SPO + VQSort only"),
        ("pfw1parstd", "SPO + chunk jobs only (\\texttt{std::sort})"), ("pfw1innode", "SPO + both (in-node)")]


def load():
    cells = []
    for p in glob.glob(os.path.join(RESULTS, "*", "*", "*", "eval.json")):  # p_F/ (pfw1*) and p_sqrtF/ (hm4 50-tree setup cost)
        e = json.load(open(p)); e["run"] = p.split(os.sep)[-3]; cells.append(e)
    return cells


def ablation(cells):
    def get(prefix, arm, d):
        m = [c for c in cells if c["run"].startswith(prefix) and c["arm"] == arm and c["dataset"] == d and c["workers"] == 1]
        return m[0] if m else None
    ds = [d for d in DATASETS if get("pfw1base", "spo", d[0])]
    base = [get("pfw1base", "spo", d) for d, _ in ds]
    aa = [get("pfw1base", "aa", d) for d, _ in ds]
    L = [HDR, r"\begin{tabular}{l" + "r" * len(ds) + "}", r"\toprule",
         "Arm & " + " & ".join(f"{n} ($F{{=}}{b['cols']}$)" for (d, n), b in zip(ds, base)) + r" \\", r"\midrule",
         "AA GBT & " + " & ".join(f"{c['tree_training_s']:.0f}" if c else "--" for c in aa) + r" \\"]
    for prefix, name in ARMS:
        row = []
        for b, (d, _) in zip(base, ds):
            c = get(prefix, "spo", d)
            if not c:
                row.append("--")
            elif prefix == "pfw1base":
                row.append(f"{c['tree_training_s']:.0f}")
            else:
                row.append(f"{c['tree_training_s']:.0f} ({b['tree_training_s'] / c['tree_training_s']:.1f}$\\times$)")
        L.append(f"{name} & " + " & ".join(row) + r" \\")
    L += [r"\midrule", "Acc.\\ SPO / AA & " + " & ".join(
        f"{b['accuracy']:.4f} / {a['accuracy']:.4f}" if a and b else "--" for a, b in zip(aa, base)) + r" \\",
        r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


def setup_cost(cells):
    def rng(v):
        v = sorted(v)
        if not v: return "--"
        return f"{v[0]:.0f}" if v[-1] - v[0] < 1 else f"{v[0]:.0f}--{v[-1]:.0f}"
    L = [HDR, r"\begin{tabular}{lrrr}", r"\toprule",
         r"Dataset & Rows $\times$ cols & \multicolumn{1}{c}{\texttt{n2-highmem-4}} & \multicolumn{1}{c}{\texttt{n2-highmem-16}} \\", r"\midrule"]
    for d, n in DATASETS:
        cs = [c for c in cells if c["dataset"] == d]
        if not cs: continue
        hm4 = [c["setup_s"] for c in cs if c["machine_type"] == "n2-highmem-4" and c["trees"] == 50]
        hm16 = [c["setup_s"] for c in cs if c["machine_type"] == "n2-highmem-16"]
        L.append(f"{n} & {cs[0]['rows'] / 1e6:.1f}M $\\times$ {cs[0]['cols']} & {rng(hm4)} & {rng(hm16)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    cells = load()
    for name, body in [("table_in_node_ablation_body.tex", ablation(cells)), ("table_setup_cost_body.tex", setup_cost(cells))]:
        open(os.path.join(OUT, name), "w").write(body); print("wrote", name, file=sys.stderr); print(body)
