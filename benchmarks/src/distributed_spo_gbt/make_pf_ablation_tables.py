#!/usr/bin/env python3
"""Emit tabular BODIES for the P=F, W=1, 10-tree Vertex probe (n2-highmem-16): the in-node ablation
table and the setup-cost table. Captions/labels live in main.tex. Each table reads only the eval.json cells listed
in its float's inputs.txt (benchmarks/results/kdd28/appendix/<float>/inputs.txt).
Usage: make_pf_ablation_tables.py [--out DIR] [--profile NAME] [--ablation_inputs F] [--setup_inputs F]
  (default DIR: the paper's tables/)"""
import argparse, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "params"))
import params as kdd28  # noqa: E402  (params/kdd28_params.json)
ABLATION_INPUTS = kdd28.results_path("appendix/tab-in-node-dist-vqsort-ablation/inputs.txt")
SETUP_INPUTS = kdd28.results_path("appendix/tab-setup-cost/inputs.txt")
OUT = os.path.join(HERE, "../../../paper/distributed_spo_gbt_kdd28/tables")
HDR = "% auto-generated by benchmarks/src/distributed_spo_gbt/make_pf_ablation_tables.py -- regenerate, do not hand-edit\n"
DATASETS = [("susy", "SUSY"), ("higgs", "HIGGS"), ("epsilon", "Epsilon"), ("youtube8m", "YouTube-8M")]
# probe arms: run-dir prefix -> row label; all SPO rows use the same P=F cells, models byte-identical
ARMS = [("pfw1base", "SPO baseline"), ("pfw1vqsort", "SPO + VQSort only"),
        ("pfw1parstd", "SPO + chunk jobs only (\\texttt{std::sort})"), ("pfw1innode", "SPO + both (in-node)")]


def load(inputs):
    """eval.json cells named in an inputs.txt (other listed files, e.g. launcher logs, are skipped)."""
    cells = []
    for p in kdd28.float_inputs(inputs):
        if os.path.basename(p) == "eval.json":
            e = json.load(open(p)); e["run"] = p.split(os.sep)[-3]; cells.append(e)
    if not cells:
        sys.exit(f"ERROR {inputs}: lists no eval.json")
    return cells


def ablation(cells):
    def get(prefix, arm, d):
        m = [c for c in cells if c["run"].startswith(prefix) and c["arm"] == arm and c["dataset"] == d and c["workers"] == 1]
        return m[0] if m else None
    ds = [d for d in DATASETS if get("pfw1base", "spo", d[0])]
    base = [get("pfw1base", "spo", d) for d, _ in ds]
    aa = [get("pfw1base", "aa", d) for d, _ in ds]
    L = [HDR, r"\begin{tabular}{l" + "r" * len(ds) + "}", r"\toprule",
         "Arm & " + " & ".join(f"{n} ($F{{=}}{b['cols']}$)" for (d, n), b in zip(ds, base)) + r" \\", r"\midrule",
         "AA GBT & " + " & ".join(f"{c['tree_training_s']:.0f}" if c else "--" for c in aa) + r" \\"]
    for prefix, name in ARMS:
        row = []
        for b, (d, _) in zip(base, ds):
            c = get(prefix, "spo", d)
            if not c:
                row.append("--")
            elif prefix == "pfw1base":
                row.append(f"{c['tree_training_s']:.0f}")
            else:
                row.append(f"{c['tree_training_s']:.0f} ({b['tree_training_s'] / c['tree_training_s']:.1f}$\\times$)")
        L.append(f"{name} & " + " & ".join(row) + r" \\")
    L += [r"\midrule", "Acc.\\ SPO / AA & " + " & ".join(
        f"{b['accuracy']:.4f} / {a['accuracy']:.4f}" if a and b else "--" for a, b in zip(aa, base)) + r" \\",
        r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


def setup_cost(cells):
    def rng(v):
        v = sorted(v)
        if not v: return "--"
        return f"{v[0]:.0f}" if v[-1] - v[0] < 1 else f"{v[0]:.0f}--{v[-1]:.0f}"
    L = [HDR, r"\begin{tabular}{lrrr}", r"\toprule",
         r"Dataset & Rows $\times$ cols & \multicolumn{1}{c}{\texttt{n2-highmem-4}} & \multicolumn{1}{c}{\texttt{n2-highmem-16}} \\", r"\midrule"]
    for d, n in DATASETS:
        cs = [c for c in cells if c["dataset"] == d]
        if not cs: continue
        hm4 = [c["setup_s"] for c in cs if c["machine_type"] == "n2-highmem-4"]
        hm16 = [c["setup_s"] for c in cs if c["machine_type"] == "n2-highmem-16"]
        L.append(f"{n} & {cs[0]['rows'] / 1e6:.1f}M $\\times$ {cs[0]['cols']} & {rng(hm4)} & {rng(hm16)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


def ablation_cells(cells):
    return [c for c in cells if c["run"].startswith(tuple(p for p, _ in ARMS)) and c["workers"] == 1
            and c["dataset"] in dict(DATASETS)]


def setup_cells(cells):
    return [c for c in cells if c["dataset"] in dict(DATASETS) and c.get("machine_type") in ("n2-highmem-4", "n2-highmem-16")]


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=OUT, help="directory for the two bodies (default: the paper's tables/)")
    ap.add_argument("--ablation_inputs", default=ABLATION_INPUTS, help="inputs.txt of tab:in-node-dist-vqsort-ablation")
    ap.add_argument("--setup_inputs", default=SETUP_INPUTS, help="inputs.txt of tab:setup-cost")
    kdd28.add_profile_arg(ap, __file__)
    a = ap.parse_args()
    abl, setup_c = ablation_cells(load(a.ablation_inputs)), setup_cells(load(a.setup_inputs))
    kdd28.check_evals(abl, a.profile, "ablation pfw1* eval.json")
    kdd28.check_evals(setup_c, a.profile, "setup-cost eval.json")
    setup = kdd28.setup_line(a.profile, ["aa"])
    for name, body in [("table_in_node_ablation_body.tex", ablation(abl)), ("table_setup_cost_body.tex", setup_cost(setup_c))]:
        body = kdd28.add_setup(body, setup)
        open(os.path.join(a.out, name), "w").write(body); print("wrote", name, file=sys.stderr); print(body)
