#!/usr/bin/env python3
"""Emit the KDD27 column-replication table BODY (tabular only; caption/label live in main.tex).
Per replication level r: mean test accuracy over datasets (of per-dataset seed means), delta vs r=0
in points, wins/ties/losses vs r=0, mean rank. Same definitions as column_replication/summarize_replication.py.
A bold last row gives single-machine SPO-GBT (same hyperparameters, single_machine_spo_gbt.csv), not ranked."""
import csv, pathlib, sys
from collections import defaultdict
from statistics import mean

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "benchmarks/results/accuracy/distributed_spo_gbt/column_replication_vertex"
OUT = ROOT / "paper/distributed_spo_gbt_kdd27/tables/table_column_replication_body.tex"
EPS = 1e-9
DASH = r"\multicolumn{1}{c}{---}"


def pooled(path):
    """replication -> (n_datasets, acc_mean, gain_pts, wins, ties, losses, mean_rank)."""
    acc = defaultdict(list)
    for r in csv.DictReader(open(path)):
        if r["rc"] == "0" and r["test_acc"]:
            acc[(r["dataset"], float(r["replication"]))].append(float(r["test_acc"]))
    m = {k: mean(v) for k, v in acc.items()}
    datasets = sorted({d for d, _ in acc})
    levels = sorted({l for _, l in acc})
    full = [d for d in datasets if all((d, l) in acc for l in levels)
            and len({len(acc[(d, l)]) for l in levels}) == 1]
    out = {}
    for l in levels:
        gains = [m[(d, l)] - m[(d, 0.0)] for d in full]
        wins, losses = sum(g > EPS for g in gains), sum(g < -EPS for g in gains)
        ranks = []
        for d in full:
            vs, v = [m[(d, x)] for x in levels], m[(d, l)]
            ranks.append(1 + sum(x > v + EPS for x in vs) + 0.5 * (sum(abs(x - v) <= EPS for x in vs) - 1))
        out[l] = (len(full), mean(m[(d, l)] for d in full), 100 * mean(gains), wins,
                  len(full) - wins - losses, losses, mean(ranks))
    return out


def single_row(path, dist_path):
    """(acc_mean, gain_pts, wins, ties, losses) of single-machine SPO-GBT vs distributed r=0."""
    acc, base = defaultdict(list), defaultdict(list)
    for r in csv.DictReader(open(path)):
        if r["rc"] == "0" and r["test_acc"]:
            acc[r["dataset"]].append(float(r["test_acc"]))
    for r in csv.DictReader(open(dist_path)):
        if r["rc"] == "0" and r["test_acc"] and float(r["replication"]) == 0.0:
            base[r["dataset"]].append(float(r["test_acc"]))
    assert set(acc) == set(base), set(acc) ^ set(base)
    gains = [mean(acc[d]) - mean(base[d]) for d in sorted(acc)]
    wins, losses = sum(g > EPS for g in gains), sum(g < -EPS for g in gains)
    return mean(mean(v) for v in acc.values()), 100 * mean(gains), wins, len(gains) - wins - losses, losses


def main():
    p = pooled(SRC / "results.csv")
    # Cross-check against summarize_replication.py's output (same rounding).
    for r in csv.DictReader(open(SRC / "summary_pooled.csv")):
        n, a, g, w, t, lo, rk = p[float(r["replication"])]
        mine = [str(n), f"{a:.4f}", f"{g:+.2f}", str(w), str(t), str(lo), f"{rk:.2f}"]
        theirs = [r[k] for k in ("n_datasets", "acc_mean", "gain_vs_0_pts", "wins", "ties", "losses", "mean_rank")]
        assert mine == theirs, (r["replication"], mine, theirs)
    lines = ["% auto-generated by benchmarks/src/distributed_spo_gbt/make_column_replication_table.py -- regenerate, do not hand-edit",
             "% data: benchmarks/results/accuracy/distributed_spo_gbt/column_replication_vertex/results.csv (Vertex AI run full20261029b); single: single_machine_spo_gbt.csv",
             "", r"\begin{tabular}{crrcr}", r"\toprule",
             r"$r$ & \multicolumn{1}{c}{Mean acc.} & \multicolumn{1}{c}{$\Delta$ (pts)} & W/T/L & \multicolumn{1}{c}{Mean rank} \\",
             r"\midrule"]
    for l, (n, a, g, w, t, lo, rk) in sorted(p.items()):
        acc = f"{a:.4f}".lstrip("0")
        if l == 0.0:
            lines.append(f"{l:.1f} & {acc} & {DASH} & {DASH} & {rk:.2f} \\\\")
        else:
            lines.append(f"{l:.1f} & {acc} & ${g:+.2f}$ & {w}/{t}/{lo} & {rk:.2f} \\\\")
    a, g, w, t, lo = single_row(SRC / "single_machine_spo_gbt.csv", SRC / "results.csv")
    acc = f"{a:.4f}".lstrip("0")
    lines += [r"\midrule",
              rf"\textbf{{single}} & \textbf{{{acc}}} & $\mathbf{{{g:+.2f}}}$ & \textbf{{{w}/{t}/{lo}}} & {DASH} \\"]
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({n} datasets, {len(p)} levels)", file=sys.stderr)


if __name__ == "__main__":
    main()
