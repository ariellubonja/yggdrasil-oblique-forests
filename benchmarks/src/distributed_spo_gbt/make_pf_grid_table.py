#!/usr/bin/env python3
"""Vertex barrier grid -> LaTeX tabular BODY: tree-training seconds per dataset x arm x W, plus test accuracy.
Selects cells by run-dir prefix, machine type and tree count (default: the P=F, 10-tree n2-highmem-16 grid).
--right_run_prefix appends a second grid to the right under bold machine-type headers (one Dataset/Arm column).
Caption/label live in main.tex. Usage: make_pf_grid_table.py [--run_prefix P] [--machine M] [--trees N] [--w 1,2,4]
  [--oom_logs GLOB] [--right_run_prefix P --right_machine M --right_w 1,2,4 --right_oom_logs GLOB] [--out BODY.tex] [--md]"""
import argparse, glob, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "../../results/runtime/distributed_spo_gbt/barriers/vertex/p_F")  # P = F runs (pf* prefixes)
DATASETS = [("epsilon", "Epsilon"), ("higgs", "HIGGS"), ("susy", "SUSY"), ("youtube8m", "YouTube-8M")]
ARMS = [("aa", "AA"), ("spo", "SPO in-node")]


def load(prefix, machine, trees):
    cells = {}
    for p in glob.glob(os.path.join(RESULTS, f"{prefix}*", "*", "eval.json")):
        e = json.load(open(p))
        if e.get("machine_type") != machine or e.get("trees") != trees or "tree_training_s" not in e:
            continue
        cells[(e["dataset"], e["arm"], e["workers"])] = dict(t=e["tree_training_s"], acc=e.get("accuracy"), p=e.get("p_total"))
    return cells


def load_oom(log_glob):
    """(dataset, arm, W) cells whose Vertex job failed for memory, from the launcher logs."""
    oom = set()
    for f in glob.glob(os.path.expanduser(log_glob)):
        txt = open(f).read(); m = re.search(r"dataset (\w+) \(", txt)
        for arm, w in re.findall(r"(aa|spo)_w(\d+) JOB_STATE_FAILED error: Replicas low on memory", txt):
            oom.add((m.group(1), arm, int(w)))
    return oom


def grid(prefix, machine, trees, w, oom_logs):
    """One grid: {(dataset, arm): cell strings for each W + accuracy}, rows with no data and no OOM omitted."""
    W = [int(x) for x in w.split(",")]; cells = load(prefix, machine, trees)
    oom = load_oom(oom_logs) if oom_logs else set(); rows = {}
    for ds, _ in DATASETS:
        for arm, _ in ARMS:
            row = [cells.get((ds, arm, x)) for x in W]
            if not any(row) and not any((ds, arm, x) in oom for x in W):
                continue
            accs = [c["acc"] for c in row if c and c["acc"] is not None]
            acc = f"{min(accs):.3f}" if accs and max(accs) - min(accs) < 0.0015 else (f"{min(accs):.3f}--{max(accs):.3f}" if accs else "")
            rows[(ds, arm)] = [f"{c['t']:.0f}" if c else ("OOM" if (ds, arm, x) in oom else "--") for c, x in zip(row, W)] + [acc]
    return dict(W=W, rows=rows, src=f"{prefix}*, {machine}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run_prefix", default="pfgrid20261025"); ap.add_argument("--machine", default="n2-highmem-16")
    ap.add_argument("--trees", type=int, default=10); ap.add_argument("--w", default="1,2,4")
    ap.add_argument("--out", default=None); ap.add_argument("--md", action="store_true")
    ap.add_argument("--oom_logs", default=None, help="launcher log glob; memory-failed cells print OOM")
    ap.add_argument("--right_run_prefix", default=None, help="second grid, appended to the right")
    ap.add_argument("--right_machine", default=None); ap.add_argument("--right_w", default=None)
    ap.add_argument("--right_oom_logs", default=None)
    a = ap.parse_args()
    grids = [grid(a.run_prefix, a.machine, a.trees, a.w, a.oom_logs)]
    if a.right_run_prefix:
        grids.append(grid(a.right_run_prefix, a.right_machine or a.machine, a.trees, a.right_w or a.w, a.right_oom_logs))
    paired = len(grids) == 2
    blank = [[""] * (len(g["W"]) + 1) for g in grids]
    lines = ["% auto-generated by benchmarks/src/distributed_spo_gbt/make_pf_grid_table.py -- regenerate, do not hand-edit",
             f"% cells: {RESULTS.split('results/')[1]}/" + " | ".join(g["src"] for g in grids) + f", {a.trees} trees",
             r"\begin{tabular}{ll|" + "||".join("r" * len(g["W"]) + "|r" for g in grids) + "}", r"\toprule"]
    if paired:
        machines = [a.machine, a.right_machine or a.machine]
        lines.append(r" & & \multicolumn{%d}{c||}{\textbf{\texttt{%s}}} & \multicolumn{%d}{c}{\textbf{\texttt{%s}}} \\"
                     % (len(grids[0]["W"]) + 1, machines[0], len(grids[1]["W"]) + 1, machines[1]))
    lines += ["Dataset & Arm & " + " & ".join(" & ".join(f"$W={w}$" for w in g["W"]) + " & Acc." for g in grids) + r" \\", r"\midrule"]
    md = ["| dataset | arm | " + " | ".join(" | ".join(f"W={w}" for w in g["W"]) + " | acc" for g in grids) + " |",
          "|---" * (sum(len(g["W"]) + 1 for g in grids) + 2) + "|"]
    for ds, dsname in DATASETS:
        first = True
        for arm, armname in ARMS:
            parts = [g["rows"].get((ds, arm)) for g in grids]
            if not any(parts):
                continue
            cols = sum((p or b for p, b in zip(parts, blank)), [])
            lines.append(f"{dsname if first else ''} & {armname} & " + " & ".join(cols) + " \\\\")
            md.append(f"| {dsname if first else ''} | {armname} | " + " | ".join(cols) + " |")
            first = False
        if not first:
            lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"; lines.append(r"\end{tabular}")
    body = "\n".join(lines) + "\n"
    if a.out:
        open(a.out, "w").write(body); print("wrote", a.out, file=sys.stderr)
    else:
        print(body)
    if a.md:
        print("\n".join(md))


if __name__ == "__main__":
    main()
