#!/usr/bin/env python3
"""Body of the KDD27 cross-network projections table (in-worker vs cross-network, per CC18 dataset).

Reads the Vertex run results.csv, writes only the tabular body; caption/label live in main.tex.
  python make_cross_network_table.py [results.csv] [out_body.tex]
"""
import csv
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    HERE, "../../results/runtime/distributed_spo_gbt/naive_column_shipping/vertex_hm4_20261029/results.csv")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    HERE, "../../../paper/distributed_spo_gbt_kdd27/tables/table_cross_network_body.tex")

by = {}
for r in csv.DictReader(open(SRC)):
    by.setdefault(r["dataset"], {})[r["arm"]] = r
rows = []
for name, v in by.items():
    a, b = v["in_worker"], v["cross_network"]
    ta, tb = float(a["tree_training_s"]), float(b["tree_training_s"])
    wait = float(b["ship_s_max"])
    rows.append(dict(name=name, n=int(a["rows_train"]), f=int(a["features"]), ta=ta, tb=tb, x=ta / tb,
                     gb=int(b["ship_bytes_in"]) / 1e9, wait=wait, wpct=100 * wait / tb,
                     acca=float(a["test_acc"]), accb=float(b["test_acc"])))
rows.sort(key=lambda r: (-r["x"], r["name"].lower()))

tex = lambda s: s.replace("_", r"\_")  # noqa: E731
acc = lambda x: f"{x:.3f}".lstrip("0")  # noqa: E731
lines = [
    "% auto-generated by benchmarks/src/distributed_spo_gbt/make_cross_network_table.py -- regenerate, do not hand-edit",
    f"% data: {os.path.relpath(SRC, os.path.join(HERE, '../../..'))}",
    r"\begin{tabular}{lrrrrrrrrrr}",
    r"\toprule",
    r" & & & \multicolumn{3}{c}{Tree-training time (s)} & \multicolumn{3}{c}{Communication} & \multicolumn{2}{c}{Test accuracy} \\",
    r"\cmidrule(lr){4-6}\cmidrule(lr){7-9}\cmidrule(lr){10-11}",
    r"Dataset & Rows & $F$ & In-worker & Cross-net. & Speedup & GB & Wait (s) & Wait \% & In-worker & Cross-net. \\",
    r"\midrule",
]
for r in rows:
    lines.append(f"{tex(r['name'])} & {r['n']:,} & {r['f']:,} & {r['ta']:.1f} & {r['tb']:.1f} & "
                 f"{r['x']:.2f}$\\times$ & {r['gb']:.2f} & {r['wait']:.1f} & {r['wpct']:.0f} & "
                 f"{acc(r['acca'])} & {acc(r['accb'])} \\\\".replace(",", "{,}"))
geo = math.exp(sum(math.log(r["x"]) for r in rows) / len(rows))
ta, tb = sum(r["ta"] for r in rows), sum(r["tb"] for r in rows)
wait = sum(r["wait"] for r in rows)
lines += [
    r"\midrule",
    f"Total / geomean & & & {ta:.0f} & {tb:.0f} & {geo:.2f}$\\times$ & {sum(r['gb'] for r in rows):.1f} & "
    f"{wait:.0f} & {100 * wait / tb:.0f} & {acc(sum(r['acca'] for r in rows) / len(rows))} & "
    f"{acc(sum(r['accb'] for r in rows) / len(rows))} \\\\",
    r"\bottomrule",
    r"\end{tabular}",
]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"wrote {OUT} ({len(rows)} datasets, geomean speedup {geo:.2f}x)")
