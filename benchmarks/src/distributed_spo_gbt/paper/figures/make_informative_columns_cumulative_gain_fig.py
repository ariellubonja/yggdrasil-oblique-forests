"""Body for fig:informative-columns-cumulative-gain: cumulative split gain over columns ranked by score.

Single-machine SPO-GBT (kdd28_hao), mean over seeds x folds. Column score = sum over all trees of
split gain (score x node examples) shared evenly over the split's columns.
Usage: make_informative_columns_cumulative_gain_fig.py <analysis_dir with splits.tsv.gz + features.tsv> <paper_dir>
"""
import collections
import csv
import gzip
import os
import sys

import numpy as np

SRC, PAPER = sys.argv[1:3]
SERIES = [("madeline", "madeline", (42, 120, 214)), ("fabert", "fabert", (235, 104, 52)),
          ("jasmine", "jasmine", (27, 175, 122)), ("robert", "robert", (237, 161, 0)),
          ("epsilon", "epsilon", (232, 123, 164)), ("madelon (CC18)", "madelon", (0, 131, 0))]
GRID = np.concatenate([np.arange(0, 10, 0.25), np.arange(10, 100.5, 1.0)])
REL = "figures/evaluation/informative_columns_cumulative_gain"

F = collections.Counter()
for r in csv.DictReader(open(f"{SRC}/features.tsv"), delimiter="\t"):
    if r["type"] == "NUMERICAL" and r["fold"] == "0":
        F[r["dataset"]] += 1
want = {s[0] for s in SERIES}
gain = collections.defaultdict(collections.Counter)
with gzip.open(f"{SRC}/splits.tsv.gz", "rt") as fh:
    next(fh)
    for line in fh:
        ds, seed, fold, arm, tree, cols, g = line.rstrip("\n").split("\t")
        if arm == "single" and ds in want:
            c = cols.split("+")
            for x in c:
                gain[(ds, seed, fold)][x] += float(g) / len(c)

os.makedirs(f"{PAPER}/{REL}", exist_ok=True)
plots = []
for ds, label, rgb in SERIES:
    curves = []
    for (d, s, f), cg in gain.items():
        if d != ds:
            continue
        v = np.zeros(F[ds])
        vals = sorted(cg.values(), reverse=True)
        v[:len(vals)] = vals
        xs = np.concatenate([[0.0], 100 * np.arange(1, F[ds] + 1) / F[ds]])
        ys = np.concatenate([[0.0], 100 * np.cumsum(v) / v.sum()])
        curves.append(np.interp(GRID, xs, ys))
    y = np.mean(curves, axis=0)
    name = label.replace(" ", "_")
    with open(f"{PAPER}/{REL}/{name}.dat", "w") as fh:
        fh.write("x y\n")
        for a, b in zip(GRID, y):
            fh.write(f"{a:g} {b:.2f}\n")
    top10 = float(np.interp(10, GRID, y))
    print(f"{ds}: F={F[ds]}, models={len(curves)}, top 10% of columns -> {top10:.1f}% of gain")
    plots.append(f"\\addplot[thick, color={{rgb,255:red,{rgb[0]};green,{rgb[1]};blue,{rgb[2]}}}] "
                 f"table[x=x, y=y] {{{REL}/{name}.dat}};\n\\addlegendentry{{{label} ($F{{=}}{F[ds]}$)}}\n")

body = ("% auto-generated by benchmarks/src/distributed_spo_gbt/paper/figures/"
        "make_informative_columns_cumulative_gain_fig.py -- regenerate, do not hand-edit\n"
        "\\begin{tikzpicture}\n\\begin{axis}[width=\\linewidth, height=4.6cm, xmin=0, xmax=100, ymin=0, ymax=100,\n"
        "  xlabel={columns, ranked by score (\\% of all columns)}, ylabel={cumulative split gain (\\%)},\n"
        "  tick label style={font=\\scriptsize}, label style={font=\\footnotesize}, tick style={draw=none},\n"
        "  ymajorgrids, xmajorgrids, grid style={gray!20}, axis line style={gray!70},\n"
        "  legend style={font=\\scriptsize, draw=none, fill=none, at={(0.98,0.03)}, anchor=south east},\n"
        "  legend cell align=left]\n" + "".join(plots) + "\\end{axis}\n\\end{tikzpicture}\n")
out = f"{PAPER}/figures/evaluation/fig_informative_columns_cumulative_gain_body.tex"
open(out, "w").write(body)
print("wrote", out)
