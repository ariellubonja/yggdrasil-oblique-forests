"""fig:col-correlation-vs-colrep: per-dataset column correlation vs. the gain from full column replication (r = 0 -> 1).

Inputs (tab-accuracy-where-spo-outperforms-aa/derived): col_correlation.csv (col_correlation.py), hao_{cls,reg}/{colrep,r0}.csv.
Writes the pgfplots body + .dat files into the paper snapshot. Usage: python3 <this file> (from the repo root).
"""
import pathlib
import pandas as pd
from scipy.stats import spearmanr

ROOT = pathlib.Path(__file__).resolve().parents[5]
DER = ROOT / "benchmarks/results/kdd28/floats/accuracy/tab-accuracy-where-spo-outperforms-aa/derived"
FIG = ROOT / "paper/distributed_spo_gbt_kdd28/figures/evaluation"
NAME = "col_correlation_vs_colrep"
WS = (4, 8, 16, 32)
BLUE, GREEN = "rgb,255:red,42;green,120;blue,214", "rgb,255:red,27;green,175;blue,122"


def gains(task, corr):
    """One row per (dataset, W): x = column correlation, y = gain from r = 0 to r = 1 (positive = replication helps)."""
    col = pd.read_csv(DER / f"hao_{task}/colrep.csv", low_memory=False)
    r0 = pd.read_csv(DER / f"hao_{task}/r0.csv", low_memory=False)
    metric = "test_auc" if task == "cls" else "test_rmse"
    out = []
    for c in corr.itertuples():
        # A CC18 copy of a TabArena dataset is the same data: its TabArena cells are used, counted once.
        for W in WS:
            one = col[(col.dataset == c.dataset) & (col.workers == W) & (col.replication == 1.0)][metric]
            zero = r0[(r0.dataset == c.dataset) & (r0.arm == f"{W}:SPO")][metric]
            if len(one) == 0 or len(one) != len(zero):
                raise SystemExit(f"STOP {task} {c.dataset} W={W}: {len(one)} r=1 cells vs {len(zero)} r=0 cells")
            g = 100 * (one.mean() - zero.mean()) if task == "cls" else 100 * (zero.mean() - one.mean()) / zero.mean()
            out.append(dict(dataset=c.dataset, W=W, x=c.mean_max_rho, y=g, n=len(one)))
    return pd.DataFrame(out)


def main():
    corr = pd.read_csv(DER / "col_correlation.csv")
    (FIG / NAME).mkdir(parents=True, exist_ok=True)
    rows, stats = [], {}
    for task, lab in (("cls", "classification"), ("reg", "regression")):
        g = gains(task, corr[corr.task == lab])
        for W in WS:
            t = g[g.W == W]
            t[["x", "y"]].to_csv(FIG / NAME / f"{task}_w{W}.dat", sep=" ", index=False, float_format="%.5f")
            stats[task, W] = (len(t), *spearmanr(t.x, t.y))
        g["task"] = task
        rows.append(g)
    pd.concat(rows).to_csv(DER / "col_correlation_vs_colrep_gain.csv", index=False)

    def panel(task, W, first, ylabel, ymin, ymax, color):
        n, rho, p = stats[task, W]
        ptxt = "$p<0.01$" if p < 0.01 else f"$p={p:.2f}$"
        opts = f"ymin={ymin}, ymax={ymax}, title={{$W={W}$: $\\rho={rho:+.2f}$, {ptxt}}}"
        if first:
            opts += f", ylabel={{{ylabel}}}"
        return (f"\\nextgroupplot[{opts}]\n"
                f"\\addplot[gray!70, forget plot] coordinates {{(0,0) (1,0)}};\n"
                f"\\addplot[only marks, mark=*, mark size=1.4pt, color={{{color}}}, fill opacity=0.85] "
                f"table[x=x, y=y] {{figures/evaluation/{NAME}/{task}_w{W}.dat}};\n")

    body = [f"% auto-generated by benchmarks/src/distributed_spo_gbt/paper/figures/make_{NAME}_fig.py -- regenerate, do not hand-edit",
            "\\begin{tikzpicture}",
            "\\begin{groupplot}[group style={group size=4 by 2, horizontal sep=0.35cm, vertical sep=1.3cm, yticklabels at=edge left},",
            "  width=0.27\\textwidth, height=4.4cm, xmin=0, xmax=1, xtick={0,0.25,0.5,0.75,1}, xlabel={column correlation},",
            "  xticklabel style={/pgf/number format/fixed}, title style={font=\\footnotesize, yshift=-1.5ex},",
            "  tick label style={font=\\scriptsize}, label style={font=\\footnotesize}, tick style={draw=none},",
            "  ymajorgrids, xmajorgrids, grid style={gray!20}, axis line style={gray!70}]"]
    for k, W in enumerate(WS):
        body.append(panel("cls", W, k == 0, "$\\Delta$ AUC, $r{=}0\\to1$ (pts)", -1, 4.5, BLUE))
    for k, W in enumerate(WS):
        body.append(panel("reg", W, k == 0, "RMSE drop, $r{=}0\\to1$ (\\%)", -1, 5.5, GREEN))
    body += ["\\end{groupplot}", "\\end{tikzpicture}", ""]
    (FIG / f"fig_{NAME}_body.tex").write_text("\n".join(body))
    for (task, W), (n, rho, p) in stats.items():
        print(f"{task} W={W:2d} n={n:2d} rho={rho:+.2f} p={p:.3f}")
    g = pd.concat(rows)
    print("y range:", g.groupby("task").y.agg(["min", "max"]).round(2).to_dict("index"))


if __name__ == "__main__":
    main()
