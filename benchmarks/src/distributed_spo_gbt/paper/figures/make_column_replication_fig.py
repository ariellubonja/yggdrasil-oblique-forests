"""KDD28 column-replication figure data: mean delta + bootstrap CI (top), per-dataset delta boxes (bottom).
Deltas are distributed level r minus single-machine SPO-GBT (single_machine_spo_gbt.csv), so 0 = single.
kdd28_ydf (fig:column-replication-where-spo-outperforms-aa): --suffix _where_spo_outperforms_aa --metric test_auc --single_csv/--r0_csv = the distacc results.csv
(same row filters and arms as make_column_replication_table.py).

Writes .dat files and a pgfplots body; the figure environment and caption live in main.tex.
"""
import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "params"))
import params as kdd28  # noqa: E402  (params/kdd28_params.json)

ROOT = Path(__file__).resolve().parents[5]
CSV = ROOT / "benchmarks/results/kdd28/runs/2026-11-01_colrep_vertex_split_budget/results.csv"
OUT = ROOT / "paper/distributed_spo_gbt_kdd28/figures/evaluation/column_replication"
SINGLE = ROOT / "benchmarks/results/kdd28/runs/2026-11-01_colrep_single_spo_10seeds/single_machine_spo_gbt.csv"
CLIP = 5.0
BODY = r"""%% auto-generated by benchmarks/src/distributed_spo_gbt/paper/figures/make_column_replication_fig.py -- regenerate, do not hand-edit
\begin{tikzpicture}
\begin{groupplot}[group style={group size=1 by 2, vertical sep=0.35cm, xticklabels at=edge bottom, xlabels at=edge bottom},
  width=\linewidth, xmin=-0.05, xmax=1.05, xtick={0,0.1,...,1.0},
  xticklabel style={/pgf/number format/fixed, /pgf/number format/precision=1, /pgf/number format/fixed zerofill},
  xlabel={column replication $r$}, tick label style={font=\footnotesize}, label style={font=\footnotesize},
  tick style={draw=none}, ymajorgrids, grid style={gray!25}, axis line style={gray!70}, every axis plot/.append style={line join=round}]
\nextgroupplot[height=3.6cm, ylabel={$\Delta$ mean %(ylab)s}]
\addplot[draw=none, fill={rgb,255:red,55;green,138;blue,221}, fill opacity=0.18, forget plot] table {%(rel)s/band.dat};
\addplot[color={rgb,255:red,0;green,131;blue,0}, dashed, forget plot] coordinates {(-0.05,0) (1.05,0)};
\node[font=\scriptsize, text={rgb,255:red,0;green,131;blue,0}, anchor=south east] at (axis cs:1.05,0) {single};
\addplot[color={rgb,255:red,55;green,138;blue,221}, mark=*, mark size=1.5pt, thick] table[x=r, y=mean] {%(rel)s/mean.dat};
\nextgroupplot[height=4.2cm, ymin=-%(clip)g, ymax=%(clip)g, ytick={%(ytick)s}, ylabel={per-dataset $\Delta$ %(unit)s}]
\addplot[color={rgb,255:red,0;green,131;blue,0}, dashed, forget plot] coordinates {(-0.05,0) (1.05,0)};
\addplot[only marks, mark=*, mark size=0.6pt, color={rgb,255:red,55;green,138;blue,221}, opacity=0.45] table[x=x, y=d] {%(rel)s/dots.dat};
\addplot[gray!90, empty line=jump] table {%(rel)s/boxes.dat};
\addplot[black, thick, empty line=jump] table {%(rel)s/medians.dat};
\addplot[color={rgb,255:red,216;green,90;blue,48}, mark=diamond*, mark size=1.6pt] table[x=r, y=mean] {%(rel)s/mean.dat};
\end{groupplot}
\end{tikzpicture}
"""


def seeds_balanced(df, keys, label):
    """Means pool seeds, so every cell must hold the same seed set (exit 2 otherwise, e.g. a seed still running)."""
    if "seed" not in df:
        return
    sets = df.groupby(keys).seed.agg(lambda v: tuple(sorted(int(t) for t in v)))
    if sets.nunique() > 1:
        print(f"ERROR {label}: unequal seed sets per {keys}: {sets.value_counts().to_dict()}", file=sys.stderr)
        sys.exit(2)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=str(CSV))
    ap.add_argument("--out", default=None, help="dir for the .dat files (default: the paper's column_replication<suffix>/)")
    ap.add_argument("--suffix", default="", help="names: column_replication<suffix>/, fig_column_replication<suffix>_body.tex")
    ap.add_argument("--metric", default="test_acc", choices=["test_acc", "test_auc", "test_rmse"])
    ap.add_argument("--relative", action="store_true", help="delta = 100 * (dist / single - 1) %% (test_rmse: + = worse)")
    ap.add_argument("--clip", type=float, default=CLIP, help="per-dataset panel y range +-clip, dots outside dropped")
    ap.add_argument("--dist_arm", default="dist_split", help="profile arm of the distributed rows")
    ap.add_argument("--single_csv", default=None,
                    help="single rows (default: <csv dir>/single_machine_spo_gbt.csv, for the default --csv its 10-seed run file)")
    ap.add_argument("--single_filter", default="", help="col=value: keep only these single rows")
    ap.add_argument("--single_arms", default="single_spo,single_spo_audit", help="profile arms of the single rows")
    ap.add_argument("--r0_csv", default="", help="rows reused as r = 0, filtered by --r0_filter")
    ap.add_argument("--r0_filter", default=None, help="default arm=<--workers>:SPO"); ap.add_argument("--r0_arm", default="distacc_spo")
    ap.add_argument("--workers", type=int, default=4, help="keep the distributed rows of this W (CSVs without a workers column: all)")
    kdd28.add_profile_arg(ap, __file__)
    a = ap.parse_args()
    M, rel = a.metric, f"figures/evaluation/column_replication{a.suffix}"
    out = Path(a.out or OUT.parent / f"column_replication{a.suffix}")
    out.mkdir(parents=True, exist_ok=True)
    if a.single_csv:
        single_path = Path(a.single_csv)
    else:  # the default --csv keeps its single rows in their own run dir (dir compared, as in the table script)
        c = Path(a.csv)
        is_default = c.parent.resolve() == CSV.parent.resolve() and c.name == CSV.name
        single_path = SINGLE if is_default else c.parent / "single_machine_spo_gbt.csv"
    single_arms = a.single_arms.split(",")

    def filt(df, f):
        col, _, val = f.partition("=")
        return df[df[col].astype(str) == val] if col else df
    d = pd.read_csv(a.csv)
    d = d[d.rc == 0]
    if "workers" in d:
        d = d[d.workers.astype(int) == a.workers]
    if a.r0_filter is None:
        a.r0_filter = f"arm={a.workers}:SPO"
    kdd28.check_frame(d, a.profile, [a.dist_arm], Path(a.csv).name + " (distributed)")
    if a.r0_csv:  # r = 0 cells reused from distacc, as in make_column_replication_table.py
        r0 = filt(pd.read_csv(a.r0_csv).query("rc == 0"), a.r0_filter)
        kdd28.check_frame(r0, a.profile, [a.r0_arm], Path(a.r0_csv).name + " (r = 0)", arm_of=lambda r: a.r0_arm)
        d = pd.concat([d[d.replication != 0], r0.assign(replication=0.0)])
    seeds_balanced(d, ["dataset", "fold", "replication"], "distributed rows")
    m = d.groupby(["dataset", "replication"])[M].mean().unstack()
    R = m.columns.values
    sg = filt(pd.read_csv(single_path), a.single_filter)
    kdd28.check_frame(sg[sg.rc == 0], a.profile, single_arms, single_path.name + " (single)",
                      arm_of=(lambda r: single_arms[0]) if a.single_filter else None)
    seeds_balanced(sg[sg.rc == 0], ["dataset", "fold"], "single rows")
    sg = sg[sg.rc == 0].groupby("dataset")[M].mean().reindex(m.index)
    assert sg.notna().all(), "single-machine run misses datasets"
    delta = (m.div(sg, axis=0) - 1) * 100 if a.relative else m.sub(sg, axis=0) * 100
    CL = a.clip
    rng = np.random.default_rng(0)
    idx = rng.integers(0, len(delta), (10000, len(delta)))
    boot = np.stack([delta[c].values[idx].mean(1) for c in R], 1)
    lo, hi = np.percentile(boot, [2.5, 97.5], 0)
    pd.DataFrame({"r": R, "mean": delta.mean().values, "lo": lo, "hi": hi}).to_csv(
        out / "mean.dat", sep=" ", index=False, float_format="%.4f")
    band = np.r_[np.c_[R, lo], np.c_[R[::-1], hi[::-1]]]
    np.savetxt(out / "band.dat", band, fmt="%.4f", header="x y", comments="")
    box, med, dots, n_out = [], [], [], 0
    hw = 0.6 * np.diff(R).min() / 2  # box half-width: 60 % of the narrowest r step
    for c, v, bx, dt in [(c, delta[c].values, box, dots) for c in R]:
        q1, q2, q3 = np.percentile(v, [25, 50, 75])
        lw = v[v >= q1 - 1.5 * (q3 - q1)].min()
        uw = v[v <= q3 + 1.5 * (q3 - q1)].max()
        bx += [(c - hw, q1), (c + hw, q1), (c + hw, q3), (c - hw, q3), (c - hw, q1), None,
                (c, q3), (c, uw), None, (c, q1), (c, lw), None,
                (c - hw / 2, uw), (c + hw / 2, uw), None, (c - hw / 2, lw), (c + hw / 2, lw), None]
        med += [(c - hw, q2), (c + hw, q2), None]
        keep = np.abs(v) <= CL
        n_out += int((~keep).sum())
        dt += [(c + j, y) for j, y in zip(rng.uniform(-hw * 0.022 / 0.03, hw * 0.022 / 0.03, keep.sum()), v[keep])]
    for name, pts in (("boxes", box), ("medians", med)):
        with open(out / f"{name}.dat", "w") as f:
            f.write("x y\n" + "".join("\n" if p is None else f"{p[0]:.4f} {p[1]:.4f}\n" for p in pts))
    for name, pts in (("dots", dots),):
        with open(out / f"{name}.dat", "w") as f:
            f.write("x d\n" + "".join(f"{x:.4f} {y:.4f}\n" for x, y in pts))
    ylab = {"test_auc": "AUC", "test_acc": "acc.\\", "test_rmse": "RMSE"}[M]
    unit = "(\\%)" if a.relative else "(pts)"
    step = CL * 0.4 if CL != CLIP else 2
    ytick = f"{-2 * step:g},{-step:g},...,{2 * step:g}"
    arms = single_arms + ([a.dist_arm, a.r0_arm] if a.r0_csv else [])
    (out.parent / f"fig_column_replication{a.suffix}_body.tex").write_text(
        kdd28.add_setup(BODY % {"clip": CL, "rel": rel, "ylab": f"{ylab} {unit}", "unit": unit, "ytick": ytick}, kdd28.setup_line(a.profile, arms)))
    print(f"{len(delta)} datasets; r=0 {delta[0.0].mean():+.2f} {unit} vs single-machine; "
          f"{n_out} of {len(delta) * len(R)} per-dataset deltas outside +-{CL:g}")


if __name__ == "__main__":
    main()
