#!/usr/bin/env python3
"""tab:ordinal-vs-native body: single-machine GBT test AUC with categoricals dropped, ordinal (NUMERICAL) or native
(CATEGORICAL, AA only, --- for SPO). AA block above the SPO block. Inputs: runs/2026-11-19_ordinal_vs_native (AA ordinal, native) and
runs/2026-11-22_categorical_dropped_vs_ordinal_aa_spo_gbt (AA/SPO dropped, SPO ordinal). Run from the repo root."""
import pathlib
import sys

import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import make_paper_tables as mpt  # noqa: E402  (ds_label: "Name (rows, cols, cat=X)", sources)

ROOT = pathlib.Path(__file__).resolve().parents[5]
RUNS = ROOT / "benchmarks/results/kdd28/runs"
RES_NATIVE = RUNS / "2026-11-19_ordinal_vs_native/results.csv"
RES_DROP = RUNS / "2026-11-22_categorical_dropped_vs_ordinal_aa_spo_gbt/results.csv"
OUT = ROOT / "paper/distributed_spo_gbt_kdd28/tables/table_ordinal_vs_native_body.tex"

sh = pd.read_csv(ROOT / mpt.SHAPES_CSV).drop_duplicates("dataset").set_index("dataset")
mpt.SHAPES = {d: (int(r.rows), int(r.features)) for d, r in sh.iterrows()}
ca = pd.read_csv(ROOT / mpt.CATS_CSV).set_index("dataset")
mpt.CATS = {d: (int(r.categorical), int(r.features)) for d, r in ca.iterrows()}
mpt.SHAPE_BELOW = True  # (rows, cols, cat) on a second gray line, as in tab:accuracy-hao-vs-ydf-params-distributed

a = pd.read_csv(RES_NATIVE).replace({"arm": {"ordinal": "aa_ordinal", "native": "aa_native"}})
b = pd.read_csv(RES_DROP, keep_default_na=False)
key = ["dataset", "fold"]
rep = a[a.arm == "aa_ordinal"].merge(b[b.arm == "aa_ordinal"], on=key, suffixes=("_a", "_b"))
assert len(rep) == 20 and (rep.test_auc_a - rep.test_auc_b).abs().max() < 1e-12, "AA ordinal must reproduce across runs"
r = pd.concat([a, b[b.arm != "aa_ordinal"]])
ARMS = ["aa_dropped", "aa_ordinal", "aa_native", "spo_dropped", "spo_ordinal"]
p = r.pivot_table(index=key, columns="arm", values="test_auc")[ARMS]
assert p.notna().all().all() and (p.groupby("dataset").size() == 5).all(), "every dataset needs 5 folds, all arms"
const = set(b.loc[b.note == "no_features_constant_predictor", "dataset"])  # every categorical dropped -> AUC .5
g = p.groupby("dataset").mean()
g = g.loc[(g.spo_ordinal - g.spo_dropped).sort_values(ascending=False).index]  # same dataset order in both blocks
f4 = lambda v: f"{v:.4f}".lstrip("0")  # noqa: E731
dag = r"$^\dagger$"
lines = [r"% auto-generated by benchmarks/src/distributed_spo_gbt/paper/tables/make_ordinal_vs_native_table.py -- regenerate, do not hand-edit",
         f"% sources: {RES_NATIVE.relative_to(ROOT)}, {RES_DROP.relative_to(ROOT)}",
         r"% dagger: no feature left after dropping categoricals, constant prediction (AUC .5). --- = arm not run (SPO has no native categoricals)",
         r"\begin{tabular}{lrrr}", r"\toprule", r"Dataset & Dropped & Ordinal & Native \\"]
for split, name in (("aa", "AA-GBT"), ("spo", "SPO-GBT")):  # AA block above the SPO block
    cols = [f"{split}_{c}" for c in ("dropped", "ordinal", "native")]
    cell = lambda ds, k: "---" if k not in g else f4(g.loc[ds, k]) + (dag if ds in const and k.endswith("dropped") else "")  # noqa: E731
    lines += [r"\midrule", r"\multicolumn{4}{@{}l}{\textbf{%s}} \\" % name]
    for src, dss in mpt.sources(list(g.index)):  # by benchmark
        lines.append(mpt.source_row(src, 4))
        lines += [f"{mpt.ds_label(ds)} & " + " & ".join(cell(ds, k) for k in cols) + r" \\" for ds in dss]
    lines.append("Mean & " + " & ".join("---" if k not in g else f4(g[k].mean()) for k in cols) + r" \\")
lines += [r"\bottomrule", r"\end{tabular}"]
OUT.write_text("\n".join(lines) + "\n")
print(OUT)
