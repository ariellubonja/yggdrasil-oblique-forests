#!/usr/bin/env python3
"""tab:ordinal-vs-native body: AA-GBT test AUC with categoricals as ordinal NUMERICAL vs native CATEGORICAL.
Input benchmarks/results/kdd28/accuracy/tab-ordinal-vs-native/results.csv (run.py there). Run from the repo root."""
import pathlib
import sys

import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import make_paper_tables as mpt  # noqa: E402  (ds_label: "Name (rows, cols, cat=X)")

ROOT = pathlib.Path(__file__).resolve().parents[5]
RES = ROOT / "benchmarks/results/kdd28/accuracy/tab-ordinal-vs-native/results.csv"
OUT = ROOT / "paper/distributed_spo_gbt_kdd28/tables/table_ordinal_vs_native_body.tex"

sh = pd.read_csv(ROOT / mpt.SHAPES_CSV).drop_duplicates("dataset").set_index("dataset")
mpt.SHAPES = {d: (int(r.rows), int(r.features)) for d, r in sh.iterrows()}
ca = pd.read_csv(ROOT / mpt.CATS_CSV).set_index("dataset")
mpt.CATS = {d: (int(r.categorical), int(r.features)) for d, r in ca.iterrows()}
mpt.SHAPE_BELOW = True  # (rows, cols, cat) on a second gray line, as in tab:accuracy-on-spaa-datasets

r = pd.read_csv(RES)
p = r.pivot_table(index=["dataset", "fold"], columns="arm", values="test_auc")
assert p.notna().all().all() and (p.groupby("dataset").size() == 5).all(), "every dataset needs 5 folds, both arms"
p["d"] = p.native - p.ordinal
g = p.groupby("dataset").agg(o=("ordinal", "mean"), n=("native", "mean"), d=("d", "mean"), w=("d", lambda x: (x > 0).sum()))
g = g.sort_values("d", ascending=False)
f3 = lambda v: f"{v:.4f}".lstrip("0")  # noqa: E731
f3s = lambda v: ("+" if v >= 0 else "$-$") + f"{abs(v):.4f}".lstrip("0")  # noqa: E731
lines = [r"% auto-generated by benchmarks/src/distributed_spo_gbt/paper/tables/make_ordinal_vs_native_table.py -- regenerate, do not hand-edit",
         f"% source: {RES.relative_to(ROOT)}", r"\begin{tabular}{lrrrr}", r"\toprule",
         r"Dataset & Ordinal & Native & $\Delta$ & Native wins \\", r"\midrule"]
for ds, x in g.iterrows():
    lines.append(f"{mpt.ds_label(ds)} & {f3(x.o)} & {f3(x.n)} & {f3s(x.d)} & {int(x.w)}/5 \\\\")
lines += [r"\midrule", f"Mean & {f3(g.o.mean())} & {f3(g.n.mean())} & {f3s(g.d.mean())} & {int(g.w.sum())}/{5 * len(g)} \\\\",
          r"\bottomrule", r"\end{tabular}"]
OUT.write_text("\n".join(lines) + "\n")
print(OUT)
