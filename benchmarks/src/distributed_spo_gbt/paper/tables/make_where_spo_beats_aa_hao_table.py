#!/usr/bin/env python3
"""tab:accuracy-where-spo-outperforms-aa body (tabular only), Hao settings (user request 2026-11-21).
Rows = kdd28_hao rows passing the recommended "SPO clearly beats AA" rule (select_spo_clearly_beats_aa.py), per suite.
SPO columns = kdd28_hao seeds 1-5. AA columns = kdd28_ydf (Hao's settings do not touch AA). Empty cell = not run yet.
Cell = mean over seeds of the fold-averaged score, +- = sample std over seeds of that score (hv.stats, since 2026-11-21).
The mean figures show means only. Run from the repo root."""
import argparse, pathlib, sys
import pandas as pd

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import make_hao_vs_ydf_compare_tables as hv  # noqa: E402  (inputs, loaders, cell format)
import make_paper_tables as mpt  # noqa: E402
kdd28 = hv.kdd28

WS = (1, 4, 8, 16, 32)
DX = hv.R / "2026-11-21_where_spo_beats_aa_cc18_reg_distributed"  # distributed CC18 + regression cells (2026-11-21)
DIST = {t: {**{f"ydf_s{s}": (hv.YDF, DX / f"{hv.YDF}/seed{s}/{t}/results.csv", ["distacc_aa"]) for s in hv.SEEDS},
            **{f"hao_s{s}": (hv.HAO, DX / f"{hv.HAO}/seed{s}/{t}/results.csv", ["distacc_spo"]) for s in hv.SEEDS}}
        for t in ("cc18_dist", "reg_dist")}
WA = hv.R / "2026-11-21_wide_eval_ydf_aa_seeds2to5"  # kdd28_ydf AA seeds 2-5 on the wide rows (2026-11-21)
WIDE_AA = {f"ydf_s{s}_{p}": (hv.YDF, WA / f"seed{s}/{p}/distacc/results.csv", ["distacc_single_aa", "distacc_aa"])
           for s in (2, 3, 4, 5) for p in ("philippine", "epsilon", "epsilon_w1")}
COLS = ([("AA+SPO-GBT single machine", "hao", "single:AA+SPO", None), ("SPO-GBT single machine", "hao", "single:SPO", None)]
        + [(f"$W{{=}}{w}$", "hao", f"{w}:SPO", "single:SPO") for w in WS]
        + [("AA-GBT single machine", "ydf", "single:AA", None)] + [(f"$W{{=}}{w}$", "ydf", f"{w}:AA", "single:AA") for w in WS])
GEN = "% auto-generated by benchmarks/src/distributed_spo_gbt/paper/tables/make_where_spo_beats_aa_hao_table.py -- regenerate, do not hand-edit\n"


def sec(x):
    return f"{x:,.0f}".replace(",", "{,}") if x >= 10 else f"{x:.1f}"


def cell(r, bold, rmse, pre):
    return hv.cell(r, bold, pre, rmse)  # one line per row: mean$_{\pm std}$


def spo_matches_aa(arm, ds):
    """Distributed SPO arm with W >= F: each worker holds at most one column, so SPO = AA splits."""
    w, fam = arm.split(":")
    return fam == "SPO" and w.isdigit() and int(w) >= mpt.SHAPES[ds][1]


def block_rows(stats, folds, by_source, mean_name, scale):
    """stats: column label -> per-dataset stats or None (never run). Missing cells stay empty."""
    rmse, ncol, rows = scale is not None, len(COLS), []
    get = lambda c, ds: stats[c].loc[ds] if stats[c] is not None and ds in stats[c].index else None  # noqa: E731
    for src, datasets in by_source:
        rows.append(mpt.source_row(src, ncol + 1))
        for ds in datasets:
            rs = [get(i, ds) for i in range(ncol)]
            best = (min if rmse else max)(r["mean"] for r in rs if r is not None)
            out = []
            for i, ((_, _, _, ref), r) in enumerate(zip(COLS, rs)):
                if r is None:
                    out.append("")
                    continue
                if r["count"] != folds[ds]:
                    sys.exit(f"ERROR: {ds} col {i}: {int(r['count'])} folds, suite has {folds[ds]}")
                rr = get([c[2] for c in COLS].index(ref), ds) if ref else None
                pre = mpt._delta_color(hv.delta(r["mean"], rr["mean"], rmse)) if rr is not None else ""
                if spo_matches_aa(COLS[i][2], ds):  # <=1 column per worker: SPO projections are single features
                    pre = mpt.PURPLE
                out.append(cell(r, r["mean"] == best, rmse, pre))
            rows.append(mpt.ds_label(ds) + " & " + " & ".join(out) + r" \\")
    alld = [d for _, ds in by_source for d in ds]
    full = [stats[i] is not None and set(alld) <= set(stats[i].index) for i in range(ncol)]
    f = (lambda s: (s.loc[alld, "mean"] / pd.Series(scale)[alld]).mean()) if rmse else (lambda s: s.loc[alld, "mean"].mean())
    avg = [round(f(stats[i]), 4) if full[i] else None for i in range(ncol)]
    top = (min if rmse else max)(v for v in avg if v is not None)
    mc = []
    for i, (v, (_, _, _, ref)) in enumerate(zip(avg, COLS)):
        rv = avg[[c[2] for c in COLS].index(ref)] if ref else None
        mc.append("" if v is None else (mpt._delta_color(hv.delta(v, rv, rmse)) if rv is not None else "")
                  + (r"\textbf{%s}" if v == top else "%s") % f"{v:.4f}"[(0 if v >= 1 else 1):])
    return rows + [r"\midrule", mean_name + " & " + " & ".join(mc) + r" \\",
                   "Mean time (s) & " + " & ".join(sec(stats[i].loc[alld, "time"].mean()) if full[i] else "" for i in range(ncol)) + r" \\"]


MEANS = "benchmarks/results/kdd28/floats/accuracy/tab-accuracy-where-spo-outperforms-aa/derived/single_machine_means.csv"
FIG_GEN = GEN.replace("regenerate", "figure body; regenerate")


def mean_figure(parts, rmse, ylabel):
    """Mean over every dataset of `parts` [(stats list, datasets, scale)] per column, over W (tikzpicture only).
    Distributed SPO/AA as lines, single-machine SPO, AA, AA+SPO as flat references."""
    def avg(i):
        v = [(st[i].loc[d, "mean"] / (sc[d] if sc else 1)) for st, ds, sc in parts for d in ds]
        return sum(v) / len(v)
    lab = {c[2]: i for i, c in enumerate(COLS)}
    xs = [str(w) for w in WS]
    lines = [r"\begin{tikzpicture}", r"\begin{axis}[width=0.5\textwidth, height=4.6cm, YLIM symbolic x coords={" + ",".join(xs)
             + "}, xtick=data,", "  xticklabels={" + ",".join(f"$W{{=}}{w}$" for w in xs) + "}, ylabel={" + ylabel + "},",
             r"  yticklabel style={/pgf/number format/fixed, /pgf/number format/precision=3, /pgf/number format/fixed zerofill},",
             r"  tick label style={font=\footnotesize}, label style={font=\footnotesize}, tick style={draw=none},",
             r"  legend style={font=\scriptsize, at={(0.5,1.03)}, anchor=south, draw=none,"
             r" /tikz/every even column/.append style={column sep=6pt}}, legend columns=2, legend cell align=left]"]
    vals = []
    for fam, col, mark, style in (("SPO", "378ADD", "*", ""), ("AA", "D85A30", "diamond*", ", dashed")):
        m = [avg(lab[f"{w}:{fam}"]) for w in WS]
        vals += m
        lines += [rf"\addplot[color={mpt._rgb(col)}, mark={mark}, thick{style}] coordinates {{"
                  + " ".join(f"({x},{v:.4f})" for x, v in zip(xs, m)) + "};", rf"\addlegendentry{{{fam}-GBT}}"]
    refs = [(f, c, avg(lab[a])) for f, c, a in (("SPO-GBT", "378ADD", "single:SPO"), ("AA-GBT", "D85A30", "single:AA"),
                                                  ("AA+SPO-GBT", "5A9E3C", "single:AA+SPO"))]
    vals += [v for _, _, v in refs]
    for f, c, v in refs:
        lines += [rf"\addplot[color={mpt._rgb(c)}, thick, densely dotted, no marks] coordinates {{({xs[0]},{v:.4f}) ({xs[-1]},{v:.4f})}};",
                  rf"\addlegendentry{{single-machine {f}}}"]
    lo, hi = min(vals), max(vals)
    lines[1] = lines[1].replace("YLIM ", f"ymin={lo - 0.1 * (hi - lo):.4f}, ymax={hi + 0.1 * (hi - lo):.4f}, ")
    return "\n".join(lines + [r"\end{axis}", r"\end{tikzpicture}"]) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(hv.OUT))
    ap.add_argument("--beats_aa", default=hv.FLOAT + "/derived/spo_clearly_beats_aa_per_dataset.csv")
    ap.add_argument("--profile_rows", default=hv.HAO, help="profile whose pass_rec rows make the table")
    ap.add_argument("--means_csv", default=MEANS, help="per-dataset single-machine SPO/AA means (read by the colrep figure)")
    ap.add_argument("--arraystretch", type=float, default=0.8, help="row height factor (local to the float's minipage)")
    ap.add_argument("--automl_eval_suite", default="kdd28_wide_real_candidates",
                    help="AutoML block (the wide real-dataset screen's selected sets), empty string = no block")
    a = ap.parse_args()
    sel = pd.read_csv(hv.ROOT / a.beats_aa)
    sel = sel[(sel.profile == a.profile_rows) & sel.pass_rec]
    pick = {s: sorted(g.dataset, key=str.lower) for s, g in sel.groupby("suite")}
    if "multiclass" in pick:
        sys.exit("ERROR: multiclass rows pass, the table has no multiclass block yet")
    S = hv.SEEDS
    suites = {"spaa": "kdd28_tabarena33", "wide": "kdd28_wide_datasets", "cc18": "kdd28_cc18_10fold", "regression": "kdd28_regression"}
    blocks = []
    def dist_frame(t, side, single):  # distributed cells cover only this table's rows: coverage over those
        kdd28._EVAL["subset"] = set(pick["cc18" if t == "cc18_dist" else "regression"])
        x = hv.load_all(DIST[t], side)
        kdd28._EVAL["subset"] = None
        return pd.concat([single, x])
    # AutoML sets (2026-11-23, user request): rows of the screen's selection, only cells already run (Hao single SPO,
    # SPO W = 4-32 at r = 0, YDF single AA). AA+SPO, SPO W = 1 and distributed AA stay empty. Not in the mean figure.
    # Loaded first so the setup comments keep naming the last suite declared below.
    _, ads, ay, ah, afolds = hv.load_automl(a.automl_eval_suite) if a.automl_eval_suite else (None, [], None, None, {})
    if "spaa" in pick or "wide" in pick:
        kdd28._declare_eval(suites["spaa"], __file__)
        y = hv.per_seed(hv.load_all(hv.INPUTS, "ydf"), list(S))
        h = hv.per_seed(pd.concat([hv.load(hv.INPUTS, "hao"), hv.load(hv.INPUTS, "hao_aaspo")]), list(S))
        kdd28._declare_eval(suites["wide"], __file__)
        kdd28._EVAL["subset"] = set(pick.get("wide", []))  # seeds 2-5 cover only this table's wide rows
        wa = pd.concat([pd.read_csv(v[1]) for v in WIDE_AA.values()])  # one check over all files: each covers one dataset
        wa = wa[wa.rc == 0]
        kdd28.check_frame(wa, hv.YDF, ["distacc_single_aa", "distacc_aa"], "wide AA seeds 2-5")
        kdd28._EVAL["subset"] = None
        wy = hv.load_all(hv.WIDE_INPUTS, "ydf")
        wy = hv.per_seed(pd.concat([wy[wy.arm.str.endswith(":AA") & wy.dataset.isin(pick.get("wide", []))], wa]), list(S))
        wh = hv.per_seed(pd.concat([hv.load(hv.WIDE_INPUTS, "hao"), hv.load(hv.WIDE_INPUTS, "hao_aaspo")]), list(S))
    if "cc18" in pick:
        kdd28._declare_eval(suites["cc18"], __file__)
        cy, ch = (hv.per_seed(dist_frame("cc18_dist", s, hv.load_all(hv.CC18_INPUTS, s, hv.CC18_ARM)), list(S))
                  for s in ("ydf", "hao"))
    if "regression" in pick:
        kdd28._declare_eval(suites["regression"], __file__)
        ry, rh = (hv.per_seed(dist_frame("reg_dist", s, hv.load_all(hv.REG_INPUTS, s)), list(S), "test_rmse")
                  for s in ("ydf", "hao"))
    fold_n =lambda s: {d: len(f) for d, f in hv.evalsuite.load_suite(suites[s])["datasets"].items()}  # noqa: E731

    def stats_of(yf, hf):
        frames = {"ydf": yf, "hao": hf}
        return [hv.stats(frames[p], arm) if (frames[p].arm == arm).any() else None for _, p, arm, _ in COLS]

    def shapes(s, w=None):
        mpt.SHAPES.clear(), mpt.CATS.clear()
        if s in ("cc18", "regression"):
            pre = "cc18" if s == "cc18" else "extra"
            hv.set_shapes(f"{hv.FLOAT}/derived/{pre}_shapes.csv", f"{hv.FLOAT}/derived/{pre}_categoricals.csv")
        else:
            hv.set_shapes(mpt.SHAPES_CSV, mpt.CATS_CSV)
            hv.set_shapes(hv.WIDE_SHAPES, mpt.CATS_CSV, set(w))
    rows, cls_parts, reg_parts = [], [], []
    if "spaa" in pick:
        shapes("spaa", pick.get("wide", []))
        cls_parts.append((stats_of(y, h), pick["spaa"], None))
        rows += block_rows(stats_of(y, h), fold_n("spaa"), mpt.sources(pick["spaa"]), f"Mean ({len(pick['spaa'])} SPAA datasets)", None)
    if "wide" in pick:
        shapes("wide", pick["wide"])
        cls_parts.append((stats_of(wy, wh), pick["wide"], None))
        rows += ([r"\midrule"] if rows else []) + block_rows(
            stats_of(wy, wh), fold_n("wide"), mpt.sources(pick["wide"]), f"Mean ({len(pick['wide'])} wide datasets)", None)
    if "cc18" in pick:
        shapes("cc18")
        cls_parts.append((stats_of(cy, ch), pick["cc18"], None))
        rows += [r"\midrule"] + block_rows(stats_of(cy, ch), fold_n("cc18"), [("OpenML CC18 (10 CV folds)", pick["cc18"])],
                                           f"Mean ({len(pick['cc18'])} CC18 datasets)", None)
    if ads:
        mpt.SHAPES.clear(), mpt.CATS.clear()
        hv.automl_shapes(ads)
        rows += [r"\midrule"] + block_rows(stats_of(ay, ah), afolds,
                                           [(r"OpenML AutoML Benchmark ${\ge}100$ columns (5 CV folds)", ads)],
                                           f"Mean ({len(ads)} AutoML datasets)", None)
    if "regression" in pick:
        shapes("regression")
        std = pd.read_csv(hv.ROOT / hv.FLOAT / "derived/extra_label_std.csv").set_index("dataset")["label_std"].to_dict()
        reg_parts.append((stats_of(ry, rh), pick["regression"], std))
        rows += [r"\midrule"] + block_rows(stats_of(ry, rh), fold_n("regression"),
                                           [(r"Regression (test RMSE, lower is better)", pick["regression"])],
                                           f"Mean RMSE / label std ({len(pick['regression'])} datasets)", std)
    pb = lambda t: r"\multicolumn{1}{c}{\parbox[b]{1.0cm}{\centering " + t + "}}"  # noqa: E731
    hdr_cells = [pb(lab) if "single" in lab else r"\multicolumn{1}{c}{" + lab + "}" for lab, _, _, _ in COLS]
    n = len(COLS)
    head = [r"\renewcommand{\arraystretch}{%g}%%" % a.arraystretch, r"\resizebox{\linewidth}{!}{%", r"\begin{tabular}{lrr|rrrrr|r|rrrrr}", r"\toprule",
            r" & \multicolumn{2}{c}{} & \multicolumn{5}{c}{SPO-GBT dist.} & \multicolumn{1}{c}{} & \multicolumn{5}{c}{AA-GBT dist.} \\",
            r"\cmidrule(lr){4-8}\cmidrule(lr){10-14}", "Dataset & " + " & ".join(hdr_cells) + r" \\", r"\midrule"]
    assert n == 13
    src = ("% source: IN-PROCESS reruns (workers = threads of one process). SPO = kdd28_hao seeds 1-5, AA = kdd28_ydf seeds 1-5 "
           "(wide: seed 1 + runs/2026-11-21_wide_eval_ydf_aa_seeds2to5). Rows: " + a.profile_rows + " pass_rec in " + a.beats_aa + "\n% inputs: " + hv.rel(hv.INPUTS) + " + "
           + hv.rel(hv.WIDE_INPUTS) + " + " + hv.rel(hv.CC18_INPUTS) + " + " + hv.rel(hv.REG_INPUTS) + " + "
           + " + ".join(hv.rel(DIST[t]) for t in DIST) + "\n")
    asrc = f"% AutoML block: eval suite {a.automl_eval_suite} (subset {', '.join(ads)}), {hv.rel(hv.AUTOML_INPUTS)}\n" if ads else ""
    setup = kdd28.setup_line(hv.HAO, ["distacc_single_spo", "distacc_single_aa_spo", "distacc_spo"]) + "\n" + \
        kdd28.setup_line(hv.YDF, ["distacc_single_aa", "distacc_aa"])
    out = pathlib.Path(a.out) / "table_dist_accuracy_where_spo_outperforms_aa_body.tex"
    out.write_text(kdd28.add_setup(GEN + hv.PM + src + asrc + "\n".join(head + rows + [r"\bottomrule", r"\end{tabular}}"]) + "\n", setup))
    print(f"wrote {out}: " + ", ".join(f"{s} {len(v)}" for s, v in pick.items()))
    lab = {c[2]: i for i, c in enumerate(COLS)}  # same cells as the table's single-machine columns
    cc18 = [p[0] for p in cls_parts[-1:]] if "cc18" in pick else []  # renamed as in select_where_spo_beats_aa_hao.py
    pd.DataFrame([{"dataset": d + (" (CC18)" if any(st is s for s in cc18) else ""), "task": task, "single_spo": st[lab["single:SPO"]].loc[d, "mean"],
                   "single_aa": st[lab["single:AA"]].loc[d, "mean"]}
                  for task, parts in (("cls", cls_parts), ("reg", reg_parts)) for st, ds, _ in parts for d in ds]
                 ).to_csv(hv.ROOT / a.means_csv, index=False, float_format="%.10g")
    print(f"wrote {a.means_csv}")
    fig = pathlib.Path(a.out).parent / "figures" / "evaluation"
    for name, parts, rmse, yl in (("accuracy", cls_parts, False, "Mean test ROC AUC"),
                                  ("rmse", reg_parts, True, "Mean test RMSE / label std")):
        if parts:
            f = fig / f"fig_dist_{name}_mean_where_spo_outperforms_aa_body.tex"
            f.write_text(kdd28.add_setup(FIG_GEN + src + mean_figure(parts, rmse, yl), setup))
            print(f"wrote {f}: {sum(len(p[1]) for p in parts)} datasets")


if __name__ == "__main__":
    main()
