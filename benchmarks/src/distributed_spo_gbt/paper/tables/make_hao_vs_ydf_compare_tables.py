#!/usr/bin/env python3
"""Hao vs YDF parameter comparison table BODIES (tabular only) for sec:accuracy-hao-vs-ydf-params:
tab:accuracy-hao-vs-ydf-params-single-machine and tab:accuracy-hao-vs-ydf-params-distributed.
YDF columns = kdd28_ydf seed 1, Hao columns = kdd28_hao mean over seeds 1-5. Run from the repo root."""
import argparse, pathlib, sys
import pandas as pd

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "params"))
sys.path.insert(0, str(HERE))
import params as kdd28  # noqa: E402
import evalsuite  # noqa: E402
import make_paper_tables as mpt  # noqa: E402  (ds_label, _delta_color, shapes/categoricals)

ROOT = HERE.parents[4]
A = ROOT / "benchmarks/results/kdd28/accuracy"
OUT = ROOT / "paper/distributed_spo_gbt_kdd28/tables"
YDF, HAO = "kdd28_ydf", "kdd28_hao"
INPUTS = {  # (profile, csv, profile arms in it)
    "ydf": (YDF, A / "tab-accuracy-on-spaa-datasets/distacc/results.csv",
            ["distacc_single_spo", "distacc_single_aa", "distacc_spo", "distacc_aa"]),
    "ydf_aaspo": (YDF, A / "tab-accuracy-on-spaa-datasets/distacc_aaspo/distacc_aaspo.csv", ["distacc_single_aa_spo"]),
    "hao": (HAO, A / "tab-accuracy-hao-vs-ydf-params/distacc/results.csv",
            ["distacc_single_spo", "distacc_single_aa", "distacc_spo", "distacc_aa"]),
    "hao_aaspo": (HAO, A / "tab-accuracy-hao-vs-ydf-params/distacc_aaspo/results.csv", ["distacc_single_aa_spo"]),
}
HDR = ("% auto-generated by benchmarks/src/distributed_spo_gbt/paper/tables/make_hao_vs_ydf_compare_tables.py -- regenerate, do not hand-edit\n"
       "% source: IN-PROCESS reruns, YDF = kdd28_ydf seed 1, Hao = kdd28_hao mean over seeds 1-5, SPAA paper eval, "
       + " + ".join(str(v[1].relative_to(ROOT / "benchmarks")) for v in INPUTS.values()) + "\n")


def load(key):
    """rc==0 rows, stamp-checked against the profile and the declared eval suite (exit 2 on drift or gaps)."""
    prof, path, arms = INPUTS[key]
    x = pd.read_csv(path)
    x = x[x.rc == 0]
    kdd28.check_frame(x, prof, arms, path.name)
    return x


def per_fold(x, seeds):
    """(dataset, fold, arm) -> metric mean over exactly `seeds` (exit 2 otherwise)."""
    got = x.groupby(["dataset", "fold", "arm"]).seed.agg(lambda v: sorted(int(t) for t in v))
    bad = got[got.map(lambda v: v != seeds)]
    if len(bad):
        sys.exit(f"ERROR: {len(bad)} cells lack seeds {seeds} or repeat one, e.g. {bad.index[0]}: {bad.iloc[0]}")
    return x.groupby(["dataset", "fold", "arm"], as_index=False)[["test_auc", "train_s"]].mean()


def stats(f, arm):
    """dataset -> mean/std/count of test AUC over folds of one arm, and time = mean train_s over folds."""
    g = f[f.arm == arm].groupby("dataset")
    return g.test_auc.agg(["mean", "std", "count"]).assign(time=g.train_s.mean())


def sources(datasets):
    """[(benchmark, datasets)]: TabArena = its binary manifest, TabReD = download_tabred_datasets.DATASETS."""
    import ast, json
    data = ROOT / "benchmarks/data"
    arena = {e["dataset_name"] for e in json.loads((data / "tabarena_binary_manifest.json").read_text())["entries"]
             if e["status"] == "ok"}
    tree = ast.parse((data / "download_tabred_datasets.py").read_text())
    red = next(set(ast.literal_eval(n.value)) for n in tree.body
               if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "DATASETS")
    bad = [d for d in datasets if (d in arena) == (d in red)]
    if bad:
        sys.exit(f"ERROR: datasets in neither or both of TabArena/TabReD: {bad}")
    return [("TabArena", [d for d in datasets if d in arena]), ("TabReD", [d for d in datasets if d in red])]


def cell(r, bold, pre=""):
    mu = f"{r['mean']:.4f}"[1:]
    sd = r"$_{\pm" + f"{r['std']:.4f}"[1:] + "}$" if r["count"] > 1 else r"\phantom{$_{\pm.0000}$}"
    c = (r"{\boldmath\textbf{" + mu + sd + "}}" if r["count"] > 1 else r"\textbf{" + mu + "}" + sd) if bold else mu + sd
    return pre + c


def body(groups, folds, by_source, mean_rows, setup):
    """groups: [(top label, [(sub label, stats or None, YDF stats to color against or None)])].
    by_source: [(benchmark, datasets)], each block under an italic benchmark row."""
    cols = [c for _, cs in groups for c in cs]
    head = [r"\resizebox{\linewidth}{!}{%", r"\begin{tabular}{l" + "".join("|" + "r" * len(cs) for _, cs in groups) + "}",
            r"\toprule"]
    top, rules, j = [], [], 2
    for lab, cs in groups:
        top.append(r"\multicolumn{%d}{c}{%s}" % (len(cs), lab)); rules.append(r"\cmidrule(lr){%d-%d}" % (j, j + len(cs) - 1))
        j += len(cs)
    head += [" & " + " & ".join(top) + r" \\", "".join(rules),
             "Dataset & " + " & ".join(r"\multicolumn{1}{c}{" + s + "}" for s, _, _ in cols) + r" \\", r"\midrule"]
    rows = []
    for src, datasets in by_source:
        rows.append(r"\multicolumn{%d}{@{}l}{\textit{%s}} \\" % (len(cols) + 1, src))
        for ds in datasets:
            have = [s.loc[ds, "mean"] for _, s, _ in cols if s is not None and ds in s.index]
            best, out = max(have), []
            for _, s, ref in cols:
                if s is None or ds not in s.index:
                    out.append("--"); continue
                r = s.loc[ds]
                if r["count"] != folds[ds]:
                    sys.exit(f"ERROR: {ds}: {int(r['count'])} folds, suite has {folds[ds]}")
                pre = mpt._delta_color((r["mean"] - ref.loc[ds, "mean"]) * 1e3) if ref is not None and ds in ref.index else ""
                out.append(cell(r, r["mean"] == best, pre))
            rows.append(mpt.ds_label(ds) + " & " + " & ".join(out) + r" \\")
    tail = [r"\midrule"]
    for name, sub in mean_rows:  # mean over `sub` datasets, -- where a column lacks one of them
        avg = [round(s.loc[sub, "mean"].mean(), 4) if s is not None and set(sub) <= set(s.index) else None for _, s, _ in cols]
        refm = [round(r.loc[sub, "mean"].mean(), 4) if r is not None and set(sub) <= set(r.index) else None
                for _, _, r in cols]
        top_v = max(v for v in avg if v is not None)
        tail.append(name + " & " + " & ".join(
            "--" if v is None else (mpt._delta_color((v - rv) * 1e3) if rv is not None else "")
            + (r"\textbf{%s}" if v == top_v else "%s") % f"{v:.4f}"[1:] for v, rv in zip(avg, refm)) + r" \\")
    alld = [d for _, ds in by_source for d in ds]  # mean over datasets of the per-dataset mean train_s
    sec = lambda x: f"{x:,.0f}".replace(",", "{,}") if x >= 10 else f"{x:.1f}"
    tail.append("Mean time (s) & " + " & ".join(sec(s.loc[alld, "time"].mean()) for _, s, _ in cols) + r" \\")
    tail += [r"\bottomrule", r"\end{tabular}}"]
    return kdd28.add_setup(HDR + "\n".join(head + rows + tail) + "\n", setup)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--eval_suite", default="kdd28_tabarena33", type=lambda s: kdd28._declare_eval(s, __file__))
    ap.add_argument("--dataset_shapes", default=mpt.SHAPES_CSV)
    ap.add_argument("--dataset_categoricals", default=mpt.CATS_CSV)
    a = ap.parse_args()
    sh = pd.read_csv(ROOT / a.dataset_shapes).drop_duplicates("dataset").set_index("dataset")
    mpt.SHAPES = {d: (int(r.rows), int(r.features)) for d, r in sh.iterrows()}
    ca = pd.read_csv(ROOT / a.dataset_categoricals).set_index("dataset")
    mpt.CATS = {d: (int(r.categorical), int(r.features)) for d, r in ca.iterrows()}
    spec = evalsuite.load_suite(a.eval_suite)
    folds = {d: len(f) for d, f in spec["datasets"].items()}
    ydf_seeds = [1]  # kdd28_ydf accuracy rows were run at seed 1 only (eval_suites.json seed_protocol)
    hao_seeds = sorted(int(s) for s in kdd28.load_profile(HAO)["seeds"])
    y = per_fold(pd.concat([load("ydf"), load("ydf_aaspo")]), ydf_seeds)
    h = per_fold(pd.concat([load("hao"), load("hao_aaspo")]), hao_seeds)
    ds = sorted(spec["datasets"])
    by_src = sources(ds)
    S = lambda f, arm: stats(f, arm)
    n = lambda k: f"{k} seed" + ("s" if k > 1 else "")
    Y, H = rf"\shortstack{{YDF\\{n(len(ydf_seeds))}}}", rf"\shortstack{{Hao\\{n(len(hao_seeds))}}}"
    single = [("SPO-GBT", [(Y, S(y, "single:SPO"), None), (H, S(h, "single:SPO"), S(y, "single:SPO"))]),
              ("AA+SPO-GBT", [(Y, S(y, "single:AA+SPO"), None), (H, S(h, "single:AA+SPO"), S(y, "single:AA+SPO"))]),
              ("AA-GBT", [(Y, S(y, "single:AA"), None), (H, S(h, "single:AA"), S(y, "single:AA"))])]
    dist = [(f"SPO-GBT dist.\\ $W{{=}}{w}$", [(Y, S(y, f"{w}:SPO"), None), (H, S(h, f"{w}:SPO"), S(y, f"{w}:SPO"))])
            for w in (1, 4, 8, 16, 32)]
    dist.append((r"AA-GBT dist.\ $W{=}4$", [(Y, S(y, "4:AA"), None), (H, S(h, "4:AA"), S(y, "4:AA"))]))
    arms = ["distacc_single_spo", "distacc_single_aa", "distacc_single_aa_spo", "distacc_spo", "distacc_aa"]
    setup = kdd28.setup_line(YDF, arms) + "\n" + kdd28.setup_line(HAO, arms)
    out = pathlib.Path(a.out); out.mkdir(parents=True, exist_ok=True)
    (out / "table_accuracy_hao_vs_ydf_params_single_machine_body.tex").write_text(
        body(single, folds, by_src, [("Mean", ds)], setup))
    mpt.SHAPE_BELOW = True  # 12 numeric columns: shape under the name keeps the font readable
    (out / "table_accuracy_hao_vs_ydf_params_distributed_body.tex").write_text(
        body(dist, folds, by_src, [("Mean", ds)], setup))
    print(f"wrote 2 bodies under {out} ({len(ds)} datasets)")


if __name__ == "__main__":
    main()
