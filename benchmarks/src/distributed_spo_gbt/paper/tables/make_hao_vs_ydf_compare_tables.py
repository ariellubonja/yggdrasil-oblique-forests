def seeds_text(s):
    return f"seed {s[0]}" if len(s) == 1 else "seeds " + (f"{s[0]}-{s[-1]}" if s == list(range(s[0], s[-1] + 1)) else ",".join(map(str, s)))


def load(inputs, key, arm_map=None):
    """rc==0 rows, stamp-checked against the profile and the declared eval suite (exit 2 on drift or gaps)."""
    prof, path, arms = inputs[key]
    x = pd.read_csv(path)
    x = x[x.rc == 0]
    if prof == HAO and arm_map:  # Hao AA cells (identical to YDF AA) are never shown
        x = x[x.arm.map(arm_map) != "single:AA"]
    kdd28.check_frame(x, prof, arms, path.name)
    return x.assign(arm=x.arm.map(arm_map)) if arm_map else x


def load_all(inputs, side, arm_map=None):
    return pd.concat([load(inputs, k, arm_map) for k in inputs if k.startswith(side)])


def per_fold(x, seeds, metric="test_auc"):
    """(dataset, fold, arm) -> metric mean over exactly `seeds` (exit 2 otherwise)."""
    got = x.groupby(["dataset", "fold", "arm"]).seed.agg(lambda v: sorted(int(t) for t in v))
    bad = got[got.map(lambda v: v != seeds)]
    if len(bad):
        sys.exit(f"ERROR: {len(bad)} cells lack seeds {seeds} or repeat one, e.g. {bad.index[0]}: {bad.iloc[0]}")
    return x.groupby(["dataset", "fold", "arm"], as_index=False)[[metric, "train_s"]].mean().rename(columns={metric: "m"})


def stats(f, arm):
    """dataset -> mean/std/count of the metric over folds of one arm, and time = mean train_s over folds."""
    g = f[f.arm == arm].groupby("dataset")
    return g.m.agg(["mean", "std", "count"]).assign(time=g.train_s.mean())


def num(v, rmse, dec=None):
    """AUC: .xxxx (1.0000 kept whole). RMSE: 4 significant digits, or `dec` decimals (the std follows its mean)."""
    if not rmse:
        t = f"{v:.4f}"
        return t[1:] if t.startswith("0.") else t
    if dec is not None:
        return f"{v:,.{dec}f}".replace(",", "{,}")
    return f"{v:,.0f}".replace(",", "{,}") if abs(v) >= 1000 else f"{v:#.4g}".rstrip(".")


def cell(r, bold, pre="", rmse=False):
    mu = num(r["mean"], rmse)
    dec = (len(mu.split(".")[1]) if "." in mu else 0) if rmse else None
    sd = (r"$_{\pm" + num(r["std"], rmse, dec) + "}$") if r["count"] > 1 else r"\phantom{$_{\pm.0000}$}"
    c = (r"{\boldmath\textbf{" + mu + sd + "}}" if r["count"] > 1 else r"\textbf{" + mu + "}" + sd) if bold else mu + sd
    return pre + c


def delta(v, ref, rmse):
    """Color value: AUC gain in 1e-3, RMSE reduction in % of the YDF RMSE (blue = Hao better)."""
    return (ref - v) / ref * 100 if rmse else (v - ref) * 1e3


def mean_row(name, cols, sub, scale=None, pad=0):
    """Mean over `sub` per column, colored against its YDF column. scale: dataset -> label std (mean RMSE / std)."""
    f = (lambda s: (s.loc[sub, "mean"] / pd.Series(scale)[sub]).mean()) if scale else (lambda s: s.loc[sub, "mean"].mean())
    avg = [round(f(s), 4) if s is not None and set(sub) <= set(s.index) else None for s, _ in cols]
    refm = [round(f(r), 4) if r is not None and set(sub) <= set(r.index) else None for _, r in cols]
    top_v = (min if scale else max)(v for v in avg if v is not None)
    return name + " & " + " & ".join(
        "--" if v is None else (mpt._delta_color(delta(v, rv, bool(scale))) if rv is not None else "")
        + (r"\textbf{%s}" if v == top_v else "%s") % f"{v:.4f}"[(0 if v >= 1 else 1):] for v, rv in zip(avg, refm)) + " &" * pad + r" \\"


def load_checks(path):
    """(profile, suite, dataset) -> passes the recommended "SPO clearly beats AA" rule (select_spo_clearly_beats_aa.py)."""
    x = pd.read_csv(ROOT / path)
    return {(r.profile, r.suite, r.dataset): bool(r.pass_rec) for r in x.itertuples()}


def body(hdr, groups, blocks, joint, setup, stretch=1.0, checks=None):
    """groups: [(top label, [sub labels])]. blocks: [(cols, folds, by_source, mean label, scale)], cols = [(stats,
    YDF stats to color against or None)] in header order, by_source = [(italic heading, datasets)], scale = None (AUC)
    or dataset -> label std (RMSE, lower is better). Each block ends with its mean and mean-time rows. joint: label of
    a mean over every block's datasets, or None. checks: load_checks() dict, adds a YDF/Hao check-mark column group
    keyed by each block's suite (6th block field)."""
    ncol = sum(len(cs) for _, cs in groups)
    if checks is not None:
        groups = groups + [(r"\shortstack{SPO clearly\\beats AA}", ["YDF", "Hao"])]
    nchk = 2 if checks is not None else 0
    head = [r"\renewcommand{\arraystretch}{%g}%%" % stretch] if stretch != 1 else []  # local to the float's minipage
    head += [r"\resizebox{\linewidth}{!}{%", r"\begin{tabular}{l" + "".join("|" + ("c" if checks is not None and gi == len(groups) - 1 else "r") * len(cs)
                                     for gi, (_, cs) in enumerate(groups)) + "}",
             r"\toprule"]
    top, rules, j = [], [], 2
    for lab, cs in groups:
        top.append(r"\multicolumn{%d}{c}{%s}" % (len(cs), lab))
        rules.append(r"\cmidrule(lr){%d-%d}" % (j, j + len(cs) - 1))
        j += len(cs)
    head += [" & " + " & ".join(top) + r" \\", "".join(rules),
             "Dataset & " + " & ".join(r"\multicolumn{1}{c}{" + s + "}" for _, cs in groups for s in cs) + r" \\",
             r"\midrule"]
    rows = []
    sec = lambda x: f"{x:,.0f}".replace(",", "{,}") if x >= 10 else f"{x:.1f}"  # noqa: E731
    for bi, (cols, folds, by_source, mean_name, scale, suite) in enumerate(blocks):
        assert len(cols) == ncol
        rmse = scale is not None
        if bi:
            rows.append(r"\midrule")
        for src, datasets in by_source:
            rows.append(mpt.source_row(src, ncol + nchk + 1))
            for ds in datasets:
                have = [s.loc[ds, "mean"] for s, _ in cols if s is not None and ds in s.index]
                best, out = (min if rmse else max)(have), []
                for s, ref in cols:
                    if s is None or ds not in s.index:
                        out.append("--")
                        continue
                    r = s.loc[ds]
                    if r["count"] != folds[ds]:
                        sys.exit(f"ERROR: {ds}: {int(r['count'])} folds, suite has {folds[ds]}")
                    pre = mpt._delta_color(delta(r["mean"], ref.loc[ds, "mean"], rmse)) if ref is not None and ds in ref.index else ""
                    out.append(cell(r, r["mean"] == best, pre, rmse))
                if checks is not None:
                    for prof in (YDF, HAO):
                        if (prof, suite, ds) not in checks:
                            sys.exit(f"ERROR: {prof} {suite} {ds}: no row in the SPO-beats-AA selection")
                        out.append(r"\checkmark" if checks[prof, suite, ds] else "")
                rows.append(mpt.ds_label(ds) + " & " + " & ".join(out) + r" \\")
        alld = [d for _, ds in by_source for d in ds]  # mean over datasets of the per-dataset mean train_s
        rows += [r"\midrule", mean_row(mean_name, cols, alld, scale, nchk),
                 "Mean time (s) & " + " & ".join(sec(s.loc[alld, "time"].mean()) for s, _ in cols) + " &" * nchk + r" \\"]
    tail = [r"\bottomrule", r"\end{tabular}}"]
    allds = [d for b in blocks for _, ds in b[2] for d in ds]
    if len(set(allds)) != len(allds):
        sys.exit("ERROR: a dataset sits in two blocks")
    if joint:
        cat = lambda fs: None if any(f is None for f in fs) else pd.concat(fs)  # noqa: E731
        jcols = [(cat([b[0][i][0] for b in blocks]), cat([b[0][i][1] for b in blocks])) for i in range(ncol)]
        tail = [r"\midrule", mean_row(joint, jcols, allds, pad=nchk)] + tail
    return kdd28.add_setup(GEN + hdr + "\n".join(head + rows + tail) + "\n", setup)


def suite_arg(s):
    try:
        evalsuite.load_suite(s)
    except KeyError as e:
        raise argparse.ArgumentTypeError(e.args[0])
    return s


def set_shapes(shapes_csv, cats_csv, only=None):
    """mpt.SHAPES / mpt.CATS from dataset,rows,features and dataset,categorical,features CSVs (repo-relative)."""
    for d, r in pd.read_csv(ROOT / shapes_csv).drop_duplicates("dataset").set_index("dataset").iterrows():
        if only is None or d in only:
            mpt.SHAPES[d] = (int(r.rows), int(r.features))
    for d, r in pd.read_csv(ROOT / cats_csv).drop_duplicates("dataset").set_index("dataset").iterrows():
        if only is None or d in only:
            mpt.CATS[d] = (int(r.categorical), int(r.features))


