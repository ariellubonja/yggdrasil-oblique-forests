def hdr(wide_ydf_seeds):
    rel = lambda d: " + ".join(str(v[1].relative_to(ROOT / "benchmarks")) for v in d.values())
    return ("% auto-generated by benchmarks/src/distributed_spo_gbt/paper/tables/make_hao_vs_ydf_compare_tables.py -- regenerate, do not hand-edit\n"
            "% source: IN-PROCESS reruns, YDF = kdd28_ydf mean over seeds 1-5, Hao = kdd28_hao mean over seeds 1-5, SPAA paper eval, "
            + rel(INPUTS) + "\n"
            f"% source (wide block): YDF = kdd28_ydf mean over {seeds_text(wide_ydf_seeds)}, Hao = kdd28_hao mean over "
            "seeds 1-5, wide dataset eval, " + rel(WIDE_INPUTS) + "\n")


def seeds_text(s):
    return f"seed {s[0]}" if len(s) == 1 else "seeds " + (f"{s[0]}-{s[-1]}" if s == list(range(s[0], s[-1] + 1)) else ",".join(map(str, s)))


def load(inputs, key):
    """rc==0 rows, stamp-checked against the profile and the declared eval suite (exit 2 on drift or gaps)."""
    prof, path, arms = inputs[key]
    x = pd.read_csv(path)
    x = x[x.rc == 0]
    kdd28.check_frame(x, prof, arms, path.name)
    return x


def per_fold(x, seeds):
    """(dataset, fold, arm) -> metric mean over exactly `seeds` (exit 2 otherwise)."""
    got = x.groupby(["dataset", "fold", "arm"]).seed.agg(lambda v: sorted(int(t) for t in v))
    bad = got[got.map(lambda v: v != seeds)]
    if len(bad):
        sys.exit(f"ERROR: {len(bad)} cells lack seeds {seeds} or repeat one, e.g. {bad.index[0]}: {bad.iloc[0]}")
    return x.groupby(["dataset", "fold", "arm"], as_index=False)[["test_auc", "train_s"]].mean()


def stats(f, arm):
    """dataset -> mean/std/count of test AUC over folds of one arm, and time = mean train_s over folds."""
    g = f[f.arm == arm].groupby("dataset")
    return g.test_auc.agg(["mean", "std", "count"]).assign(time=g.train_s.mean())


def cell(r, bold, pre=""):
    mu = f"{r['mean']:.4f}"[1:]
    sd = r"$_{\pm" + f"{r['std']:.4f}"[1:] + "}$" if r["count"] > 1 else r"\phantom{$_{\pm.0000}$}"
    c = (r"{\boldmath\textbf{" + mu + sd + "}}" if r["count"] > 1 else r"\textbf{" + mu + "}" + sd) if bold else mu + sd
    return pre + c


def mean_row(name, cols, sub):
    """Mean over `sub` datasets per column, -- where a column lacks one of them, colored against its YDF column."""
    avg = [round(s.loc[sub, "mean"].mean(), 4) if s is not None and set(sub) <= set(s.index) else None for s, _ in cols]
    refm = [round(r.loc[sub, "mean"].mean(), 4) if r is not None and set(sub) <= set(r.index) else None for _, r in cols]
    top_v = max(v for v in avg if v is not None)
    return name + " & " + " & ".join(
        "--" if v is None else (mpt._delta_color((v - rv) * 1e3) if rv is not None else "")
        + (r"\textbf{%s}" if v == top_v else "%s") % f"{v:.4f}"[1:] for v, rv in zip(avg, refm)) + r" \\"


def body(groups, blocks, joint, setup, wide_ydf_seeds, stretch=1.0):
    """groups: [(top label, [sub labels])]. blocks: [(cols, folds, by_source, mean label)], cols = [(stats or None,
    YDF stats to color against or None)] in header order, by_source = [(italic heading, datasets)]. Each block ends
    with its mean and mean-time rows. joint: label of a mean over every block's datasets."""
    ncol = sum(len(cs) for _, cs in groups)
    head = [r"\renewcommand{\arraystretch}{%g}%%" % stretch] if stretch != 1 else []  # local to the float's minipage
    head += [r"\resizebox{\linewidth}{!}{%", r"\begin{tabular}{l" + "".join("|" + "r" * len(cs) for _, cs in groups) + "}",
            r"\toprule"]
    top, rules, j = [], [], 2
    for lab, cs in groups:
        top.append(r"\multicolumn{%d}{c}{%s}" % (len(cs), lab)); rules.append(r"\cmidrule(lr){%d-%d}" % (j, j + len(cs) - 1))
        j += len(cs)
    head += [" & " + " & ".join(top) + r" \\", "".join(rules),
             "Dataset & " + " & ".join(r"\multicolumn{1}{c}{" + s + "}" for _, cs in groups for s in cs) + r" \\",
             r"\midrule"]
    rows = []
    sec = lambda x: f"{x:,.0f}".replace(",", "{,}") if x >= 10 else f"{x:.1f}"
    for bi, (cols, folds, by_source, mean_name) in enumerate(blocks):
        assert len(cols) == ncol
        if bi:
            rows.append(r"\midrule")
        for src, datasets in by_source:
            rows.append(mpt.source_row(src, ncol + 1))
            for ds in datasets:
                have = [s.loc[ds, "mean"] for s, _ in cols if s is not None and ds in s.index]
                best, out = max(have), []
                for s, ref in cols:
                    if s is None or ds not in s.index:
                        out.append("--"); continue
                    r = s.loc[ds]
                    if r["count"] != folds[ds]:
                        sys.exit(f"ERROR: {ds}: {int(r['count'])} folds, suite has {folds[ds]}")
                    pre = mpt._delta_color((r["mean"] - ref.loc[ds, "mean"]) * 1e3) if ref is not None and ds in ref.index else ""
                    out.append(cell(r, r["mean"] == best, pre))
                rows.append(mpt.ds_label(ds) + " & " + " & ".join(out) + r" \\")
        alld = [d for _, ds in by_source for d in ds]  # mean over datasets of the per-dataset mean train_s
        rows += [r"\midrule", mean_row(mean_name, cols, alld),
                 "Mean time (s) & " + " & ".join(sec(s.loc[alld, "time"].mean()) for s, _ in cols) + r" \\"]
    cat = lambda fs: None if any(f is None for f in fs) else pd.concat(fs)
    jcols = [(cat([b[0][i][0] for b in blocks]), cat([b[0][i][1] for b in blocks])) for i in range(ncol)]
    allds = [d for b in blocks for _, ds in b[2] for d in ds]
    if len(set(allds)) != len(allds):
        sys.exit("ERROR: a dataset sits in two blocks")
    tail = [r"\midrule", mean_row(joint, jcols, allds), r"\bottomrule", r"\end{tabular}}"]
    return kdd28.add_setup(hdr(wide_ydf_seeds) + "\n".join(head + rows + tail) + "\n", setup)


def suite_arg(s):
    try:
        evalsuite.load_suite(s)
    except KeyError as e:
        raise argparse.ArgumentTypeError(e.args[0])
    return s


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--eval_suite", default="kdd28_tabarena33", type=lambda s: kdd28._declare_eval(s, __file__))
    ap.add_argument("--wide_eval_suite", default="kdd28_wide_datasets", type=suite_arg,
                    help="suite of the second block, declared (strict checks) while its inputs load")
    ap.add_argument("--wide_ydf_seeds", default="1", help="comma list: kdd28_ydf seeds every wide cell must have")
    ap.add_argument("--dataset_shapes", default=mpt.SHAPES_CSV)
    ap.add_argument("--wide_dataset_shapes", default=WIDE_SHAPES, help="dataset,rows,features of the wide block")
    ap.add_argument("--dataset_categoricals", default=mpt.CATS_CSV)
    ap.add_argument("--single_arraystretch", type=float, default=1.0, help="row height factor, single-machine body")
    ap.add_argument("--dist_arraystretch", type=float, default=1.0, help="row height factor, distributed body")
    a = ap.parse_args()
    spec, wspec = evalsuite.load_suite(a.eval_suite), evalsuite.load_suite(a.wide_eval_suite)
    if set(spec["datasets"]) & set(wspec["datasets"]):
        sys.exit(f"ERROR: --eval_suite and --wide_eval_suite share datasets {sorted(set(spec['datasets']) & set(wspec['datasets']))}")
    sh = pd.read_csv(ROOT / a.dataset_shapes).drop_duplicates("dataset").set_index("dataset")
    mpt.SHAPES = {d: (int(r.rows), int(r.features)) for d, r in sh.iterrows()}
    for d, r in pd.read_csv(ROOT / a.wide_dataset_shapes).set_index("dataset").iterrows():
        if d in wspec["datasets"]:
            mpt.SHAPES[d] = (int(r.rows), int(r.features))
    ca = pd.read_csv(ROOT / a.dataset_categoricals).set_index("dataset")
    mpt.CATS = {d: (int(r.categorical), int(r.features)) for d, r in ca.iterrows()}
    folds = {d: len(f) for d, f in spec["datasets"].items()}
    wfolds = {d: len(f) for d, f in wspec["datasets"].items()}
    ydf_seeds = sorted(int(s) for s in kdd28.load_profile(YDF + ".distacc_single_spo")["seeds"])  # 1-5 since 2026-11-20
    hao_seeds = sorted(int(s) for s in kdd28.load_profile(HAO)["seeds"])
    wide_ydf_seeds = sorted(int(s) for s in a.wide_ydf_seeds.split(","))
    if not set(wide_ydf_seeds) <= set(ydf_seeds):
        sys.exit(f"ERROR: --wide_ydf_seeds {wide_ydf_seeds} not in the {YDF} seeds {ydf_seeds}")
    arms = ["distacc_single_spo", "distacc_single_aa", "distacc_single_aa_spo", "distacc_spo", "distacc_aa"]
    setup = kdd28.setup_line(YDF, arms) + "\n" + kdd28.setup_line(HAO, arms)
    y = per_fold(pd.concat([load(INPUTS, k) for k in INPUTS if k.startswith("ydf")]), ydf_seeds)
    h = per_fold(pd.concat([load(INPUTS, "hao"), load(INPUTS, "hao_aaspo")]), hao_seeds)
    kdd28._declare_eval(a.wide_eval_suite, __file__)  # wide inputs are checked against their own suite
    wy = per_fold(pd.concat([load(WIDE_INPUTS, k) for k in WIDE_INPUTS if k.startswith("ydf")]), wide_ydf_seeds)
    wh = per_fold(pd.concat([load(WIDE_INPUTS, "hao"), load(WIDE_INPUTS, "hao_aaspo")]), hao_seeds)
    setup += (f"\n% wide block: eval suite {a.wide_eval_suite}, profile {YDF} {seeds_text(wide_ydf_seeds)}, "
              f"profile {HAO} {seeds_text(hao_seeds)}")
    ds, wds = sorted(spec["datasets"]), sorted(wspec["datasets"])
    by_src = mpt.sources(ds)
    mpt.sources(wds)  # exits if a wide dataset is in none or several benchmark manifests
    wlab = r"OpenML ${\ge}100$ column datasets"  # user's wording (2026-11-20)
    if wide_ydf_seeds != ydf_seeds:
        k = len(wide_ydf_seeds)
        wlab += rf", \textbf{{YDF-parameter runs have only {k} seed{'s' if k > 1 else ''}}}"
    w_src = [(wlab, wds)]
    n = lambda k: f"{k} seed" + ("s" if k > 1 else "")
    Y, H = rf"\shortstack{{YDF\\{n(len(ydf_seeds))}}}", rf"\shortstack{{Hao\\{n(len(hao_seeds))}}}"
    pair = lambda yf, hf, arm: [(stats(yf, arm), None), (stats(hf, arm), stats(yf, arm))]
    single_arms = [("SPO-GBT", "single:SPO"), ("AA+SPO-GBT", "single:AA+SPO"), ("AA-GBT", "single:AA")]
    dist_arms = [(f"SPO-GBT dist.\\ $W{{=}}{w}$", f"{w}:SPO") for w in (1, 4, 8, 16, 32)] + [(r"AA-GBT dist.\ $W{=}4$", "4:AA")]
    tables = {}
    for name, spec_arms in (("single_machine", single_arms), ("distributed", dist_arms)):
        groups = [(lab, [Y, H]) for lab, _ in spec_arms]
        cols = lambda yf, hf: [c for _, arm in spec_arms for c in pair(yf, hf, arm)]
        blocks = [(cols(y, h), folds, by_src, f"Mean ({len(ds)} SPAA datasets)"),
                  (cols(wy, wh), wfolds, w_src, f"Mean ({len(wds)} wide datasets)")]
        tables[name] = (groups, blocks, f"Mean (all {len(ds) + len(wds)})")
    out = pathlib.Path(a.out); out.mkdir(parents=True, exist_ok=True)
    (out / "table_accuracy_hao_vs_ydf_params_single_machine_body.tex").write_text(
        body(*tables["single_machine"], setup, wide_ydf_seeds, a.single_arraystretch))
    mpt.SHAPE_BELOW = True  # 12 numeric columns: shape under the name keeps the font readable
    (out / "table_accuracy_hao_vs_ydf_params_distributed_body.tex").write_text(
        body(*tables["distributed"], setup, wide_ydf_seeds, a.dist_arraystretch))
    print(f"wrote 2 bodies under {out} ({len(ds)} + {len(wds)} datasets)")


if __name__ == "__main__":
    main()
