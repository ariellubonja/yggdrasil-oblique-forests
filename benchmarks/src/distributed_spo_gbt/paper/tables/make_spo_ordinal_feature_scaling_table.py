#!/usr/bin/env python3
"""tab:spo-ordinal-feature-scaling body: SPO-GBT test AUC with features divided by their train-fold std vs. unscaled.
Inputs: the three results.csv in benchmarks/results/kdd28/floats/appendix/tab-spo-ordinal-feature-scaling/inputs.txt.
Run from the repo root."""
import pathlib
import sys

import pandas as pd
from scipy.stats import wilcoxon

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import make_paper_tables as mpt  # noqa: E402  (sources: TabArena / TabReD membership)

ROOT = pathlib.Path(__file__).resolve().parents[5]
RUN = ROOT / "benchmarks/results/kdd28/runs/2026-11-21_spo_gbt_feature_scaling_none_vs_trainstd_cc18_tabarena_tabred"
CC18, MIXED, HEAVY = (RUN / d / "results.csv" for d in
                      ("cc18_10fold", "tabarena_tabred_mixed_categorical_numeric", "tabarena_categorical_heavy"))
OUT = ROOT / "paper/distributed_spo_gbt_kdd28/tables/table_spo_ordinal_feature_scaling_body.tex"
FOLDS = {"CC18": 10, "TabArena": 5, "TabReD": 1}


def deltas(path, bench):
    """Per-dataset fold mean of B_trainstd - A_none test AUC (SPO-GBT, run 1), plus (cols, n_ordinal_cols)."""
    r = pd.read_csv(path)
    r = r[(r.learner == "SPO-GBT") & (r.run == 1)]
    bins = r.commit.str.extract(r"bin (\S+?),?\s")[0]
    assert bins.notna().all() and bins.nunique() == 1, f"{path}: binary commits {set(bins)}"
    assert (r.seed == 1).all() and (r.threads == 4).all() and (r.metric_name == "test_auc").all(), path
    assert set(r.arm) == {"A_none", "B_trainstd"}, f"{path}: arms {set(r.arm)}"
    assert not r.duplicated(["dataset", "fold", "arm"]).any(), f"{path}: duplicate cells"
    p = r.pivot(index=["dataset", "fold"], columns="arm", values="metric_value")
    assert p.notna().all().all(), f"{path}: missing arm in {list(p[p.isna().any(axis=1)].index)}"
    src = {d: "CC18" for d in p.index.levels[0]} if bench == "CC18" else \
        {d: s for s, ds in mpt.sources(list(p.index.levels[0])) for d in ds}
    assert set(src.values()) <= set(FOLDS), f"{path}: sources {set(src.values())}"
    for ds, g in p.groupby(level="dataset"):
        assert sorted(g.index.get_level_values("fold")) == list(range(FOLDS[src[ds]])), f"{path}: {ds} folds"
    shp = r.groupby("dataset")[["cols", "n_ordinal_cols"]].nunique()
    assert (shp == 1).all().all(), f"{path}: inconsistent cols / n_ordinal_cols"
    shp = r.groupby("dataset")[["cols", "n_ordinal_cols"]].first()
    return (p.B_trainstd - p.A_none).groupby(level="dataset").mean(), shp, bins.iloc[0]


def mixed(d, shp):
    return d[(shp.n_ordinal_cols > 0) & (shp.n_ordinal_cols < shp.cols)]


cc, cc_shp, b1 = deltas(CC18, "CC18")
mx, mx_shp, b2 = deltas(MIXED, "TabArena")
hv, hv_shp, b3 = deltas(HEAVY, "TabArena")
assert not set(mx.index) & set(hv.index), "a dataset is in both TabArena dirs"
ta, ta_shp = pd.concat([mx, hv]), pd.concat([mx_shp, hv_shp])
rows = [("CC18", cc), ("CC18, mixed types", mixed(cc, cc_shp)), ("TabArena + TabReD, mixed types", mixed(ta, ta_shp))]

f4s = lambda v: ("+" if v >= 0 else "$-$") + f"{abs(v):.4f}".lstrip("0")  # noqa: E731
f2 = lambda v: f"{v:.2f}".lstrip("0")  # noqa: E731
lines = [r"% auto-generated by benchmarks/src/distributed_spo_gbt/paper/tables/make_spo_ordinal_feature_scaling_table.py -- regenerate, do not hand-edit",
         f"% source: {RUN.relative_to(ROOT)}/{{cc18_10fold,tabarena_tabred_mixed_categorical_numeric,tabarena_categorical_heavy}}/results.csv",
         f"% binaries: {', '.join(sorted({b1, b2, b3}))}", r"\begin{tabular}{lrrrr}", r"\toprule",
         r"Datasets & \# & Mean $\Delta$AUC & Better / worse & $p$ \\", r"\midrule"]
for name, d in rows:
    nz = d[d != 0]
    lines.append(f"{name} & {len(d)} & {f4s(d.mean())} & {(d > 0).sum()}/{(d < 0).sum()} & {f2(wilcoxon(nz).pvalue)} \\\\")
lines += [r"\bottomrule", r"\end{tabular}"]
OUT.write_text("\n".join(lines) + "\n")
print("\n".join(lines[3:]))
print(OUT)
