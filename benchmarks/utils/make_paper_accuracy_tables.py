#!/usr/bin/env python3
"""Emit conference-paper-ready LaTeX tables from the hist-vs-exact accuracy study.

Inputs (produced by accuracy_stats.py):
  <stats_dir>/report.md                        -- aggregate stats (parsed)
  <stats_dir>/per_dataset_SPO-{RF,GBT}_accuracy.csv

Outputs (written to <stats_dir>/paper/):
  table_main_summary.tex        -- compact aggregate table (main text)
  table_per_dataset_accuracy.tex-- 36-dataset x 2-learner x 3-arm table (appendix)
  preview.md                    -- markdown rendering of both

Usage: make_paper_accuracy_tables.py [stats_dir]
       (default stats_dir: benchmarks/results/accuracy/hist_vs_exact_accuracy)
"""

import os
import re
import sys

import pandas as pd

DEFAULT_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "results", "accuracy", "hist_vs_exact_accuracy")

ARM_ORDER = [
    ("Dynamic_Random_Histogram_thresh250", "Dynamic (64 bins, $\\tau{=}250$)"),
    ("Random", "Random, 64 bins"),
    ("Random_bins16", "Random, 16 bins"),
    ("Random_bins32", "Random, 32 bins"),
    ("Random_bins128", "Random, 128 bins"),
    ("Random_bins256", "Random, 256 bins"),
]
MAIN_ARMS = ARM_ORDER[:2]  # per-dataset table: shipped config + worst case only
# Summary table: bin counts other than 64/256 are grayed out (context only).
FOCUS_ARMS = {"Dynamic_Random_Histogram_thresh250", "Random", "Random_bins256"}

LEARNERS = ["SPO-RF", "SPO-GBT"]


# ---------------------------------------------------------------- report.md --
def parse_report(path):
    """-> {(learner, arm): dict of aggregate stats} for the accuracy metric."""
    text = open(path).read()
    out = {}
    for learner in LEARNERS:
        m = re.search(rf"## {learner} -- accuracy\n(.*?)(?=\n## )", text, re.S)
        section = m.group(1)
        for arm_m in re.finditer(
                r"### (\S+) vs Exact.*?(?=\n### |\n- Friedman|\Z)", section, re.S):
            arm, body = arm_m.group(1), arm_m.group(0)
            g = lambda pat: re.search(pat, body)
            stats = {}
            stats["n"] = int(g(r"Datasets: (\d+)").group(1))
            mm = g(r"Mean per-dataset delta: ([+-][\d.]+) \(median ([+-][\d.]+)")
            stats["mean"], stats["median"] = float(mm.group(1)), float(mm.group(2))
            ci = g(r"95% CI \(t\): \[([+-][\d.]+), ([+-][\d.]+)\]")
            stats["lo"], stats["hi"] = float(ci.group(1)), float(ci.group(2))
            wtl = g(r"Win/tie/loss[^:]*: (\d+)/(\d+)/(\d+)")
            stats["wtl"] = f"{wtl.group(1)}/{wtl.group(2)}/{wtl.group(3)}"
            stats["noninf"] = float(
                g(r"Non-inferior \(no penalty worse than ([\d.]+)\)").group(1))
            stats["tost"] = float(
                g(r"Equivalent \(TOST\) within \+-([\d.]+)").group(1))
            sig = g(r"Per-dataset Wilcoxon \(Holm[^)]*\): (\d+) dataset")
            stats["n_sig"] = int(sig.group(1)) if sig else 0
            loo = g(r"Leave-one-out \(drop (\S+)\): mean ([+-][\d.]+), "
                    r"95% CI \[([+-][\d.]+), ([+-][\d.]+)\]")
            stats["loo_drop"] = re.sub(r"^task_\d+_", "", loo.group(1))
            stats["loo_mean"] = float(loo.group(2))
            stats["loo_lo"], stats["loo_hi"] = float(loo.group(3)), float(loo.group(4))
            out[(learner, arm)] = stats
    return out


# ------------------------------------------------------------- main summary --
def fmt3(x):  # delta in units of 10^-3, one decimal
    return f"{x * 1e3:+.1f}"


def make_summary(agg):
    lines = [
        "% Auto-generated by make_paper_accuracy_tables.py -- do not edit.",
        "% Deltas are (arm - Exact) held-out test accuracy in units of 10^-3;",
        "% positive = histogram arm better. Aggregates over per-dataset means of",
        "% paired per-(seed,fold) deltas; margins = smallest margin passing at alpha=0.05.",
        "\\begin{table*}",
        "\\centering",
        "\\caption{Held-out test accuracy of random-histogram split finding vs.\\ "
        "exact splits, aggregated over 36 datasets (34 OpenML CC18 binary tasks, "
        "10-fold CV $\\times$ 3 seeds; HIGGS and SUSY held-out, single run). "
        "$\\Delta$ = arm $-$ Exact in units of $10^{-3}$ accuracy; CIs are "
        "per-dataset paired $t$ intervals. W/T/L counts datasets "
        "($|\\Delta| \\le 10^{-3}$ is a tie). LOO $\\Delta$ = leave-one-out, "
        "dropping the most influential dataset (cylinder-bands in every arm; "
        "Exact degenerates on its missing values). Margin = smallest one-sided "
        "non-inferiority margin passing at $\\alpha{=}0.05$; Sig.\\ = datasets "
        "with a Holm-corrected per-dataset Wilcoxon difference. Bin-count "
        "ablations: seed 1, CC18 only ($n{=}34$).}",
        "\\label{tab:hist-vs-exact-summary}",
        "\\begin{tabular}{llrccccc}",
        "\\toprule",
        "Learner & Split finder & $n$ & $\\Delta$ [95\\% CI] ($\\times 10^{-3}$)"
        " & LOO $\\Delta$ Acc. [95\\% CI] & W/T/L & Margin ($\\times 10^{-3}$)"
        " & Sig. \\\\",
    ]
    for learner in LEARNERS:
        lines.append("\\midrule")
        for arm, label in ARM_ORDER:
            s = agg[(learner, arm)]
            cells = [learner if (arm, label) == ARM_ORDER[0] else "", label,
                     f"{s['n']}",
                     f"{fmt3(s['mean'])} [{fmt3(s['lo'])}, {fmt3(s['hi'])}]",
                     f"{fmt3(s['loo_mean'])} [{fmt3(s['loo_lo'])}, "
                     f"{fmt3(s['loo_hi'])}]",
                     s["wtl"], f"{s['noninf'] * 1e3:g}", f"{s['n_sig']}"]
            if arm not in FOCUS_ARMS:
                cells = [f"\\textcolor{{gray}}{{{c}}}" if c else c for c in cells]
            lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


# --------------------------------------------------------------- per-dataset --
def display_name(ds):
    if ds.startswith("HIGGS"):
        return "HIGGS (10.5M)"
    if ds.startswith("SUSY"):
        return "SUSY (4.5M)"
    name = re.sub(r"^task_\d+_", "", ds)
    return name.replace("_", "\\_")


def cell(mean, std, delta, p_holm):
    if pd.isna(mean):
        return "--"
    mark = ""
    if not pd.isna(p_holm) and p_holm < 0.05:
        mark = "$^{\\ast}$" if delta > 0 else "$^{\\dagger}$"
    if pd.isna(std):  # physics: single run
        return f"{mean:.4f}{mark}"
    return f"{mean:.4f} $\\pm$ {std:.4f}{mark}"


def make_per_dataset(frames):
    lines = [
        "% Auto-generated by make_paper_accuracy_tables.py -- do not edit.",
        "\\begin{table*}",
        "\\centering",
        "\\caption{Per-dataset held-out test accuracy (mean $\\pm$ std over "
        "3 seeds $\\times$ 10 CV folds; HIGGS/SUSY: one run on a held-out "
        "500k-row test split). Dyn.\\ = Dynamic Random Histogram (64 bins, "
        "threshold 250), Rand.\\ = Random Histogram at every node (64 bins). "
        "$^{\\ast}$/$^{\\dagger}$: significantly better/worse than Exact "
        "(per-dataset Wilcoxon over paired folds, Holm-corrected, "
        "$\\alpha{=}0.05$).}",
        "\\label{tab:hist-vs-exact-per-dataset}",
        "\\small",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{l cc cc cc}",
        "\\toprule",
        " & \\multicolumn{3}{c}{SPO-RF} & \\multicolumn{3}{c}{SPO-GBT} \\\\",
        "\\cmidrule(lr){2-4} \\cmidrule(lr){5-7}",
        "Dataset & Exact & Dyn. & Rand. & Exact & Dyn. & Rand. \\\\",
        "\\midrule",
    ]
    rf, gbt = frames["SPO-RF"], frames["SPO-GBT"]
    order = [d for d in rf["dataset"] if not d.startswith(("HIGGS", "SUSY"))]
    order += [d for d in rf["dataset"] if d.startswith(("HIGGS", "SUSY"))]
    physics_started = False
    for ds in order:
        if ds.startswith(("HIGGS", "SUSY")) and not physics_started:
            lines.append("\\midrule")
            physics_started = True
        row = [display_name(ds)]
        for df in (rf, gbt):
            r = df[df["dataset"] == ds].iloc[0]
            row.append(cell(r["Exact_mean"], r["Exact_std"], 0.0, float("nan")))
            for arm, _ in MAIN_ARMS:
                row.append(cell(r[f"{arm}_mean"], r[f"{arm}_std"],
                                r[f"{arm}_delta"], r[f"{arm}_p_holm"]))
        lines.append(" & ".join(row) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


# ------------------------------------------------------------------ preview --
def md_preview(agg, frames):
    out = ["# Paper tables preview (markdown rendering)", "",
           "## Table 1 -- summary (main text)", "",
           "| Learner | Split finder | n | Δ [95% CI] (×10⁻³) | "
           "LOO Δ [95% CI] | W/T/L | Non-inf. margin (×10⁻³) | Sig. datasets |",
           "|---|---|---|---|---|---|---|---|"]
    for learner in LEARNERS:
        for arm, label in ARM_ORDER:
            s = agg[(learner, arm)]
            label_md = label.replace("$\\tau{=}250$", "τ=250").replace("\\", "")
            out.append(
                f"| {learner} | {label_md} | {s['n']} | {fmt3(s['mean'])} "
                f"[{fmt3(s['lo'])}, {fmt3(s['hi'])}] | {fmt3(s['loo_mean'])} "
                f"[{fmt3(s['loo_lo'])}, {fmt3(s['loo_hi'])}] | {s['wtl']} | "
                f"{s['noninf'] * 1e3:g} | {s['n_sig']} |")
    out += ["", "## Table 2 -- per-dataset accuracy (appendix)", "",
            "| Dataset | RF Exact | RF Dyn. | RF Rand. | GBT Exact | GBT Dyn. "
            "| GBT Rand. |", "|---|---|---|---|---|---|---|"]
    rf, gbt = frames["SPO-RF"], frames["SPO-GBT"]
    order = [d for d in rf["dataset"] if not d.startswith(("HIGGS", "SUSY"))]
    order += [d for d in rf["dataset"] if d.startswith(("HIGGS", "SUSY"))]
    for ds in order:
        row = [display_name(ds).replace("\\_", "_")]
        for df in (rf, gbt):
            r = df[df["dataset"] == ds].iloc[0]
            row.append(cell(r["Exact_mean"], r["Exact_std"], 0.0, float("nan")))
            for arm, _ in MAIN_ARMS:
                row.append(cell(r[f"{arm}_mean"], r[f"{arm}_std"],
                                r[f"{arm}_delta"], r[f"{arm}_p_holm"]))
        row = [c.replace(" $\\pm$ ", " ± ").replace("$^{\\ast}$", " \\*")
                .replace("$^{\\dagger}$", " †") for c in row]
        out.append("| " + " | ".join(row) + " |")
    out.append("")
    return "\n".join(out)


def main():
    stats_dir = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DIR
    agg = parse_report(os.path.join(stats_dir, "report.md"))
    frames = {L: pd.read_csv(os.path.join(stats_dir,
                                          f"per_dataset_{L}_accuracy.csv"))
              for L in LEARNERS}
    out_dir = os.path.join(stats_dir, "paper")
    os.makedirs(out_dir, exist_ok=True)
    for name, content in [
            ("table_main_summary.tex", make_summary(agg)),
            ("table_per_dataset_accuracy.tex", make_per_dataset(frames)),
            ("preview.md", md_preview(agg, frames))]:
        with open(os.path.join(out_dir, name), "w") as f:
            f.write(content)
        print("wrote", os.path.join(out_dir, name))


if __name__ == "__main__":
    main()
